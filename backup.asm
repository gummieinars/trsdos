;
; STORE A NUMBER OF 'ALL BITS SET' BYTES IN TRACK BUFFER
; ENTRY:  B       - BYTE COUNTER
;         HL      - BUFFER POINTER
; EXIT:   B       - ZERO
;         C       - 11111111B
;         HL      - INCREMENTED BY B BYTES
;57AA (440F)
STOBAS:	LD	C,11111111B	;LOAD ALL BITS SET
;
;
; STORE A NUMBER OF BYTES IN TRACK BUFFER
; ENTRY:  B       - BYTE COUNTER
;         C       - BYTE TO STORE
;         HL      - BUFFER POINTER
; EXIT:   B       - ZERO
;         HL      - INCREMENTED BY B BYTES
;57AC (4411)
STOBNB:	CALL	STOBTB-O	;STORE THE BYTE IN BUFFER
	DJNZ	STOBNB		;LOOP UNTIL ALL BYTES STORED
	RET
;
;
; STORE A BYTE IN TRACK BUFFER
; ENTRY:  C       - BYTE TO STORE
;         HL      - BUFFER POINTER
; EXIT:   HL      - INCREMENTED
;57B2 (4417)
STOBTB:	LD	(HL),C		;STORE BYTE IN BUFFER
	INC	HL		;BUMP BUFFER POINTER
	RET
