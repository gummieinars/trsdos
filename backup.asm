BACKUP:	DI			;DISABLE INTERRUPTS
	LD	SP,STACKT	;LOAD TOP OF STACK
	PUSH	HL		;SAVE COMMAND LINE POINTER
	LD	A,(ERRENT)	;BYTE FROM ERROR HANDLER START
	CP	0C7H		;TEST IF 'RST 00H' - BOOT
	JR	Z,BACKCO	;THEN CONTINUE IF IT IS
	LD	A,(SYSCON)	;GET SYSTEM CONDITION FLAGS
	BIT	5,A		;TEST PROGRAM CHAINING ACTIVE
	JR	Z,BACKCO	;CONTINUE IF INACTIVE
	LD	HL,INVDCM	;POINT AT INVALID MESSAGE
	CALL	DOPMSG		;DISPLAY THE MESSAGE STRING
	JP	ERRENT		;THEN ABORT TO DOS ERROR
BACKCO:	LD	HL,SIGNOM	;POINT AT SIGN-ON STRING
	CALL	DOPMSG		;DISPLAY THE MESSAGE
	POP	HL		;RECOVER COMMAND LINE POINTER
	LD	A,(ERRENT)	;BYTE FROM ERROR HANDLER START
	CP	0C7H		;TEST IF 'RST 00H' - BOOT
	JR	Z,PMTSRC	;THEN WE PROMPT FOR DRIVE
	LD	A,(HL)		;GET COMMAND LINE CHARACTER
	CP	':'		;TEST IF DRIVE DELIMITER
	JR	NZ,PMTSRC	;SKIP IF NOT THE DELIMITER
	INC	HL		;ELSE BUMP COMMAND POINTER
	JR	GETSRC		;THEN SKIP DRIVE PROMPT
PMTSRC:	LD	HL,WHICSM	;POINT AT SOURCE DRIVE PROMPT
	CALL	DOPMSG		;DISPLAY PROMPT STRING
	LD	HL,HITBUF-O	;POINT AT INPUT BUFFER
	LD	B,1		;LOAD INPUT LINE LENGTH
	CALL	KBLINE		;READ KEYBOARD LINE
GETSRC:	LD	A,(HL)		;GET DRIVE CODE TO A
	SUB	'0'		;REMOVE ASCII BIAS
	JP	C,PMTSRC	;PROMPT AGAIN IF INVALID
	CP	NUMDRV		;TEST IF DRIVE IN RANGE
	JP	NC,PMTSRC	;PROMPT AGAIN IF INVALID
	INC	HL		;BUMP BUFFER POINTER
	RLCA			;ROTATE THREE
	RLCA			; BITS TO
	RLCA			;  THE LEFT
	OR	11000111B	;MAKE INTO A 'SET' OP-CODE
	LD	(SRCDRB),A	;STORE THE BIT SET VALUE
	XOR	A		;ZERO ACCUMULATOR
	SET	0,A		;SET DRIVE SELECT BIT
;
;
; SOURCE DRIVE SELECT BIT MASK STORAGE
;5256
SRCDRB	Equ	$-1		;DRIVE SELECT CODE
;
;
; STORE SOURCE DRIVE BIT SELECT MASK AND CONTINUE
;
	LD	(SRCCOD),A	;SAVE SOURCE DRIVE CODE
	LD	A,(ERRENT)	;BYTE FROM ERROR HANDLER START
	CP	0C7H		;TEST IF 'RST 00H' - BOOT
	JR	Z,PMTDST	;THEN WE PROMPT FOR DRIVE
GETDSL:	LD	A,(HL)		;GET COMMAND LINE CHARACTER
	INC	HL		;BUMP COMMAND POINTER
	CP	CR		;TEST IF END OF LINE
	JR	Z,PMTDST	;THEN PROMPT FOR DRIVE
	CP	':'		;TEST IF DRIVE DELIMITER
	JR	NZ,GETDSL	;SKIP IF NOT THE DELIMITER
	JR	GETDST		;ELSE SKIP DRIVE PROMPT
PMTDST:	LD	HL,WHICDM	;POINT AT DESTINATION PROMPT
	CALL	DOPMSG		;DISPLAY PROMPT STRING
	LD	HL,HITBUF-O	;POINT AT INPUT BUFFER
	LD	B,1		;LOAD INPUT LINE LENGTH
	CALL	KBLINE		;READ KEYBOARD LINE
GETDST:	LD	A,(HL)		;GET DRIVE CODE TO A
	SUB	'0'		;REMOVE ASCII BIAS
	JP	C,PMTDST	;PROMPT AGAIN IF INVALID
	CP	4		;TEST IF DRIVE IN RANGE
	JP	NC,PMTDST	;PROMPT AGAIN IF INVALID
	RLCA			;ROTATE THREE
	RLCA			; BITS TO
	RLCA			;  THE LEFT
	OR	11000111B	;MAKE INTO A 'SET' OPCODE
	LD	(DSTDRB),A	;STORE THE BIT SET VALUE
	XOR	A		;ZERO ACCUMULATOR
	SET	0,A		;SET DRIVE SELECT BIT
;
;
; DESTINATION DRIVE BIT SELECT MASK STORAGE
;5290
DSTDRB	Equ	$-1		;DRIVE SELECT CODE
;
;
; STORE DESTINATION DRIVE BIT SELECT MASK AND CONTINUE
;
	LD	(DSTCOD),A	;SAVE DESTINATION DRIVE CODE
	LD	A,(ERRENT)	;BYTE FROM ERROR HANDLER START
	CP	0C7H		;TEST IF 'RST 00H' - BOOT
	JR	Z,PMTDTE	;THEN WE PROMPT FOR DATE
	LD	A,(CLKMON)	;GET MONTH NUMBER FROM DOS
	OR	A		;TEST IF NON-ZERO
	JR	Z,PMTDTE	;PROMPT IF MONTH NOT SET
	LD	HL,DTEBUF	;POINT AT DATE STRING BUFFER
	CALL	GETDTE		;GET DATE STRING FROM DOS
	JR	SKIPDA		;THEN SKIP DATE PROMPT
PMTDTE:	LD	HL,BACKDM	;POINT AT BACKUP DATE PROMPT
	CALL	DOPMSG		;DISPLAY PROMPT STRING
	LD	HL,DTEBUF	;POINT AT DATE STRING BUFFER
	LD	B,8		;LOAD MAXIMUM LINE LENGTH
	CALL	KBLINE		;READ A LINE OF INPUT
	LD	A,B		;GET INPUT LINE SIZE
	CP	8		;TEST IF CORRECT LENGTH
	JR	NZ,PMTDTE	;PROMPT AGAIN IF NOT CORRECT
	LD	A,(DTEBUF+2)	;GET DELIMITER TO A
	CP	'/'		;TEST IF CORRECT DELIMITER
	JR	NZ,PMTDTE	;PROMPT AGAIN IF INCORRECT
	LD	A,(DTEBUF+5)	;GET DELIMITER TO A
	CP	'/'		;TEST IF CORRECT DELIMITER
	JR	NZ,PMTDTE	;PROMPT AGAIN IF INCORRECT
SKIPDA:	LD	HL,BACKIT	;POINT AT CODE TO RELOCATE
	LD	DE,SYSBUF	;POINT AT DESTINATION ADDRESS
	LD	BC,LENREL	;LOAD LENGTH OF CODE
	LDIR			;RELOCATE THE CODE
	XOR	A		;ZERO ACCUMULATOR
	LD	(CURDRN-O),A	;ZERO CURRENT DRIVE NUMBER
	LD	A,(SRCCOD-O)	;GET SOURCE DRIVE CODE TO A
	LD	HL,DSTCOD-O	;POINT AT DESTINATION CODE
	SUB	(HL)		;TEST IF SAME DRIVE NUMBER
	LD	(SGLDRV-O),A	;SAVE ONE DRIVE BACKUP FLAG
	CALL	SELSRC-O	;SELECT SOURCE DRIVE
	CALL	HOMHED-O	;HOME DRIVE HEAD TO TRACK ZERO
	LD	A,(CSTREG)	;GET CONTROLLER STATUS TO A
	LD	HL,SDNRDM	;SOURCE NOT READY MESSAGE
	BIT	7,A		;TEST IF DRIVE NOT READY
	JP	NZ,ABORTM-O	;THEN WE ABORT THE BACKUP
	LD	HL,SDNISM	;SOURCE NOT IN SYSTEM
	BIT	2,A		;TEST IF AT TRACK ZERO
	JP	Z,ABORTM-O	;ABORT THE BACKUP IF NOT
	LD	DE,0		;LOAD TRACK AND SECTOR ZERO
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	CALL	RDSECT-O	;READ BOOT SECTOR TO BUFFER
	LD	HL,SRCRDM-O	;SOURCE DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	LD	A,(BOOTDT-O)	;DIRECTORY TRACK IN BOOT SECTOR
	LD	(DIRTRK-O),A	;SAVE DIRECTORY TRACK NUMBER
	LD	A,(DIRTRK-O)	;LOAD DIRECTORY TRACK TO A
	LD	D,A		;COPY TRACK NUMBER TO A
	LD	E,0		;ZERO SECTOR NUMBER
	LD	BC,GATSEC-O	;POINT AT GAT SECTOR BUFFER
	CALL	RDSECT-O	;READ THE GAT SECTOR
	LD	HL,SRCRDM-O	;SOURCE DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	CALL	SELDST-O	;SELECT DESTINATION DRIVE
	CALL	HOMHED-O	;HOME DRIVE HEAD TO TRACK ZERO
	LD	A,(CSTREG)	;GET CONTROLLER STATUS TO A
	LD	HL,DDNRDM	;DESTINATION NOT READY MESSAGE
	BIT	7,A		;TEST IF DRIVE NOT READY
	JP	NZ,ABORTM-O	;THEN WE ABORT THE BACKUP
	LD	HL,DDNISM	;DESTINATION NOT IN SYSTEM
	BIT	2,A		;TEST IF AT DRIVE ZERO
	JP	Z,ABORTM-O	;ABORT THE BACKUP IF NOT
	LD	HL,WRPROM-O	;DESTINATION WRITE PROTECTED
	BIT	6,A		;TEST IF WRITE PROTECTED
	JP	NZ,ABORTM-O	;ABORT BACKUP IF IT IS
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	LD	DE,LATFIS	;LAST TRACK FIRST SECTOR
	CALL	RDSECT-O	;READ SECTOR ON LAST TRACK
	JP	NZ,DSTNOF	;SKIP IF READ ERROR
	LD	A,(DIRTRK-O)	;GET DIRECTORY TRACK TO A
	LD	D,A		;COPY TRACK TO D REGISTER
	LD	E,FIRSEC	;GET STARTING SECTOR TO E
	LD	BC,GATBUF-O	;POINT AT GAT SECTOR BUFFER
	CALL	RDSECT-O	;READ GAT SECTOR TO BUFFER
	LD	HL,DSTRDM-O	;DESTINATION DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT BACKUP IF READ ERROR
	LD	HL,GASMPW-O	;POINT AT GAT MASTER PASSWORD
	LD	DE,MASTPW-O	;POINT AT DESTINATION GAT
	LD	B,10		;PASSWORD AND DISK NAME LENGTH
TESTID:	LD	A,(DE)		;GET BYTE FROM DESTINATION
	CP	(HL)		;TEST IF MATCHING SOURCE BYTE
	JR	NZ,FOREQU	;ABORT IF MISMATCH
	INC	DE		;BUMP DESTINATION OFFSET
	INC	HL		;BUMP SOURCE OFFSET
	DJNZ	TESTID		;LOOP FOR NEXT TEST BYTE
	LD	HL,LOCKTB-O	;POINT AT LOCK TABLE IN GAT
	LD	DE,GATBUF-O	;POINT AT GAT BUFFER
	LD	BC,NUMTRK	;LOAD ENTRY COUNT TO BC
	LDIR			;COPY LOCK TABLE TO GAT
	JP	NOFORM		;THEN SKIP FORMATTING CODE
;
;
; FORMAT REQUIRED, DISKETTES CONTAIN DIFFERENT PACK IDS!
;5380
FOREQU:	LD	HL,FORMRM	;FORMAT REQUIRED MESSAGE
;
;
; DESTINATION DISK NOT FORMATTED
;5383
DSTNOF:	CALL	HOMHED-O	;HOME DRIVE HEAD TO TRACK ZERO
	LD	HL,GATBUF-O	;POINT TO GAT SECTOR
	XOR	A		;ZERO TRACK COUNTER
CLRGAL:	LD	(HL),11111100B	;LOAD UNUSED ENTRY BYTE
	INC	HL		;BUMP BUFFER POINTER
	INC	A		;BUMP ENTRY COUNTER
	CP	NUMTRK		;TEST IF DONE WITH ENTRIES
	JR	NZ,CLRGAL	;LOOP UNTIL ALL DONE
CLRGAB:	CP	Low DOSVER-O	;TEST IF AT VERSION BYTE
	JR	Z,ERRTST	;THEN GO TEST FOR ERRORS
	LD	(HL),11111111B	;PAD OUT WITH ALL BITS SET
	INC	HL		;BUMP BUFFER POINTER
	INC	A		;BUMP ENTRY COUNTER
	JR	CLRGAB		;LOOP UNTIL ALL DONE
ERRTST:	LD	BC,410		;LOAD TEST LOOP COUNTER
	LD	HL,NODSKM	;NO DISK IN DRIVE MESSAGE
IDXONE:	DEC	BC		;DECREMENT LOOP COUNTER
	LD	A,B		;GET MSB TO A FOR TEST
	OR	C		;TEST IF END OF LOOP
	JP	Z,ABORTM-O	;THEN WE ABORT TEST LOOP
	LD	A,(CSTREG)	;GET FLOPPY CONTROLLER STATUS
	AND	00000010B	;TEST IF INDEX HOLE REACHED
	JR	NZ,IDXONE	;LOOP IF NOT THERE YET
	LD	BC,13114	;LOAD TEST LOOP COUNTER
	LD	HL,OPDORM	;DOOR NOT CLOSED MESSAGE
IDXTWO:	DEC	BC		;DECREMENT LOOP COUNTER
	LD	A,B		;GET MSB TO A FOR TEST
	OR	C		;TEST IF END OF LOOP
	JP	Z,ABORTM-O	;THEN WE ABORT TEST LOOP
	LD	A,(CSTREG)	;GET FLOPPY CONTROLLER STATUS
	AND	00000010B	;TEST IF PAST INDEX HOLE
	JR	Z,IDXTWO	;LOOP IF NOT THERE YET
	LD	DE,0		;ZERO DE REGISTER FOR COUNT
	LD	BC,372		;LOAD TEST LOOP COUNTER
	LD	HL,NODSKM	;NO DISK IN DRIVE MESSAGE
IDXTRI:	DEC	BC		;DECREMENT LOOP COUNTER
	LD	A,B		;GET MSB TO A FOR TEST
	OR	C		;TEST IF END OF LOOP
	JP	Z,ABORTM-O	;THEN WE ABORT TEST LOOP
	INC	DE		;BUMP COUNTER
	LD	A,(CSTREG)	;GET FLOPPY CONTROLLER STATUS
	AND	00000010B	;TEST IF INDEX HOLE REACHED
	JR	NZ,IDXTRI	;LOOP IF NOT THERE YET
	LD	BC,13120	;LOAD TEST LOOP COUNTER
	LD	HL,OPDORM	;DOOR NOT CLOSED MESSAGE
IDXFOU:	DEC	BC		;DECREMENT LOOP COUNTER
	LD	A,B		;GET MSB TO A FOR TEST
	OR	C		;TEST IF END OF LOOP
	JP	Z,ABORTM-O	;THEN WE ABORT TEST LOOP
	INC	DE		;BUMP COUNTER
	LD	A,(CSTREG)	;GET FLOPPY CONTROLLER STATUS
	AND	00000010B	;TEST IF PAST INDEX HOLE
	JR	Z,IDXFOU	;LOOP IF NOT THERE YET
	LD	HL,-5429	;GET NEGATED INDEX HOLE COUNT
	ADD	HL,DE		;TEST IF TOO MANY HOLES
	LD	HL,HASECM	;HARD SECTORED DISK MESSAGE
	JP	NC,ABORTM-O	;ABORT IF HARD SECTORED
;
;
; INITIALIZE FOR FORMATTING TRACKS
;
	XOR	A		;ZERO ACCUMULATOR
	LD	(TRKNUM),A	;SET TRACK NUMBER TO ZERO
;
;
; FORMAT DISK TRACKS LOOP
;53FB
FORMDL:	LD	A,(TRKNUM)	;GET TRACK NUMBER TO A
	CALL	BINASC-O	;CONVERT NUMBER TO ASCII
	LD	(FMTTKT),BC	;STORE ASCII NUMBER IN STRING
	LD	HL,FMTTKM	;POINT AT PROGRESS STRING
	CALL	MSGOUT-O	;DISPLAY THE STRING
	LD	A,(TRKNUM)	;LOAD TRACK NUMBER TO A
	LD	B,A		;COPY TRACK NUMBER TO B
	LD	A,(DIRTRK-O)	;GET DIRECTORY TRACK TO A
	CP	B		;TEST IF ON DIRECTORY TRACK
	LD	B,DIRMRK	;LOAD DIRECTORY ADDRESS MARK
	JR	Z,FORLOK	;SKIP IF DIRECTORY TRACK
	LD	B,DTAMRK	;LOAD DATA ADDRESS MARK
FORLOK:	LD	A,B		;GET ADDRESS MARK TO A
	LD	(THEMRK),A	;SAVE THE ADDRESS MARK
	LD	HL,TRKBUF	;POINT AT TRACK IMAGE BUFFER
	LD	DE,SKEWTB	;POINT AT SECTOR SKEW TABLE
	LD	B,14		;LOAD BYTE COUNTER TO B
	CALL	STOBAS-O	;STORE ALL BITS SET BYTE
;
;
; FORMAT DISK SECTORS LOOP
;5428
FORMDS:	LD	B,6		;LOAD BYTE COUNTER TO B
	LD	C,00000000B	;LOAD ALL BITS RESET BYTE
	CALL	STOBNB-O	;STORE THE BYTES IN BUFFER
	LD	C,IDAMRK	;LOAD IDENTITY ADDRESS MARK
	CALL	STOBTB-O	;STORE THE ADDRESS MARK
	LD	C,0		;LOAD TRACK NUMBER TO C
TRKNUM	Equ	$-1		;TRACK NUMBER STORAGE
	CALL	STOBTB-O	;STORE THE TRACK NUMBER
	LD	C,0		;LOAD HEAD NUMBER TO C
	CALL	STOBTB-O	;STORE HEAD NUMBER IN BUFFER
	LD	A,(DE)		;GET SECTOR NUMBER TO A
	LD	C,A		;COPY THE NUMBER TO C
	CALL	STOBTB-O	;STORE SECTOR NUMBER IN BUFFER
	LD	C,1		;LOAD SECTOR SIZE (256 BYTES)
	CALL	STOBTB-O	;STORE SECTOR SIZE CODE
	LD	C,CRCMRK	;LOAD CRC ADDRESS MARK
	CALL	STOBTB-O	;STORE THE ADDRESS MARK
	LD	C,11111111B	;LOAD ALL BITS SET BYTE
	CALL	STOBTB-O	;STORE THE BYTE IN BUFFER
	LD	B,11		;LOAD BYTE COUNTER TO B
	CALL	STOBAS-O	;STORE ALL BITS SET BYTES
	LD	B,6		;LOAD BYTE COUNTER TO B
	LD	C,00000000B	;LOAD ALL BITS RESET BYTE
	CALL	STOBNB-O	;STORE BYTE IN BUFFER
	LD	C,0		;GET ADDRESS MARK TO C
THEMRK	Equ	$-1		;DATA/DIRECTORY/LOCKED MARK
	CALL	STOBTB-O	;STORE ADDRESS MARK IN BUFFER
	LD	B,0		;LOAD BYTE COUNTER (256)
	LD	C,FILMRK	;LOAD SECTOR FILL BYTE
	CALL	STOBNB-O	;FILL THE SECTOR DATA FIELD
	LD	C,CRCMRK	;LOAD CRC ADDRESS MARK
	CALL	STOBTB-O	;STORE THE ADDRESS MARK
	LD	C,11111111B	;LOAD ALL BITS SET BYTE
	CALL	STOBTB-O	;STORE THE BYTE IN BUFFER
	LD	B,11		;LOAD BYTE COUNTER TO B
	CALL	STOBAS-O	;STORE ALL BITS SET BYTES
	INC	DE		;BUMP SKEW TABLE INDEX
	LD	A,(DE)		;GET SECTOR NUMBER FROM TABLE
	INC	A		;BUMP THE SECTOR NUMBER
	JR	NZ,FORMDS	;LOOP FOR NEXT IF MORE SECTORS
	LD	B,91		;LOAD BYTE COUNTER TO B
	CALL	STOBAS-O	;STORE ALL BITS SET BYTES
	CALL	WRTRAK		;WRITE THE TRACK TO DISK
;
;
; NOT FORMATTING TRACK - SKIP TO NEXT TRACK
;5486
	LD	A,(TRKNUM)	;GET TRACK NUMBER TO A
	INC	A		;BUMP THE TRACK NUMBER
	LD	(TRKNUM),A	;RE-SAVE TRACK NUMBER
	CP	NUMTRK		;TEST IF DONE LAST TRACK
	JR	Z,INISYS	;THEN WE ARE DONE FORMATTING
	LD	A,WDSTIN	;STEP IN DRIVE HEAD COMMAND
	LD	(CSTREG),A	;OUTPUT THE COMMAND
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
FORMWL:	LD	A,(CSTREG)	;GET CONTROLLER STATUS TO A
	RRCA			;COPY BUSY BIT TO CARRY
	JR	C,FORMWL	;LOOP UNTIL NOT BUSY
	JP	FORMDL		;THEN FORMAT NEXT TRACK
;
;
; WRITE A TRACK FROM TRACK BUFFER TO DISK - RETRY ONCE
;54A3
WRTRAK:	CALL	TRAKWR		;WRITE TRACK TO DISK
	RET	Z		;DONE IF SUCCESSFUL WRITE
;
;
; WRITE A TRACK FROM TRACK BUFFER TO DISK
;54A7
TRAKWR:	CALL	SELDST-O	;SELECT DISK DRIVE
	LD	BC,TRKBUF	;POINT AT TRACK BUFFER
	LD	HL,CSTREG	;COMMAND/STATUS REGISTER
	LD	(HL),WDWTRK	;WRITE TRACK COMMAND
	LD	DE,DTAREG	;POINT AT DATA REGISTER
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	DI			;DISABLE INTERRUPTS
	JR	TRAKWL		;THEN ENTER WRITE TRACK LOOP
;
;
; TEST IF NOT BUSY - IF SO, THEN WE ARE DONE WRITING
;54BC
TRAKWN:	RRCA			;COPY BUSY BIT TO CARRY
	JR	NC,TRAKWX	;ALL DONE IF NOT BUSY
;
;
; TEST IF CONTROLLER READY - LOOP IF NOT, ELSE LOAD AND WRITE
;54BF
TRAKWL:	LD	A,(HL)		;GET CONTROLLER STATUS TO A
	BIT	1,A		;TEST IF CONTROLLER IS READY
	JR	Z,TRAKWN	;TEST IF DONE IF IT ISN'T
	LD	A,(BC)		;GET DATA BYTE FROM BUFFER
	LD	(DE),A		;OUTPUT BYTE TO CONTROLLER
	INC	BC		;BUMP BUFFER POINTER
	JP	TRAKWL		;LOOP BACK FOR NEXT BYTE
;
;
; DONE WRITING TRACK - TEST FOR ANY ERRORS
; ENTRY:  BC      - CURRENT TRACK BUFFER OFFSET
;54CA
TRAKWX:	LD	A,(HL)		;GET FINAL STATUS TO A
	LD	HL,TRFASM	;TRANSFER RATE TOO FAST
	BIT	2,A		;TEST IF LOST DATA ERROR
	JP	NZ,ABORTM-O	;DISPLAY MESSAGE AND ABORT
	LD	HL,-TRKBUF	;NEGATED TRACK BUFFER OFFSET
	ADD	HL,BC		;ADD TO BUFFER OFFSET
	EX	DE,HL		;SWAP RESULT TO DE
	LD	HL,-TRKSIZ	;NEGATED TRACK BUFFER SIZE
	ADD	HL,DE		;ADD TO BUFFER OFFSET
	LD	HL,MSLOWM	;MOTOR SPEED TOO SLOW
	JP	NC,ABORTM-O	;DISPLAY MESSAGE AND ABORT
	LD	HL,-TRKOSI	;NEGATED MAXIMUM OVERFLOW SIZE
	ADD	HL,DE		;ADD TO BUFFER OFFSET
	LD	HL,MFASTM	;MOTOR SPEED TO FAST
	JP	C,ABORTM-O	;DISPLAY MESSAGE AND ABORT
	RET
;
;
; DONE FORMATTING - INITIALIZE THE DISK SYSTEM
;54ED
INISYS:	LD	A,CR		;LOAD NEWLINE CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	LD	D,0		;START AT TRACK ZERO
INISYN:	LD	L,D		;GET TRACK NUMBER TO L
	LD	H,High GATBUF-O	;INDEX INTO GAT SECTOR
	LD	A,(HL)		;GET ALLOCATION BYTE
	INC	A		;TEST IF TRACK LOCKED OUT
	JP	Z,NEXTIN	;THEN SKIP READING THE TRACK
	LD	A,D		;GET TRACK NUMBER TO A
	CALL	BINASC-O	;CONVERT TO ASCII DECIMAL
	LD	(VFYTKT-O),BC	;STORE IN VERIFY STRING
	LD	E,0		;ZERO SECTOR NUMBER
INISNS:	PUSH	DE		;SAVE TRACK AND SECTOR
	LD	A,D		;GET TRACK NUMBER TO A
	LD	A,E		;GET SECTOR NUMBER TO A
	CALL	BINASC-O	;CONVERT TO DECIMAL ASCII
	LD	(VFYTKS-O),BC	;STORE IN VERIFY STRING
	LD	HL,VFYTKM-O	;POINT AT VERIFY STRING
	CALL	MSGOUT-O	;DISPLAY THE MESSAGE
	POP	DE		;RECOVER TRACK AND SECTOR
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	CALL	RDSECT-O	;READ SECTOR INTO BUFFER
	LD	HL,NOTFOM	;POINT AT NOT FOUND MESSAGE
	BIT	4,A		;TEST IF RECORD NOT FOUND
	JP	NZ,LOCKTK-O	;THEN LOCK OUT THE TRACK
	LD	HL,CRCERM	;POINT AT CRC ERROR MESSAGE
	BIT	3,A		;TEST IF CRC ERROR
	JP	NZ,LOCKTK-O	;THEN LOCK OUT THE TRACK
	LD	HL,VFYSLM	;TRANSFER RATE TOO FAST
	BIT	2,A		;TEST IF LOST DATA
	JP	NZ,ABORTM-O	;THEN ABORT THE FORMAT
	INC	E		;BUMP SECTOR NUMBER
	LD	A,E		;GET SECTOR NUMBER TO A
	CP	NUMSEC		;TEST IF LAST SECTOR READ
	JP	NZ,INISNS	;LOOP FOR NEXT IF NOT
;
;
; LOOP FOR NEXT TRACK INITIALIZING
;553C
NEXTIN:	INC	D		;BUMP TRACK NUMBER
	LD	A,D		;GET TRACK NUMBER TO A
	CP	NUMTRK		;TEST IF LAST TRACK DONE
	JP	NZ,INISYN	;LOOP FOR NEXT IF NOT
	LD	A,CR		;LOAD NEWLINE CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	LD	HL,GATBUF-O	;POINT AT GAT BUFFER
	LD	DE,LOCKTB-O	;POINT AT LOCK-OUT TABLE
	LD	BC,NUMTRK	;LOAD ENTRY COUNT
	LDIR			;STORE LOCKED ENTRIES
;
;
; CONTINUATION IF NO FORMATTING NEEDED
;5553
NOFORM:	LD	HL,LOCKTB-O	;POINT AT TRACK LOCK-OUT TABLE
	LD	DE,GASLOT-O	;POINT AT THE OTHER TABLE
	LD	B,NUMTRK	;LOAD ENTRY COUNT
MEDIAT:	LD	A,(DE)		;GET LOCK-OUT TABLE BYTE
	CPL			;COMPLEMENT THE BYTE
	LD	C,A		;SAVE THE RESULT IN C
	PUSH	DE		;SAVE OTHER TABLE POINTER
	LD	A,E		;LOAD TABLE POINTER LSB
	SUB	Low GASLOT-O	;INDEX INTO ALLOCATION TABLE
	LD	E,A		;UPDATE TABLE POINTER
	LD	A,(DE)		;GET ALLOCATION BYTE
	POP	DE		;RECOVER OTHER TABLE POINTER
	AND	C		;AND WITH LOCK-OUT TABLE BYTE
	AND	(HL)		;AND WITH LOCK-OUT TABLE BYTE
	PUSH	HL		;SAVE LOCK-OUT TABLE POINTER
	LD	HL,REJECM	;DISK IS BAD AND REJECTED
	JP	NZ,ABORTM-O	;ABORT IF FLAWED DISKETTE
	POP	HL		;RECOVER SAVED TABLE POINTER
	INC	DE		;BUMP SECOND TABLE POINTER
	INC	HL		;BUMP FIRST TABLE POINTER
	DJNZ	MEDIAT		;LOOP UNTIL ALL ENTRIES DONE
	LD	A,(SGLDRV-O)	;GET SINGLE DRIVE BACKUP FLAG
	OR	A		;TEST IF ONLY ONE DRIVE
	JP	NZ,BACKIT-O	;THEN GO DO THE BACKUP
	LD	HL,4095		;INIT FOR MEMORY TEST LOOP
RAMTST:	LD	A,H		;GET ADDRESS MSB TO A
	SUB	High 4096	;SUBTRACT ONE MEMORY BLOCK
	LD	H,A		;UPDATE MEMORY POINTER MSB
	LD	A,(HL)		;GET BYTE FROM MEMORY
	LD	B,A		;SAVE THE BYTE IN B
	CPL			;COMPLEMENT THE BYTE
	LD	(HL),A		;STORE BYTE IN MEMORY
	CP	(HL)		;TEST IF WE HAVE RAM THERE
	LD	(HL),B		;RESTORE PREVIOUS BYTE
	JR	NZ,RAMTST	;LOOP UNTIL RAM IS FOUND
	LD	A,H		;GET TOP OF RAM MSB TO A
	SUB	High SCTBUF	;COMPUTE FREE MEMORY MSB
	LD	B,0		;INIT FOR COPY BUFFER SIZE
GETBUS:	INC	B		;BUMP BUFFER SIZE IN TRACKS
	SUB	High SIZTRK	;SUBTRACT TRACK OF SECTORS
	JR	NC,GETBUS	;LOOP UNTIL BUFFER UNDERFLOW
	LD	A,B		;GET TRACK COUNT TO A
	DEC	A		;COMPUTE BUFFER SIZE IN TRACKS
	LD	(COPYBS-O),A	;SAVE THE COPY BUFFER SIZE
	JP	BACKIT-O	;EXECUTE RELOCATED CODE
;
;
; DEFINE OFFSET FROM OUR LOCATION TO RELOCATED CODE
;
O	Equ	$-SYSBUF	;DEFINE THE OFFSET
;
;
; CODE COPIED TO 'SYSBUF' AND ABOVE, OVERLAYING TRSDOS
;559B (4200)
BACKIT:	CALL	SELDST-O	;SELECT DESTINATION DRIVE
	CALL	HOMHED-O	;HOME DISK DRIVE HEAD
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	LD	DE,0		;TRACK ZERO, SECTOR ZERO
	CALL	RDSECT-O	;READ BOOT SECTOR INTO BUFFER
	LD	HL,DSTRDM-O	;DESTINATION DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	LD	A,76H		;LOAD HALT OP-CODE
	LD	(HITBUF-O),A	;STORE AT BOOT SECTOR START
	LD	A,WDWRIT	;WRITE DATA SECTOR COMMAND
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	CALL	WRSECT-O	;WRITE THE BOOT SECTOR BACK
	LD	HL,DSTWRM-O	;DESTINATION DISK WRITE ERROR
	JP	NZ,ABORTM-O	;ABORT IF WRITE ERROR
	CALL	SELSWP-O	;SELECT DRIVE OR SWAP DISK
	CALL	HOMHED-O	;HOME DISK DRIVE HEAD
	XOR	A		;ZERO ACCUMULATOR
	LD	(XFRCNT-O),A	;ZERO TRACKS TRANSFERED COUNT
	LD	D,0		;ZERO THE TRACK NUMBER
REFILL:	LD	BC,SCTBUF	;POINT AT SECTOR BUFFER
	LD	A,(TRKREG)	;GET TRACK FROM CONTROLLER
	LD	(CTLTRK-O),A	;SAVE THE TRACK NUMBER
	LD	A,D		;GET TRACK NUMBER TO A
	LD	(CURTRK-O),A	;SAVE THE TRACK NUMBER
NEXTRK:	PUSH	BC		;SAVE SECTOR BUFFER POINTER
	LD	H,High GATSEC-O	;SECTOR BUFFER POINTER MSB
	LD	L,D		;INDEX INTO GAT SECTOR
	LD	C,(HL)		;GET ALLOCATION BYTE TO C
	LD	A,D		;GET TRACK NUMBER TO A
	ADD	A,Low GASLOT-O	;INDEX TO LOCK-OUT TABLE
	LD	L,A		;POINT AT LOCK-OUT TABLE
	LD	A,(HL)		;GET LOCK_OUT TABLE VALUE
	CPL			;COMPLEMENT THE BYTE
	AND	C		;MASK WITH ALLOCATION BYTE
	LD	H,High GATBUF-O	;CORRESPONDING GAT ADDRESS
	LD	C,(HL)		;GET LOCK-OUT BYTE TO C
	OR	C		;MERGE WITH LOCK-OUT BYTE
	CP	C		;TEST IF MATCHING VALUE
	POP	BC		;RECOVER SECTOR BUFFER POINTER
	JP	Z,LMATCH-O	;CONTINUE IF VALUES MATCH
	CALL	SELSWP-O	;SELECT DRIVE OR SWAP DISK
	LD	E,0		;ZERO SECTOR NUMBER
NEXSEC:	PUSH	BC		;SAVE BUFFER POINTER
	LD	A,D		;GET TRACK NUMBER TO A
	CALL	BINASC-O	;CONVERT TO DECIMAL ASCII
	LD	(LODTKT-O),BC	;STORE IN LOADING MESSAGE
	LD	A,E		;GET SECTOR NUMBER TO A
	CALL	BINASC-O	;CONVERT TO DECIMAL ASCII
	LD	(LODTKS-O),BC	;STORE IN LOADING MESSAGE
	POP	BC		;RECOVER BUFFER POINTER
	PUSH	DE		;SAVE TRACK AND SECTOR
	LD	HL,LODTKM-O	;POINT AT LOADING MESSAGE
	CALL	MSGOUT-O	;DISPLAY PROGRESS STRING
	POP	DE		;RECOVER TRACK AND SECTOR
	CALL	RDSECT-O	;READ SECTOR INTO BUFFER
	LD	HL,SRCRDM-O	;SOURCE DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	INC	E		;BUMP SECTOR NUMBER
	LD	A,E		;GET SECTOR TO A FOR TEST
	CP	NUMSEC		;TEST IF DONE WITH TRACK
	JR	NZ,NEXSEC	;LOOP FOR NEXT SECTOR IF NOT
	LD	A,(CSTREG)	;GET CONTROLLER STATUS TO A
	LD	L,D		;GET TRACK NUMBER TO L
	LD	H,High TRKTYP-O	;TRACK FORMAT TYPE BUFFER MSB
	LD	(HL),A		;STORE TRACK FORMAT TYPE
	LD	HL,XFRCNT-O	;POINT AT TRACK COUNTER
	INC	(HL)		;BUMP TRACKS LOADED COUNT
	LD	A,(SGLDRV-O)	;GET SINGLE DRIVE BACKUP FLAG
	OR	A		;TEST IF SINGLE DRIVE BACKUP
	JR	NZ,BUFULL	;SKIP IF NOT SINGLE DRIVE
	LD	A,(COPYBS-O)	;GET COPY BUFFER SIZE TO A
	CP	(HL)		;TEST IF COPY BUFFER FULL
	JR	Z,BUFULL	;WRITE OUT THE BUFFER IF SO
LMATCH:	INC	D		;BUMP TRACK NUMBER
	LD	A,D		;GET TRACK TO A FOR TEST
	CP	NUMTRK		;TEST IF DONE WITH DISK
	JP	NZ,NEXTRK-O	;LOOP FOR NEXT TRACK IF NOT
	LD	A,(XFRCNT-O)	;GET TRACKS TRANSFERED COUNT
	OR	A		;TEST IF NO TRACKS TO TRANSFER
	JP	Z,WRTINF-O	;THEN COPY THE INFORMATION
BUFULL:	LD	BC,SCTBUF	;POINT AT SECTOR BUFFER
	LD	A,0		;GET TRACK NUMBER TO A
;
;
; STORAGE FOR CURRENT TRACK FOR COPY PROGRESS
;5648
CTLTRK	Equ	$-1		;STORAGE FOR TRACK
;
;
; CONTINUATION OF TRACK COPY ROUTINE
;
	LD	(TRKREG),A	;SET UP TRACK REGISTER
	LD	D,0		;GET TRACK NUMBER TO D
;
;
; STORAGE FOR CURRENT TRACK
;564D
CURTRK	Equ	$-1		;STORAGE FOR TRACK
;
;
; CONTINUATION OF TRACK COPY ROUTINE
;564E
TRKNXT:	PUSH	BC		;SAVE BUFFER POINTER
	LD	H,High GATSEC-O	;LOAD BUFFER POINTER MSB
	LD	L,D		;GET TRACK NUMBER TO L
	LD	C,(HL)		;GET ALLOCATION TABLE BYTE
	LD	A,D		;GET TRACK NUMBER TO A
	ADD	A,Low GASLOT-O	;INDEX INTO LOCK-OUT TABLE
	LD	L,A		;POINT INTO LOCK-OUT TABLE
	LD	A,(HL)		;GET BYTE FROM THE TABLE
	CPL			;COMPLEMENT THE BYTE
	AND	C		;MASK WITH ALLOCATION BYTE
	LD	H,High GATBUF-O	;GET BUFFER POINTER MSB
	LD	C,(HL)		;GET ALLOCATION BYTE TO C
	OR	C		;MERGE WITH OTHER TABLE BYTE
	LD	L,D		;GET TRACK NUMBER TO L
	LD	(HL),A		;STORE BYTE IN THE TABLE
	CP	C		;TEST IF BYTES MATCH
	POP	BC		;RECOVER BUFFER POINTER
	JP	Z,SKIPTK-O	;SKIP TRACK IF MATCH
	CALL	RESELD-O	;RE-SELECT DISKETTE DRIVE
	LD	E,0		;ZERO SECTOR NUMBER
	LD	A,D		;GET TRACK NUMBER TO A
	OR	E		;TEST IF BOOT SECTOR
	JR	NZ,NOTBOT	;SKIP IF IT ISN'T
	LD	A,(BC)		;GET BOOT SECTOR BYTE TO A
	LD	(BOOTSA-O),A	;SAVE THE SECTOR BYTE
	LD	A,76H		;LOAD 'HALT' OP-CODE
	LD	(BC),A		;STORE IN BOOT SECTOR
NOTBOT:	PUSH	BC		;SAVE BUFFER POINTER
WRNEXS:	PUSH	BC		;SAVE BUFFER POINTER AGAIN
	LD	A,D		;GET TRACK NUMBER TO A
	CALL	BINASC-O	;CONVERT TO DECIMAL ASCII
	LD	(COPTKT-O),BC	;STORE IN COPYING MESSAGE
	LD	A,E		;GET SECTOR NUMBER TO A
	CALL	BINASC-O	;CONVERT TO DECIMAL ASCII
	LD	(COPTKS-O),BC	;STORE IN COPYING MESSAGE
	POP	BC		;RECOVER BUFFER POINTER
	PUSH	DE		;SAVE TRACK AND SECTOR
	LD	HL,COPTKM-O	;POINT AT COPYING MESSAGE
	CALL	MSGOUT-O	;DISPLAY PROGRESS STRING
	POP	DE		;RECOVER TRACK AND SECTOR
	LD	L,D		;GET TRACK NUMBER TO L
	LD	H,High TRKTYP-O	;TRACK FORMAT TYPE BUFFER MSB
	LD	A,(HL)		;GET FORMAT TYPE TO A
	AND	01100000B	;MASK TO FORMAT TYPE BITS
	RLCA			;ROTATE
	RLCA			; TO TWO
	RLCA			;  LS BITS
	OR	WDWRIT		;MAKE INTO WRITE SECTOR CODE
	CALL	WRSECT-O	;WRITE OUT THE SECTOR
	LD	HL,DSTWRM-O	;DESTINATION DISK WRITE ERROR
	JP	NZ,ABORTM-O	;ABORT IF WRITE ERROR
	INC	E		;BUMP SECTOR NUMBER
	LD	A,E		;GET SECTOR NUMBER TO A
	CP	NUMSEC		;TEST IF DONE WITH TRACK
	JR	NZ,WRNEXS	;LOOP FOR NEXT SECTOR IF NOT
	POP	BC		;RECOVER BUFFER POINTER
	LD	E,0		;ZERO SECTOR NUMBER
SCTNXT:	PUSH	BC		;SAVE BUFFER POINTER
	LD	A,D		;GET TRACK NUMBER TO A
	CALL	BINASC-O	;CONVERT TO ASCII DECIMAL
	LD	(VFYTKT-O),BC	;STORE IN VERIFYING MESSAGE
	LD	A,E		;GET SECTOR NUMBER TO A
	CALL	BINASC-O	;CONVERT TO ASCII DECIMAL
	LD	(VFYTKS-O),BC	;STORE IN VERIFYING MESSAGE
	POP	BC		;RECOVER BUFFER POINTER
	PUSH	DE		;SAVE TRACK AND SECTOR
	LD	HL,VFYTKM-O	;POINT AT VERIFYING MESSAGE
	CALL	MSGOUT-O	;DISPLAY PROGRESS STRING
	POP	DE		;RECOVER TRACK AND SECTOR
	CALL	RDSECT-O	;READ THE SECTOR TO STORE
	LD	HL,DSTRDM-O	;DESTINATION DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	INC	E		;BUMP SECTOR NUMBER
	LD	A,E		;GET SECTOR TO A FOR TEST
	CP	NUMSEC		;TEST IF DONE LAST SECTOR
	JR	NZ,SCTNXT	;LOOP FOR NEXT ONE IF NOT
	LD	HL,XFRCNT-O	;POINT AT TRACK TRANSFER COUNT
	DEC	(HL)		;DECREMENT THE COUNT
SKIPTK:	INC	D		;BUMP TRACK NUMBER
	LD	A,D		;GET TRACK TO A FOR TEST
	CP	NUMTRK		;TEST IF DONE LAST TRACK
	JR	Z,WRTINF	;THEN WE SKIP THE FOLLOWING
	LD	A,(XFRCNT-O)	;GET TRACK TRANSFER COUNT TO A
	OR	A		;TEST IF TRANSFER BUFFER EMPTY
	JP	NZ,TRKNXT-O	;LOOP FOR NEXT TRACK IF NOT
	JP	REFILL-O	;ELSE REFILL THE BUFFER
;
;
; COPY DONE - WRITE OUT INFORMATION
;56EA
WRTINF:	LD	HL,DTEBUF-O	;POINT AT BACKUP DATE STRING
	LD	DE,GASCRD-O	;POINT AT DATE LOCATION IN GAT
	LD	BC,8		;NUMBER OF BYTES TO COPY
	LDIR			;COPY BACKUP DATE TO GAT
	CALL	RESELD-O	;RE-SELECT DISKETTE DRIVE
	LD	A,(DIRTRK-O)	;GET DIRECTORY TRACK TO A
	LD	D,A		;GET DIRECTORY TRACK TO D
	LD	E,0		;LOAD GAT SECTOR NUMBER
	LD	BC,GATSEC-O	;POINT AT GAT SECTOR BUFFER
	LD	A,WDWRID	;WRITE DIRECTORY SECTOR COMMAND
	CALL	WRSECT-O	;WRITE OUT THE GAT SECTOR
	LD	HL,DSTWRM-O	;DESTINATION DISK WRITE ERROR
	JP	NZ,ABORTM-O	;ABORT IF WRITE ERROR
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	CALL	RDSECT-O	;READ GAT SECTOR TO BUFFER
	LD	HL,DSTRDM-O	;DESTINATION DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	LD	DE,0		;TRACK ZERO, SECTOR ZERO
	CALL	RDSECT-O	;READ BOOT SECTOR TO BUFFER
	LD	HL,DSTRDM-O	;DESTINATION DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	LD	A,0		;GET SAVED BOOT SECTOR BYTE
;
;
; STORAGE FOR SAVED BOOT SECTOR BYTE
;572B
BOOTSA	Equ	$-1		;SAVED BYTE STORAGE
;
;
; CONTINUATION OF BACKUP OPERATION
;
	LD	(BC),A		;RESTORE SAVED BYTE
	LD	A,WDWRIT	;WRITE DATA SECTOR COMMAND
	CALL	WRSECT-O	;WRITE OUT BOOT SECTOR
	LD	HL,DSTWRM-O	;DESTINATION DISK WRITE ERROR
	JP	NZ,ABORTM-O	;ABORT IF WRITE ERROR
	CALL	HOMHED-O	;HOME THE DRIVE HEAD
	LD	HL,BAKCOM-O	;BACKUP COMPLETE MESSAGE
;
;
; DISPLAY MESSAGE, PROMPT FOR <ENTER> AND RE-BOOT SYSTEM
; ENTRY:  HL      - POINTER TO MESSAGE STRING
;573E (43A3)
ABORTM:	CALL	MSGOUT-O	;DISPLAY ERROR MESSAGE
;
;
; PROMPT FOR <ENTER> KEY PRESS - THEN REBOOT SYSTEM
;5741 (43A6)
	LD	HL,HITENM-O	;POINT AT PROMPT STRING
	CALL	MSGOUT-O	;DISPLAY THE MESSAGE
PREENW:	LD	A,(KROSEV)	;READ KEYBOARD ROW
	RRCA			;ROTATE <ENTER> BIT TO CARRY
	JR	NC,PREENW	;LOOP UNTIL KEY PRESSED
	RST	00H		;THEN RE-BOOT SYSTEM
;
;
; WRITE A SECTOR FROM SECTOR BUFFER TO DISK - RETRY ONCE
; ENTRY:  A       - DISK CONTROLLER COMMAND CODE
;         BC      - POINTER TO BUFFER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - DISK CONTROLLER STATUS FLAGS
;         D       - UNCHANGED
;         E       - UNCHANGED
;         ZF      - SET IF SUCCESSFUL WRITE
;574E (43B3)
WRSECT:	LD	(SECTWC-O),A	;STORE COMMAND CODE
;
;
; WRITE A SECTOR FROM SECTOR BUFFER TO DISK - RETRY ONCE
; ENTRY:  BC      - POINTER TO BUFFER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - DISK CONTROLLER STATUS FLAGS
;         D       - UNCHANGED
;         E       - UNCHANGED
;         ZF      - SET IF SUCCESSFUL WRITE
;
	PUSH	BC		;SAVE BUFFER POINTER
	CALL	SECTWR-O	;WRITE SECTOR TO DISK
	POP	HL		;RECOVER BUFFER POINTER
	RET	Z		;DONE IF SUCCESSFUL WRITE
	LD	B,H		;BUFFER POINTER MSB TO B
	LD	C,L		;BUFFER POINTER LSB TO C
;
;
; WRITE A SECTOR FROM SECTOR BUFFER TO DISK
; ENTRY:  BC      - POINTER TO BUFFER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - DISK CONTROLLER STATUS FLAGS
;         D       - UNCHANGED
;         E       - UNCHANGED
;         ZF      - SET IF SUCCESSFUL WRITE
;5759 (43BE)
SECTWR:	LD	(SCTREG),DE	;STORE TRACK AND SECTOR
	PUSH	DE		;SAVE TRACK AND SECTOR
	CALL	SELDRV-O	;SELECT DISKETTE DRIVE
	LD	HL,CSTREG	;COMMAND/STATUS REGISTER
	LD	(HL),WDSEEK	;SEEK TO TRACK COMMAND
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
SECTWB:	LD	A,(HL)		;GET FLOPPY STATUS
	RRCA			;TEST IF CONTROLLER BUSY
	JR	C,SECTWB	;LOOP WHILE IT IS
	LD	(HL),0		;ELSE OUTPUT COMMAND CODE
SECTWC	Equ	$-1		;FLOPPY COMMAND CODE
	LD	DE,DTAREG	;POINT AT DATA REGISTER
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	DI			;DISABLE INTERRUPTS
	JR	SECTWL		;THEN ENTER READ LOOP
;
;
;TEST IF NOT BUSY - IF SO, THEN WE ARE DONE WRITING
;577A
SECTWN:	RRCA			;COPY BUSY BIT TO CARRY
	JR	NC,SECTWX	;ALL DONE IF NOT BUSY
;
;
; TEST IF CONTROLLER READY - LOOP IF NOT, ELSE LOAD AND WRITE
;577D (43E2)
SECTWL:	LD	A,(HL)		;GET CONTROLLER STATUS TO A
	BIT	1,A		;TEST IF CONTROLLER IS READY
	JR	Z,SECTWN	;TEST IF DONE IF IT ISN'T
	LD	A,(BC)		;GET DATA BYTE FROM BUFFER
	LD	(DE),A		;OUTPUT BYTE TO CONTROLLER
	INC	BC		;BUMP BUFFER POINTER
	JP	SECTWL-O	;LOOP BACK FOR NEXT BYTE
;
;
; DONE WRITING - GET FINAL STATUS AND RETURN
;57B8
SECTWX:	LD	A,(HL)		;GET FINAL STATUS TO A
	AND	01111100B	;MASK TO ERROR BITS
	POP	DE		;RECOVER TRACK AND SECTOR
	RET	Z		;RETURN IF NO ERRORS
	LD	(HL),WDFORC	;ELSE FORCE INTERRUPT
	RET
;
;
; TRACK UNUSABLE - DISPLAY MESSAGE AND LOCK OUT THE TRACK
; ENTRY:  D       - TRACK NUMBER
;         HL      - MESSAGE STRING POINTER
;5790 (43F5)
LOCKTK:	PUSH	DE		;SAVE TRACK AND SECTOR
	CALL	MSGOUT-O	;DISPLAY THE MESSAGE
	POP	DE		;RECOVER TRACK AND SECTOR
	LD	L,D		;GET TRACK NUMBER TO L
	LD	H,High GATBUF-O	;INDEX INTO GAT SECTOR
	LD	(HL),11111111B	;LOCK OUT THE TRACK
	JP	NEXTIN		;RE-ENTER SYSTEM INITIALIZE
;
;
; CONVERT A BINARY NUMBER TO ASCII DECIMAL
; ENTRY:  A       - BINARY NUMBER
; EXIT:   B       - DECIMAL ASCII NUMBER LSB
;         C       - DECIMAL ASCII NUMBER MSB
;579D (4402)
BINASC:	LD	C,'0'		;LOAD INITIAL ASCII ZERO
BINASL:	SUB	10		;SUBTRACT DECIMAL TEN
	JR	C,BINASX	;ALL DONE IF UNDERFLOW
	INC	C		;ELSE BUMP ASCII NUMBER MSB
	JR	BINASL		;LOOP FOR NEXT SUBTRACTION
BINASX:	ADD	A,'9'+1		;ADD REMAINDER TO LSB
	LD	B,A		;COPY ASCII RESULT LSB TO B
	RET
