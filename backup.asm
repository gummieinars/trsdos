;
; HOME DRIVE HEAD TO TRACK ZERO
;57B5 (441A)
HOMHED:	LD	A,WDHOME	;HOME DRIVE HEAD COMMAND
	LD	(CSTREG),A	;OUTPUT TO FLOPPY CONTROLLER
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
HOMHEW:	LD	A,(CSTREG)	;GET CONTROLLER STATUS TO A
	RRCA			;ROTATE BUSY BIT TO CARRY
	JR	C,HOMHEW	;LOOP UNTIL NOT BUSY
	RET
;
;
; SELECT SOURCE DRIVE FOR BACKUP
; ENTRY:  HL      - POINTER TO PROMPT STRING
;         SRCCOD  - DRIVE CODE WITH BIT SEVEN SET IF SELECTED
;57C5 (442A)
SELSRC:	LD	A,0		;GET SOURCE DRIVE CODE TO A
;
;
; COURCE DRIVE CODE STORAGE
;
SRCCOD	Equ	$-1		;SOURCE DRIVE CODE
;
;
; CONTINUATION TO PROMPT FOR AND SELECT SOURCE DRIVE
;
	OR	10000000B	;SET SOURCE SELECTED BIT
	PUSH	HL		;SAVE HL REGISTER
	LD	HL,INSSDM-O	;SOURCE DISK PROMPT STRING
	CALL	PMTSEL-O	;PROMPT AND SELECT DRIVE
	POP	HL		;RECOVER HL REGISTER
	RET
;
;
; SELECT A DRIVE AND SWAP DISK IF NEEDED ROUTINE
;57D2 (4437)
SELSWP:	LD	A,(CURDRN-O)	;GET CURRENT DRIVE NUMBER
	BIT	7,A		;TEST IF SOURCE SELECTED
	JR	NZ,SELSRC	;THEN RE-SELECT THE DRIVE
	CALL	SELSRC-O	;SELECT SOURCE DRIVE
	LD	A,(SGLDRV-O)	;GET SINGLE DRIVE BACKUP FLAG
	OR	A		;TEST IF SINGLE DRIVE
	RET	NZ		;ALL DONE IF IT ISN'T
	CALL	HOMHED-O	;ELSE HOME DISK DRIVE HEAD
	PUSH	BC		;SAVE BC REGISTER
	PUSH	DE		;SAVE DE REGISTER
	PUSH	HL		;SAVE HL REGISTER
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	LD	DE,0		;TRACK ZERO, SECTOR ZERO
	CALL	RDSECT-O	;READ BOOT SECTOR TO BUFFER
	LD	HL,SRCRDM-O	;SOURCE DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	POP	HL		;RECOVER HL REGISTER
	POP	DE		;RECOVER DE REGISTER
	POP	BC		;RECOVER BC REGISTER
	LD	A,(HITBUF-O)	;GET FIRST BOOT SECTOR BYTE
	OR	A		;TEST IF BYTE IS ZERO
	JR	NZ,ZEROCD	;ZERO DRIVE CODE AND RETRY
	PUSH	BC		;SAVE BC REGISTER
	PUSH	DE		;SAVE DE REGISTER
	PUSH	HL		;SAVE HL REGISTER
	LD	A,(DIRTRK-O)	;GET DIRECTORY TRACK TO A
	LD	D,A		;COPY TRACK NUMBER TO D
	LD	E,0		;GET HIT SECTOR NUMBER TO E
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	CALL	RDSECT-O	;READ HIT SECTOR TO BUFFER
	LD	HL,SRCRDM-O	;SOURCE DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	LD	HL,GASMPW-O	;POINT AT GAT MASTER PASSWORD
	LD	DE,HISMPW-O	;POINT AT MASTER PASSWORD
	LD	B,10		;LOAD COMPARE LENGTH
TSTSAM:	LD	A,(DE)		;GET BYTE FROM SECTOR
	CP	(HL)		;TEST IF A MATCH
	JR	NZ,SNARKY	;ABORT IF MISMATCH
	INC	DE		;BUMP DESTINATION POINTER
	INC	HL		;BUMP SOURCE POINTER
	DJNZ	TSTSAM		;LOOP UNTIL ALL COMPARED
	POP	HL		;RECOVER HL REGISTER
	POP	DE		;RECOVER DE REGISTER
	POP	BC		;RECOVER BC REGISTER
	RET
;
;
; SNARKY REMARK DISPLAYED WHEN WRONG DISK INSERTED
;5828
SNARKY:	LD	HL,WAKUPM-O	;POINT AT WAKE-UP MESSAGE
	CALL	MSGOUT-O	;DISPLAY THE MESSAGE STRING
	POP	HL		;RECOVER HL REGISTER
	POP	DE		;RECOVER DE REGISTER
	POP	BC		;RECOVER BC REGISTER
;
;
; ZERO CURRENT DRIVE NUMBER AND TRY AGAIN
;5831
ZEROCD:	XOR	A		;ZERO ACCUMULATOR
	LD	(CURDRN-O),A	;SET CURRENT DRIVE NUMBER
	JR	SELSWP		;THEN TRY AGAIN
;
;
; SELECT DESTINATION DRIVE FOR BACKUP
; ENTRY:  HL      - POINTER TO PROMPT STRING
;         DSTCOD  - DRIVE CODE WITH BIT SIX SET IF SELECTED
;5837 (449C)
SELDST:	LD	A,0		;GET DESTINATION DRIVE CODE
;
;
; DESTINATION DRIVE CODE STORAGE
;
DSTCOD	Equ	$-1		;DESTINATION  DRIVE CODE
;
;
; CONTINUATION TO PROMPT FOR AND SELECT DESTINATION DRIVE
;
	OR	01000000B	;SET DESTINATION SELECT BIT
	PUSH	HL		;SAVE HL REGISTER
	LD	HL,INSDDM-O	;DESTINATION DISK PROMPT STRING
	CALL	PMTSEL-O	;PROMPT AND SELECT DRIVE
	LD	A,(CSTREG)	;GET CONTROLLER STATUS TO A
	LD	HL,WRPROM-O	;DESTINATION WRITE PROTECTED
	BIT	6,A		;TEST IF WRITE PROTECTED
	JP	NZ,ABORTM-O	;ABORT BACKUP IF SO
	POP	HL		;RECOVER HL REGISTER
	RET
;
;
; RE-SELECT DISKETTE DRIVE
;584F (44B4)
RESELD:	LD	A,(CURDRN-O)	;GET CURRENT DRIVE NUMBER
	BIT	6,A		;TEST IF ALREADY SELECTED
	JR	NZ,SELDST	;THEN NO NEED TO RE-SELECT
	CALL	SELDST-O	;SELECT DESTINATION DRIVE
	LD	A,(SGLDRV-O)	;GET SINGLE DRIVE BACKUP FLAG
	OR	A		;TEST IF SINGLE DRIVE
	RET	NZ		;THEN WE JUST RETURN
	CALL	HOMHED-O	;HOME DISK DRIVE HEAD
	PUSH	BC		;SAVE BUFFER POINTER
	PUSH	DE		;SAVE TRACK AND SECTOR
	PUSH	HL		;SAVE HL REGISTER
	LD	BC,HITBUF-O	;POINT AT SECTOR BUFFER
	LD	DE,0		;TRACK ZERO, SECTOR ZERO
	CALL	RDSECT-O	;READ BOOT SECTOR INTO BUFFER
	POP	HL		;RECOVER HL REGISTER
	POP	DE		;RECOVER TRACK AND SECTOR
	POP	BC		;RECOVER BUFFER POINTER
	LD	HL,DSTRDM-O	;DESTINATION DISK READ ERROR
	JP	NZ,ABORTM-O	;ABORT IF READ ERROR
	LD	A,(HITBUF-O)	;GET BOOT SECTOR BYTE
	CP	76H		;TEST IF 'HALT' OP-CODE
	RET	Z		;DONE IF ALREADY WRITTEN
	XOR	A		;ELSE ZERO ACCUMULATOR
	LD	(CURDRN-O),A	;SET CURRENT DRIVE TO ZERO
	JR	RESELD		;THEN SELECT THE DRIVE
;
;
; SELECT DRIVE - PROMPT FOR DISKETTE CHANGE IF ONLY ONE DRIVE
; ENTRY:  A       - DRIVE CODE FOR NEW DRIVE SELECT
;         BC      - BUFFER POINTER
;         DE      - TRACK AND SECTOR
;         HL      - DRIVE CHANGE PROMPT STRING POINTER
;         CURDRN  - CURRENT DRIVE NUMBER
;         SGLDRV  - SINGLE DRIVE BACKUP FLAG
;5882 (44E7)
PMTSEL:	CP	0		;TEST IF DRIVE IS CURRENT
;
;
; CURRENT DRIVE NUMBER
;
CURDRN	Equ	$-1		;CURRENT DRIVE NUMBER STORAGE
;
;
; CONTINUATION OF DRIVE SELECT CODE

	JR	Z,SELDRV	;THEN RE-SELECT THE DRIVE
	LD	(CURDRN-O),A	;SET NEW CURRENT DRIVE NUMBER
	LD	A,0		;GET SINGLE DRIVE BACKUP FLAG
;
;
; SINGLE DRIVE BACKUP FLAG - NON ZERO IF DOUBLE DRIVE
;
SGLDRV	Equ	$-1		;SINGLE DRIVE BACKUP FLAG
;
;
; CONTINUATION OF DRIVE SELECT CODE
;
	OR	A		;TEST IF SINGLE DRIVE
	JR	NZ,SELDRV	;THEN JUST RE-SELECT DRIVE
	PUSH	BC		;SAVE BUFFER POINTER
	PUSH	DE		;SAVE TRACK AND SECTOR
	PUSH	HL		;SAVE PROMPT STRING POINTER
	LD	A,CR		;LOAD NEWLINE CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
WENTER:	CALL	MSGOUT-O	;DISPLAY PROMPT STRING
WRELEA:	LD	A,(KROSEV)	;READ KEYBOARD ROW
	RRCA			;ROTATE <ENTER> BIT TO CARRY
	JR	C,WRELEA	;LOOP UNTIL KEY RELEASED
	LD	BC,16384	;LOAD LOOP COUNTER
WAITLP:	LD	A,(KROSEV)	;READ KEYBOARD ROW
	RRCA			;ROTATE <ENTER> BIT TO CARRY
	JR	C,ISRELE	;DONE IF KEY RELEASED
	DEC	BC		;DECREMENT LOOP COUNTER
	LD	A,B		;GET VALUE TO A FOR TEST
	OR	C		;TEST IF LOOP EXHAUSTED
	JR	NZ,WAITLP	;LOOP UNTIL LOOP DONE
	LD	A,EE		;END OF LINE ERASE CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	LD	BC,13107	;LOAD DELAY VALUE
	CALL	DELAYL		;DELAY FOR 192 MILLISECONDS
	JR	WENTER		;THEN LOOP UNTIL <ENTER> KEY
ISRELE:	LD	A,EE		;END OF LINE ERASE CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	POP	HL		;RECOVER PROMPT STRING POINTER
	POP	DE		;RECOVER TRACK AND SECTOR
	POP	BC		;RECOVER BUFFER POINTER
;
;
; RE-SELECT CURRENT DRIVE
; ENTRY:  CURDRN  - CURRENT DRIVE NUMBER
;58C2 (4527)
SELDRV:	LD	A,(CSTREG)	;GET CONTROLLER STATUS
	PUSH	AF		;SAVE THE STATUS
	LD	A,(CURDRN-O)	;GET DRIVE NUMBER TO A
	LD	(DRVREG),A	;RE-SELECT CURRENT DRIVE
	POP	AF		;RECOVER SAVED STATUS
	RLCA			;COPY NOT READY BIT TO CARRY
	PUSH	BC		;SAVE BUFFER POINTER
	LD	BC,0		;LOAD DELAY VALUE
	CALL	C,DELAYL	;DELAY FOR 960 MILLISECONDS
	POP	BC		;RECOVER BUFFER POINTER
	RET
;
;
; READ A DISK SECTOR INTO SECTOR BUFFER - RETRY ONCE
; ENTRY:  BC      - POINTER TO BUFFER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - DISK CONTROLLER STATUS FLAGS
;         D       - UNCHANGED
;         E       - UNCHANGED
;         ZF      - SET IF SUCCESSFUL READ
;58D7 (453C)
RDSECT:	PUSH	BC		;SAVE BUFFER POINTER
	CALL	SECTRD-O	;READ SECTOR INTO BUFFER
	POP	HL		;RECOVER BUFFER POINTER
	RET	Z		;DONE IF SUCCESSFUL READ
	LD	B,H		;BUFFER POINTER MSB TO B
	LD	C,L		;BUFFER POINTER LSB TO C
;
;
; READ A DISK SECTOR INTO SECTOR BUFFER
; ENTRY:  BC      - POINTER TO BUFFER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - DISK CONTROLLER STATUS FLAGS
;         D       - UNCHANGED
;         E       - UNCHANGED
;         ZF      - SET IF SUCCESSFUL READ
;58DF (4544)
SECTRD:	CALL	SELDRV-O	;RE-SELECT CURRENT DRIVE
	LD	(SCTREG),DE	;STORE TRACK AND SECTOR
	PUSH	DE		;SAVE TRACK AND SECTOR VALUES
	LD	HL,CSTREG	;COMMAND/STATUS REGISTER
	LD	(HL),WDSEEK	;SEEK TO TRACK COMMAND
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
SECTRB:	LD	A,(HL)		;GET FLOPPY CONTROLLER STATUS
	RRCA			;COPY BUSY BIT TO CARRY
	JR	C,SECTRB	;LOOP IF CONTROLLER BUSY
	LD	(HL),WDREAD	;READ SECTOR COMMAND
	LD	DE,DTAREG	;POINT AT DATA REGISTER
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	DI			;DISABLE INTERRUPTS
	JR	SECTRL		;THEN ENTER READ LOOP
;
;
; TEST IF NOT BUSY - IF SO, THEN WE ARE DONE READING
;5900 (4565)
SECTRN:	RRCA			;COPY BUSY BIT TO CARRY
	JR	NC,SECTRX	;ALL DONE IF NOT BUSY
;
;
; TEST IF DATA BYTE READY - LOOP IF NOT, ELSE READ AND STORE
;5903 (4568)
SECTRL:	LD	A,(HL)		;GET CONTROLLER STATUS TO A
	BIT	1,A		;TEST IF DATA BYTE IS READY
	JR	Z,SECTRN	;TEST IF DONE IF IT ISN'T
	LD	A,(DE)		;GET DATA BYTE FROM DISK
	LD	(BC),A		;STORE BYTE IN BUFFER
	INC	BC		;BUMP BUFFER POINTER
	JP	SECTRL-O	;LOOP BACK FOR NEXT BYTE
;
;
; DONE READING - GET FINAL STATUS AND RETURN
;590E (4573)
SECTRX:	LD	A,(HL)		;GET FINAL STATUS TO A
	AND	01011100B	;MASK TO ERROR BITS
	POP	DE		;RECOVER TRACK AND SECTOR
	RET	Z		;RETURN IF NO ERRORS
	LD	(HL),WDFORC	;ELSE FORCE INTERRUPT
	RET
;
;
; DISPLAY A MESSAGE STRING
; ENTRY:  HL      - POINTER TO STRING
;5916 (457B)
MSGOUT:	PUSH	HL		;SAVE MESSAGE POINTER
MSGOUL:	LD	A,(HL)		;GET CHARACTER FROM STRING
	CP	CC		;TEST IF MESSAGE END
	JR	Z,MSGOUX	;EXIT IF END OF STRING
	CALL	VDCHAR		;ELSE DISPLAY THE CHARACTER
	INC	HL		;BUMP MESSAGE POINTER
	CP	CR		;TEST IF MESSAGE END
	JR	NZ,MSGOUL	;LOOP FOR NEXT CHARACTER
MSGOUX:	POP	HL		;RECOVER MESSAGE POINTER
	RET
