;
; SAVE VALUE OF A VARIABLE ON THE STACK
; ENTRY:  HL      - VARIABLE ADDRESS
;         CF      - SET
; EXIT:   (SP)    - THE VARIABLE (2, 4 OR 8 BYTES)
;         CF      - SET
;
PSHVAR:	LD	A,(VARTYP)	;GET VARIABLE TYPE FLAG
	DEC	A		;TEST IF
	DEC	A		; VARIABLE
	DEC	A		;  IS A STRING
	OR	A		;SET FLAGS
	SCF			;RESTORE CARRY FLAG
	JP	Z,PSHSTR	;SAVE STRING
	LD	C,(HL)		;GET VARIABLE VALUE
	INC	HL		;BUMP POINTER
	LD	B,(HL)		;GET VARIABLE VALUE
	PUSH	BC		;PUSH VALUE ON STACK
	JP	M,PSHVEX	;DONE IF INTEGER VARIABLE
	INC	HL		;BUMP POINTER
	LD	C,(HL)		;GET VARIABLE VALUE
	INC	HL		;BUMP POINTER
	LD	B,(HL)		;GET VARIABLE VALUE
	PUSH	BC		;PUSH IT ON THE STACK
	JP	PO,PSHVEX	;DONE IF SINGLE PRECISION
	INC	HL		;BUMP POINTER
	JR	C,PSHVUN	;SKIP ALWAYS (???)
	LD	HL,PRIACC	;POINT TO 'PRIACC' LSB (???)
PSHVUN:	LD	C,(HL)		;GET VARIABLE VALUE
	INC	HL		;BUMP POINTER
	LD	B,(HL)		;GET VARIABLE VALUE
	INC	HL		;BUMP POINTER
	PUSH	BC		;PUSH IT ON THE STACK
	LD	C,(HL)		;GET VARIABLE VALUE
	INC	HL		;BUMP POINTER
	LD	B,(HL)		;GET VARIABLE VALUE
	PUSH	BC		;PUSH IT ON THE STACK
PSHVEX:	JP	C,FNEREN	;RE-ENTER 'FN' EVALUATION LOOP
;
;
; CHECK USER DEFINED FUNCTION SYNTAX
; ENTRY:  HL      - CODE STRING POINTER
; EXIT:   A       - 'FN' TOKEN
;         B       - 'FN' TOKEN
;         DE      - VARIABLE ADDRESS
;         FORFUN  - BIT 7 SET IF FUNCTION
;
FNCHK:	RST	TSTNXT		;NEXT MUST
	 Db	FNTOK		; BE FN TOKEN
	LD	A,10000000B	;SHOW USER DEFINED
	LD	(FORFUN),A	; FUNCTION IN PROGRESS
	OR	(HL)		;GET FIRST CHARACTER OF
	LD	B,A		; 'FN' VARIABLE NAME TO B
	JP	FUNVAR		;SEARCH FOR 'FN' VARIABLE
;
;
; 'FN' - USER DEFINED FUNCTION
;
FNEVAL:	CALL	FNCHK		;CHECK 'FN' SYNTAX
	LD	A,(VARTYP)	;GET VARIABLE TYPE FLAG
	OR	A		;SET FLAGS
	PUSH	AF		;SAVE THE FLAGS FOR LATER
	LD	(GRBPNT),HL	;SAVE BASIC CODE POINTER
	EX	DE,HL		;GET POINTER TO VARIABLE
	LD	A,(HL)		;GET VARIABLE POINTER LSB
	INC	HL		;BUMP TO MSB
	LD	H,(HL)		;GET VARIABLE POINTER MSB
	LD	L,A		;HL CONTAINS POINTER
	OR	H		;TEST IF FUNCTION DEFINED
	JP	Z,DEFERR	;UNDEFINED USER FUNCTION IF NOT
	LD	A,(HL)		;GET BYTE FROM PROGRAM
	CP	'('		;TEST IF OPEN PARENS
	JP	NZ,FNEVOK	;SKIP IF NOT
	RST	CHRGET		;SKIP PAST PARENS
	LD	(SIXUSI),HL	;SAVE CURRENT STATEMENT INDEX
	JR	FNEPAR		;GO GET PARAMETERS
NXTFNP:	RST	TSTNXT		;NEXT BYTE MUST
	 Db	','		; BE A COMMA
FNEPAR:	LD	C,4		;NUMBER OF WORDS NEEDED
	CALL	CKSTAK		;TEST FREE SPACE AVAILABLE
	LD	A,10000000B	;SHOW USER DEFINED
	LD	(FORFUN),A	; FUNCTION IN PROGRESS
	CALL	FNDVAR		;FIND/CREATE A VARIABLE
	EX	DE,HL		;MOVE VARIABLE ADDRESS TO HL
	SCF			;MUST SET CARRY FLAG
	JP	PSHVAR		;SAVE VARIABLE VALUE ON STACK
PSHSTR:	JP	NC,FRMEBU	;JUMP NEVER TAKEN
	PUSH	DE		;SAVE CODE STRING POINTER
	EX	DE,HL		;MOVE VARIABLE ADDRESS TO DE
	CALL	STKDSC		;SAVE STRING DESCRIPTOR
	POP	DE		;RECOVER CODE STRING POINTER
	XOR	A		;ZERO ACCUMULATOR
FNEREN:	PUSH	HL		;SAVE VARIABLE ADDRESS
	PUSH	AF		;SAVE VARIABLE TYPE
	EX	DE,HL		;GET CODE STRING POINTER TO HL
	LD	A,(HL)		;GET BYTE FROM PROGRAM
	CP	')'		;TEST IF CLOSING PARENS
	JR	NZ,NXTFNP	;PROCESS NEXT VALUE IF NOT
	LD	HL,(GRBPNT)	;GET BASIC CODE POINTER BACK
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	'('		; BE OPENING PARENS
	PUSH	HL		;SAVE CODE POINTER
	LD	HL,(SIXUSI)	;GET INDEX TO CURRENT STATEMENT
FNENEX:	CALL	FNDVAR		;FIND/CREATE A VARIABLE
	EX	(SP),HL		;SAVE VAR ADDR, GET CODE PTR
	CALL	ASSVAL		;ASSIGN VALUE TO VARIABLE
	LD	A,(HL)		;GET BYTE FROM PROGRAM
	CP	')'		;TEST IF CLOSING PARENS
	JR	Z,FNEVEX	;SKIP IF IT IS
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	','		; BE A COMMA
	EX	(SP),HL		;GET VARIABLE ADDRESS
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	','		; BE A COMMA
	JR	FNENEX		;THEN EVALUATE NEXT EXPRESSION
FNEVEX:	RST	CHRGET		;SKIP PAST CLOSING PARENS
	EX	(SP),HL		;GET VARIABLE ADDRESS
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	')'		; BE A CLOSING PARENS
	Db	3EH		;SKIP NEXT INSTRUCTION
;
;
; RESTORE VALUES OF SAVED VARIABLES
; ENTRY:  (SP)    - VARIABLE TYPE FLAGS AND VALUES
;
FNEVOK:	PUSH	DE		;SAVE VARIABLE ADDRESS
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	EQUTOK		; BE EQUALS TOKEN
	CALL	FRMEV2		;EVALUATE EXPRESSION
	DEC	HL		;BACKUP CODE STRING POINTER
	RST	CHRGET		;TEST IF END OF LINE
	JP	NZ,SNEROR	;SYNTAX ERROR IF IT ISN'T
	RST	GETYPE		;TEST DATA MODE
	JR	Z,FNEPST	;SKIP IF A STRING
FNEPOS:	POP	DE		;RECOVER VARIABLE ADDRESS
FNEPOP:	POP	AF		;RECOVER VARIABLE TYPE FLAG
	JR	Z,FNESTR	;SKIP IF VARIABLE A STRING
	JR	NC,FNEDBL	;JUMP IF DOUBLE PRECISION
	POP	HL		;RECOVER VARIABLE ADDRESS
	POP	BC		;RECOVER VALUE
	LD	(HL),B		;STORE VALUE BYTE
	DEC	HL		;DECREMENT POINTER
	LD	(HL),C		;STORE VALUE BYTE
	JP	M,FNEPOP	;LOOP BACK IF INTEGER
	DEC	HL		;DECREMENT POINTER
	POP	BC		;RECOVER VALUE
	LD	(HL),B		;STORE VARIABLE BYTE
	DEC	HL		;DECREMENT POINTER
	LD	(HL),C		;GET VALUE BYTE
	JP	PO,FNEPOP	;LOOP BACK IF SINGLE PRECISION
	DEC	HL		;ELSE DECREMENT POINTER
	POP	BC		;RECOVER VALUE
	LD	(HL),B		;STORE VALUE BYTE
	DEC	HL		;DECREMENT POINTER
	LD	(HL),C		;STORE VALUE BYTE
	DEC	HL		;DECREMENT POINTER
	POP	BC		;RECOVER VALUE
	LD	(HL),B		;STORE VALUE BYTE
	DEC	HL		;DECREMENT POINTER
	LD	(HL),C		;STORE VALUE BYTE
	JR	FNEPOP		;THEN LOOP BACK FOR NEXT VALUE
FNEDBL:	PUSH	DE		;SAVE VARIABLE ADDRESS
	PUSH	AF		;SAVE VARIABLE TYPE
	RST	GETYPE		;TEST DATA MODE
	LD	DE,TSDSTK	;POINT TO STRING DESCRIPTOR
	CALL	Z,STKDSC	;SET UP DESCRIPTOR IF STRING
	POP	AF		;RECOVER VARIABLE TYPE
	JP	CNVTNP		;CONVERT TO CORRECT TYPE
