	LD	A,(HL)		;GET CHARACTER FROM LINE
	CALL	CKLETR		;TEST IF ALPHA CHARACTER
	EX	DE,HL		;GET RESULT REGISTER TO HL
	JR	NC,HEXALP	;SKIP IF ALPHA CHARACTER
	CP	'9'+1		;TEST IF NUMERIC HEX
	JR	NC,CONVEX	;END OF CONVERSION IF NOT
	SUB	'0'		;ELSE REMOVE ASCII BIAS
	JR	C,CONVEX	;DONE IF NOT NUMERIC
	JR	HEXDIG		;ELSE ADD IN NEW DIGIT
HEXALP:	CP	'F'+1		;TEST IF ALPHA HEX
	JR	NC,CONVEX	;DONE IF NOT HEX DIGIT
	SUB	'7'		;REMOVE ALPHA BIAS
HEXDIG:	ADD	HL,HL		;SHIFT
	ADD	HL,HL		; LS NYBBLE
	ADD	HL,HL		;  FOUR POSITIONS
	ADD	HL,HL		;   TO THE LEFT
	OR	L		;MERGE IN NEW LS DIGIT
	LD	L,A		;UPDATE RESULT REGISTER
	DEC	B		;DECREMENT CHARACTER COUNTER
	JP	Z,OVEROR		;OVERFLOW IF MORE THAN 16 BITS
	EX	DE,HL		;SAVE RESULT REGISTER IN DE
	JR	HEXCLP		;THEN CONVERT NEXT DIGIT
;
;
; OCTAL CONVERSION
;
OCTCON:	DEC	HL		;BACKUP LINE INDEX
OCTCLP:	RST	CHRGET		;GET CHARACTER FROM LINE
	EX	DE,HL		;MOVE RESULT REGISTER TO HL
	JR	NC,CONVEX	;DONE IF END OF NUMBER
	CP	'8'		;TEST IF VALID OCTAL DIGIT
	JP	NC,SNEROR	;SYNTAX ERROR IF NOT
	LD	BC,OVEROR	;ADDRESS OF OVERFLOW ROUTINE
	PUSH	BC		;PUSH IT ON THE STACK
	ADD	HL,HL		;SHIFT LEFT ONE POSITION
	RET	C		;ABORT IF OVERFLOW
	ADD	HL,HL		;SHIFT LEFT ONE POSITION
	RET	C		;ABORT IF OVERFLOW
	ADD	HL,HL		;SHIFT LEFT ONE POSITION
	RET	C		;ABORT IF OVERFLOW
	POP	BC		;REMOVE ERROR ADDRESS
	LD	B,0		;ZERO B REGISTER
	SUB	'0'		;SUBTRACT ASCII BIAS
	LD	C,A		;DIGIT NOW IN BC REGISTER
	ADD	HL,BC		;MERGE IN NEW DIGIT
	EX	DE,HL		;SAVE RESULT REGISTER IN DE
	JR	OCTCLP		;THEN CONVERT NEXT DIGIT
CONVEX:	CALL	STOINT		;STORE INTEGER IN 'PRIACC'
	EX	DE,HL		;RESTORE LINE INDEX TO HL
	RET
