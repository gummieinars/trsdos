	POP	HL		;RECOVER CODE STRING POINTER
	POP	BC		;RECOVER ENDING VALUE
	POP	AF		;RECOVER STARTING VALUE
	LD	B,A		;GET STARTING VALUE TO B
	EX	(SP),HL		;GET STRING POINTER
	PUSH	HL		;SAVE IT AGAIN
	LD	HL,POPRET	;SET RETURN ADDRESS SO THAT
	EX	(SP),HL		; CODE POINTER IS RESTORED
	LD	A,C		;GET ENDING VALUE TO A
	OR	A		;TEST IF ZERO
	RET	Z		;THEN NOTHING DONE
	LD	A,(HL)		;GET STRING LENGTH TO A
	SUB	B		;TEST IF PAST END OF STRING
	JP	C,FCEROR		;THEN ILLEGAL FUNCTION CALL
	INC	A		;BUMP THE RESULT
	CP	C		;TEST IF END IS LARGER
	JR	C,MIDLEL	;SKIP IF IT IS
	LD	A,C		;ELSE DEFAULT TO END
MIDLEL:	LD	C,B		;GET START TO C
	DEC	C		;DECREMENT BY ONE
	LD	B,0		;BC IS START INDEX
	PUSH	DE		;SAVE STRING POINTER
	INC	HL		;BUMP PAST LENGTH BYTE
	LD	E,(HL)		;GET LSB OF ADDRESS TO E
	INC	HL		;BUMP TO MSB
	LD	H,(HL)		;GET MSB OF ADDRESS TO H
	LD	L,E		;HL CONTAINS STRING ADDRESS
	ADD	HL,BC		;INDEX INTO STRING
	LD	B,A		;GET COUNTER TO B
	POP	DE		;RECOVER STRING POINTER
	EX	DE,HL		;MOVE POINTER TO HL
	LD	C,(HL)		;GET LENGTH TO C
	INC	HL		;BUMP TO ADDRESS LSB
	LD	A,(HL)		;GET LSB OF ADDRESS
	INC	HL		;BUMP TO MSB
	LD	H,(HL)		;GET MSB OF ADDRESS
	LD	L,A		;HL CONTAINS ADDRESS
	EX	DE,HL		;DE=SOURCE, HL=DESTINATION
	LD	A,C		;GET LENGTH TO A
	OR	A		;TEST IF ZERO
	RET	Z		;THEN NOTHING DONE
