LOADLP:	EX	DE,HL		;SAVE WORKSPACE POINTER IN DE
	LD	HL,(STRSPC)	;GET STRING SPACE POINTER
	LD	BC,-86		;LOAD MINIMUM VARIABLE SPACE
	ADD	HL,BC		;GET MAXIMUM PROGRAM TOP
	RST	CPHLDE		;TEST IF PROGRAM TOO BIG
	EX	DE,HL		;GET WORKSPACE POINTER BACK
	JP	C,TOOBIG	;TOO BIG SO CLEAR WORKSPACE
	CALL	INPBYT		;READ ANOTHER BYTE
	LD	(HL),A		;STORE IT IN MEMORY
	INC	HL		;BUMP WORKSPACE POINTER
	JP	NC,LOADLP	;LOOP IF NOT END OF LOAD
	CALL	RELINK		;UPDATE LINE POINTERS
	INC	HL		;BUMP WORKSPACE
	INC	HL		; POINTER TWICE
	LD	(VARTAB),HL	;SET ADDR OF SIMPLE VARIABLES
	LD	HL,MAXOPN	;POINT TO MAX FILES STORAGE
	LD	A,(HL)		;GET MAX NUMBER OF OPEN FILES
	LD	(MAXOST),A	;SAVE THE VALUE
	LD	(HL),0		;ZERO MAX OPEN FILE COUNT
	CALL	CODCLR		;PERFORM 'CLEAR'
	LD	A,(MAXOST)	;GET SAVED MAX OPEN FILE COUNT
	LD	(MAXOPN),A	;RESTORE MAX OPEN FILE COUNT 
	LD	A,(RUNFLG)	;GET FILE RUN FLAG
	OR	A		;TEST IF FILE RUN WANTED
	JP	Z,WARMST	;WARM START BASIC IF NOT
	JP	XQLOOP		;ELSE RUN THE FILE
;
;
; LINK - CALLED JUST BEFORE ENTERING BASIC'S COMMAND MODE
;
RDYLNK:	CALL	DFLOUT		;MARK END OF DISK I/O (EPRLNK)
	CALL	FILCLS		;CLOSE FILE NUMBER ZERO
	POP	HL		;GET RETURN ADDRESS
	PUSH	DE		;SAVE DE REGISTER
	LD	DE,WRMREN	;GET WARM START RE-ENTRY
	RST	CPHLDE		;TEST IF CALLED FROM IT
	POP	DE		;RECOVER DE REGISTER
	PUSH	HL		;RESAVE RETURN ADDRESS
	CALL	Z,TSTPRO	;IF WARM TEST IF PROTECTED FILE
	JP	GETCPT		;RECOVER CODE POINTER AND RET
;
;
; FILE WAS TOO BIG TO LOAD SO CLEAR THE WORKSPACE
;
TOOBIG:	CALL	RESPTR		;ISSUE 'NEW' COMMAND
	JP	OMEROR		;OUT OF MEMORY ERROR
;
;
; 'MERGE' - APPEND A BASIC SOURCE PROGRAM TO CURRENT ONE
;
MERCMD:	POP	BC		;CLEAR RETURN ADDRESS
	CALL	OPENIN		;OPEN FILE FOR INPUT
	DEC	HL		;BACKUP CODE STRING POINTER
	RST	CHRGET		;TEST IF END OF LINE
	JP	Z,MERCOK	;THEN ALL IS OK
	CALL	RDYLNK		;CLOSE THE FILE
	JP	SNEROR		;THEN REPORT SYNTAX ERROR
MERCOK:	XOR	A		;ZERO ACCUMULATOR
	LD	(RUNFLG),A	;CLEAR FILE RUN FLAG TO A
	CALL	INPBYT		;READ BYTE FROM FILE
	JP	C,INMAIN	;BACK TO INPUT LOOP IF EOF
	INC	A		;TEST IF TOKENIZED BASIC
	JP	Z,BMEROR		;BAD FILE MODE IF IT IS
;
;
; LOAD AN ASCII BASIC FILE INTO WORKSPACE
;
LODASC:	LD	HL,(FIOPTR)	;GET FILE I/O POINTER
	LD	BC,7		;INDEX TO NEXT ASCII LINE
	ADD	HL,BC		;GET ADDRESS OF POINTER
	CALL	BACREC		;TEST IF MORE DATA IN RECORD
	JP	INMAIN		;BACK TO INPUT LOOP
;
;
; LINK - CALLED IMMEDIATELY AFTER LINE HAS BEEN TOKENIZED
; ENTRY:  HL      - POINTER TO TOKENIZED LINE
;
TOKLNK:	RET	C		;RETURN IF NUMERIC
	POP	AF		;REMOVE RETURN ADDRESS
	PUSH	HL		;SAVE CODE STRING POINTER
	LD	HL,(FIOPTR)	;GET FILE I/O POINTER
	LD	A,H		;TEST IF INPUTTING
	OR	L		; FROM A FILE
	LD	DE,DSCODE	;DIRECT STATEMENT IN FILE
	JP	NZ,ERRENT	;REPORT ERROR IF FILE INPUT
	POP	HL		;RECOVER CODE STRING POINTER
	CALL	TSTPRO		;TEST IF FILE IS PROTECTED
	JP	EXELIN		;JUMP TO EXECUTION LOOP
;
;
; 'SAVE' - SAVE A BASIC SOURCE PROGRAM TO DISK
;
SAVCMD:	LD	D,2		;LOAD OUTPUT CODE
	CALL	OPENIO		;OPEN FILE FOR OUTPUT
	DEC	HL		;DECREMENT CODE POINTER
	RST	CHRGET		;TEST IF END OF LINE
	JP	Z,SAVCTK	;SKIP FORWARD IF SO
	RST	TSTNXT		;NEXT CHARACTER
	 Db	','		; MUST BE A COMMA
	RST	TSTNXT		;NEXT BYTE MUST BE AN 'A'
	 Db	'A'		; TO INDICATE ASCII SAVE
	JP	LSTCMD		;THEN USE LIST ROUTINE TO SAVE
SAVCTK:	LD	A,0FFH		;LOAD TONENIZED BASIC HEADER
	CALL	OUTBYT		;OUTPUT HEADER BYTE TO FILE
	LD	HL,(VARTAB)	;GET ADDR OF SIMPLE VARIABLES
	EX	DE,HL		;SAVE IT IN DE REGISTER
	LD	HL,(TXTTAB)	;GET START OF PROGRAM STORAGE
SAVCLP:	RST	CPHLDE		;SEE IF END OF PROGRAM PROGRAM
	JP	Z,RDYLNK	;THEN NOTHING MORE TO DO
	LD	A,(HL)		;ELSE GET BYTE FROM PROGRAM
	INC	HL		;BUMP TO NEXT BYTE
	PUSH	DE		;SAVE END OF PROGRAM POINTER
	CALL	OUTBYT		;OUTPUT BYTE TO FILE
	POP	DE		;RECOVER END OF PROGRAM POINTER
	JP	SAVCLP		;THEN CONTINUE WITH NEXT BYTE
;
;
; CLOSE - CLOSE A SEQUENTIAL OR RANDOM ACCESS FILE
;
CLOCMD:	LD	BC,FILCLS	;LOAD ADDRESS OF CLOSE ROUTINE
	LD	A,(MAXOPN)	;GET MAX NUMBER OF OPEN FILES
	JP	NZ,FILCLO	;CLOSE SPECIFIC FILE NUMBER
	PUSH	HL		;SAVE CODE STRING POINTER
CLOCNX:	PUSH	BC		;SET CLOSE ROUTINE ADDRESS
	PUSH	AF		;SAVE FILE NUMBER
	LD	DE,CLOMNY	;ADDRESS OF CLOSE LOOP
	PUSH	DE		;PUSH IT ON THE STACK
	PUSH	BC		;PUSH CLOSE ROUTINE ADDRESS
	RET
;
;
; CLOSE A NUMBER OF OPENED FILES
; ENTRY:  (SP+0)  - FILE COUNTER
;         (SP+2)  - CLOSE ROUTINE ADDRESS
;
CLOMNY:	POP	AF		;RECOVER FILE NUMBER
	POP	BC		;RECOVER CLOSE ROUTINE ADDRESS
	DEC	A		;DECREMENT FILE NUMBER
	JP	P,CLOCNX	;CLOSE NEXT FILE IF MORE
	POP	HL		;ELSE GET CODE STRING POINTER
	RET
;
;
; CLOSE OPEN FILES
; ENTRY:  (SP+0)  - ADDRESS OF CLOSE ROUTINE
;         (SP+2)  - CODE STRING POINTER
;
CLOFIL:	POP	BC		;RECOVER CLOSE ROUTINE ADDRESS
	POP	HL		;RECOVER CODE STRING POINTER
	LD	A,(HL)		;GET CHARACTER FROM BASIC
	CP	','		;TEST IF COMMA FOLLOWS
	RET	NZ		;RETURN IF NO MORE FILES
	RST	CHRGET		;SKIP PAST THE COMMA
;
;
; CLOSE OPEN FILES
; ENTRY:  BC      - ADDRESS OF CLOSE ROUTINE
;         HL      - CODE STRING POINTER
;
FILCLO:	PUSH	BC		;PUSH CLOSE ROUTINE ADDRESS
	LD	A,(HL)		;GET BYTE FROM PROGRAM
	CP	'#'		;TEST IF FILE DESIGNATOR
	CALL	Z,PARSER	;THEN SKIP PAST IT
	CALL	BYTGET		;EVALUATE EXPRESSION < 256
	EX	(SP),HL		;SAVE CODE STRING ADDRESS
	PUSH	HL		;SAVE CLOSE ROUTINE ADDRESS
	LD	DE,CLOFIL	;LOAD RETURN ADDRESS
	PUSH	DE		;PUSH IT ON THE STACK
	JP	(HL)		;THEN JUMP TO CLOSE ROUTINE
;
;
; LINK - CALLED FROM 'NEW' AND 'CLEAR' ALLOWING FILE CLOSE
;
CLOLNK:	PUSH	DE		;SAVE DE REGISTER
	PUSH	BC		;SAVE BC REGISTER
	XOR	A		;ZERO ACCUMULATOR
	CALL	CLOCMD		;CLOSE BASIC PROGRAM FILE
	POP	BC		;RECOVER BC REGISTER
	POP	DE		;RECOVER DE REGISTER
	XOR	A		;ZERO ACCUMULATOR, CLEAR CF
	RET
;
;
; FIELD - ORGANIZE A RANDOM FILE-BUFFER INTO FIELDS
;
FLDCMD:	CALL	GETBNF		;GET POINTER TO FILE BUFFER
	JP	Z,BNEROR		;BAD FILE NUMBER IF CLOSED
	SUB	3		;TEST IF RANDOM FILE
	JP	NZ,BMEROR	;BAD FILE MODE IF NOT
	EX	DE,HL		;SAVE CODE STRING POINTER
	LD	HL,11		;INDEX TO RECORD SIZE
	ADD	HL,BC		;GET ADDRESS OF SIZE BYTE
	LD	A,(HL)		;GET RECORD SIZE TO A
	LD	(RECSIZ),A	;SAVE THE SIZE BYTE
	XOR	A		;ZERO ACCUMULATOR
	EX	DE,HL		;GET CODE STRING POINTER BACK
	LD	DE,34		;INDEX TO START OF DATA BUFFER
FLDCLP:	EX	DE,HL		;GET DATA BUFFER INDEX TO HL
	ADD	HL,BC		;INDEX INTO DATA BUFFER
	LD	B,A		;GET PREVIOUS FIELD SIZE TO B
	EX	DE,HL		;GET CODE STRING POINTER
	LD	A,(HL)		;GET DATA FROM BASIC LINE
	CP	','		;TEST IF COMMA
	RET	NZ		;DONE IF IT ISN'T
	PUSH	DE		;SAVE DATA BUFFER INDEX
	PUSH	BC		;SAVE FILE BUFFER POINTER
	CALL	GETBYT		;EVALUATE EXPRESSION < 256
	PUSH	AF		;SAVE RESULT ON STACK
	RST	TSTNXT		;NEXT CHARACTER
	 Db	'A'		; MUST BE AN 'A'
	RST	TSTNXT		;NEXT CHARACTER
	 Db	'S'		; MUST BE AN 'S'
	CALL	FNDVAR		;FIND/CREATE A VARIABLE
	CALL	TSTSTR		;TEST IF DATA TYPE IS A STRING
	POP	AF		;RECOVER SAVED VALUE
	POP	BC		;RECOVER FILE BUFFER POINTER
	EX	(SP),HL		;GET FILE BUFFER INDEX
	LD	C,A		;GET FIELD SIZE TO C
	ADD	A,B		;ADD TO TOTAL FIELD SUM
	JP	NC,FLDCOK	;SKIP IF IT FITS INTO BUFFER
	JP	NZ,FLEROR	;ELSE FIELD OVERFLOW
FLDCOK:	LD	B,A		;GET TOTAL SIZE TO B
	LD	A,(RECSIZ)	;RECOVER RECORD SIZE BYTE
	CP	B		;TEST IF WITHIN RECORD
	JR	NC,FLDCST	;SKIP IF IT IS
	OR	A		;TEST IF LRL NOT 0
	JP	NZ,FLEROR	;FIELD OVERFLOW IF NOT
FLDCST:	LD	A,B		;GET TOTAL SIZE TO A
	OR	A		;TEST IF TOTAL SIZE IS ZERO
	EX	DE,HL		;GET DATA BUFFER INDEX TO HL
	LD	(HL),C		;STORE FIELD SIZE IN BUFFER
	INC	HL		;BUMP BUFFER POINTER
	LD	(HL),E		;STORE BUFFER FIELD INDEX LSB
	INC	HL		;BUMP POINTER
	LD	(HL),D		;STORE BUFFER FIELD INDEX MSB
	LD	B,0		;ZERO B REGISTER
	POP	HL		;RECOVER CODE STRING POINTER
	JP	NZ,FLDCLP	;LOOP BACK TOTAL SIZE NOT ZERO
	LD	A,C		;GET FIELD SIZE TO A
	OR	A		;TEST IF ZERO
	RET	NZ		;RETURN IF IT ISN'T
	JP	FLDCLP		;ELSE GO GET NEXT FIELD
;
;
; 'RSET' - RIGHT JUSTIFY A STRING IN RANDOM BUFFER FIELD
;
RSECMD:	Db	0F6H		;SHOW RSET WANTED (OR 0AFH)
;
;
; 'LSET' - LEFT JUSTIFY A STRING IN RANDOM BUFFER FIELD
;
LSECMD:	SCF			;SHOW LSET WANTED
	PUSH	AF		;SAVE LSET/RSET FLAG
	CALL	FNDVAR		;FIND/CREATE A VARIABLE
	CALL	TSTSTR		;TEST IF DATA TYPE IS A STRING
	PUSH	DE		;SAVE ADDRESS OF VARIABLE
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	EQUTOK		; BE EQUALS TOKEN
	CALL	FRMEV2		;EVALUATE EXPRESSION
	POP	BC		;RECOVER VARIABLE POINTER
	EX	(SP),HL		;GET OTHER STRING POINTER
	PUSH	HL		;SAVE POINTER AGAIN
	PUSH	BC		;SAVE STRING POINTER
	CALL	TSTDIS		;GET POINTER TO STRING
	LD	B,(HL)		;GET STRING LENGTH TO B
	EX	(SP),HL		;GET STRING POINTER TO HL
	LD	A,(HL)		;GET STRING LENGTH TO A
	LD	C,A		;SAVE STRING LENGTH IN C
	PUSH	BC		;SAVE STRING LENGTHS
	PUSH	HL		;SAVE STRING POINTER
	PUSH	AF		;SAVE STRING LENGTH
	INC	HL		;BUMP STRING POINTER
	LD	E,(HL)		;GET LSB OF STRING ADDRESS
	INC	HL		;BUMP TO MSB
	LD	D,(HL)		;GET MSB OF STRING ADDRESS
	OR	A		;TEST IF EMPTY STRING
	JP	Z,LRSEAB	;THEN JUST EXIT
	LD	HL,(TXTTAB)	;GET START OF PROGRAM STORAGE
	RST	CPHLDE		;TEST IF STRING IN STRING SPACE
	JP	NC,LRSEIS	;SKIP IF IT IS
	LD	HL,(VARTAB)	;GET ADDR OF SIMPLE VARIABLES
	RST	CPHLDE		;TEST IF IN VARIABLE SPACE
	JP	C,LRSEIS	;SKIP IF IT IS
	LD	E,C		;GET STRING LENGTH TO E
	LD	D,0		;STRING LENGTH IS IN DE
	LD	HL,(STRSPC)	;GET LSPT POINTER
	ADD	HL,DE		;GET POINTER TO END OF STRING
	EX	DE,HL		;SAVE POINTER IN DE
	LD	HL,(STRPTR)	;GET STRING STORAGE POINTER
	CALL	COMPAR		;TEST IF STRING IN STRING SPACE
	JP	C,MAKSTR	;SKIP IF IT ISN'T
LRSENX:	POP	AF		;GET STRING LENGTH BACK
	LD	A,C		;GET SIZE TO A
	CALL	ALLOCS		;TEST FREE MEMORY, SET POINTER
	POP	HL		;GET STRING POINTER
	POP	BC		;GET OTHER STRING POINTER
	EX	(SP),HL		;SAVE POINTER, GET VARIABLE PTR
	PUSH	DE		;SAVE STRING END POINTER
	PUSH	BC		;SAVE STRING POINTER
	CALL	TSTDIS		;GET POINTER TO STRING
	POP	BC		;RECOVER STRING POINTER
	POP	DE		;RECOVER STRING END POINTER
	EX	(SP),HL		;SAVE POINTER TO SECOND STRING
	PUSH	BC		;SAVE STRING POINTER
	PUSH	HL		;SAVE STRING POINTER
	INC	HL		;BUMP POINTER TO ADDRESS
	LD	(HL),E		;STORE LSB OF ADDRESS
	INC	HL		;BUMP TO MSB
	LD	(HL),D		;STORE MSB OF ADDRESS
	PUSH	AF		;SAVE STRING LENGTH
LRSEIS:	POP	AF		;RECOVER STRING LENGTH
	POP	HL		;RECOVER STRING DESCRIPTOR PTR
	INC	HL		;BUMP TO ADDRESS
	LD	E,(HL)		;GET LSB OF ADDRESS
	INC	HL		;BUMP TO MSB
	LD	D,(HL)		;GET MSB OF ADDRESS
	POP	BC		;RECOVER STRING POINTER
	POP	HL		;RECOVER STRING DESCRIPTOR PTR
	PUSH	DE		;SAVE STRING ADDRESS ON STACK
	INC	HL		;BUMP TO ADDRESS
	LD	E,(HL)		;GET LSB OF SOURCE ADDRESS
	INC	HL		;BUMP TO MSB
	LD	D,(HL)		;GET MSB OF SOURCE ADDRESS
	EX	DE,HL		;MOVE ADDRESS TO HL
	POP	DE		;RECOVER DESTINATION ADDRESS
	LD	A,C		;GET LENGTH OF FIRST STRING
	CP	B		;TEST IF LARGER THAN SECOND
	JP	NC,LRSELA	;SKIP IF IT IS
	LD	B,A		;ELSE MOVE FIRST COUNTER TO B
LRSELA:	SUB	B		;GET REMAINING CHARACTERS
	LD	C,A		;GET COUNTER TO C
	POP	AF		;GET LSET/RSET FLAG
	CALL	NC,BLKSTR	;FILL WITH BLANKS IF LSET
	INC	B		;BUMP COUNTER
LRSELP:	DEC	B		;DECREMENT COUNT
	JP	Z,LRSEXI	;SKIP IF ALL MOVED
	LD	A,(HL)		;GET BYTE FROM SOURCE STRING
	LD	(DE),A		;STORE IN DESTINATION
	INC	HL		;BUMP SOURCE POINTER
	INC	DE		;BUMP DESTINATION POINTER
	JP	LRSELP		;LOOP FOR NEXT BYTE
LRSEAB:	POP	BC		;CLEAN
	POP	BC		; ALL
	POP	BC		;  REDUNDANT
	POP	BC		;   VALUES
	POP	BC		;    FROM STACK
LRSEXI:	CALL	C,BLKSTR	;FILL WITH BLANKS IF RSET
	POP	HL		;RECOVER CODE STRING POINTER
	RET
;
;
; FILL STRING WITH BLANKS
; ENTRY:  DE      - POINTER TO STRING
;         C       - NUMBER OF LOCATIONS TO BLANK
;
BLKSTR:	LD	A,' '		;LOAD A BLANK
	INC	C		;BUMP COUNTER BY ONE
BLKSLP:	DEC	C		;DECREMENT COUNTER
	RET	Z		;RETURN IF ALL DONE
	LD	(DE),A		;STORE BLANK IN STRING
	INC	DE		;BUMP POINTER
	JP	BLKSLP		;LOOP FOR NEXT LOCATION
;
;
; STRING ISN'T IN STRING SPACE SO CREATE IT
;
MAKSTR:	POP	AF		;GET STRING LENGTH
	POP	HL		;GET STRING POINTER
	POP	BC		;GET STRING LENGTHS
	EX	(SP),HL		;GET STRING POINTER TO HL
	EX	DE,HL		;MOVE POINTER TO DE
	JP	NZ,MAKSNZ	;SKIP IF LENGTH ISN'T ZERO
	PUSH	BC		;SAVE STRING LENGTHS
	LD	A,B		;GET STRING LENGTH TO A
	CALL	RSVSPC		;RESERVE SPACE FOR STRING
	CALL	DSCSTK		;PASS STRING TO BASIC
	POP	BC		;RECOVER STRING LENGTHS
MAKSNZ:	EX	(SP),HL		;MOVE POINTER TO STACK
	PUSH	BC		;SAVE LENGTH
	PUSH	HL		;SAVE STRING POINTER
	PUSH	AF		;SAVE STRING LENGTH
	JP	LRSENX		;THEN RE-ENTER ROUTINE
;
;
; 'EOF' - END-OF-FILE DETECTOR
;
EOFCMD:	CALL	GETBFN		;GET POINTER TO FILE BUFFER
	CP	2		;TEST IF OPEN FOR WRITE
	JP	Z,BMEROR		;BAD FILE MODE IF SO
	LD	HL,15		;INDEX TO NUMBER OF RECORDS
	ADD	HL,BC		;GET ADDRESS TO HL
	LD	A,(HL)		;GET MSB OF VALUE
	DEC	HL		;BACKUP TO LSB
	LD	E,(HL)		;GET LSB OF VALUE
	DEC	HL		;BACKUP TO NEXT RECORD NUMBER
	CP	(HL)		;TEST IF AT LAST RECORD
	JR	NZ,EOFCNL	;SKIP IF NOT
	DEC	HL		;BACKUP TO LSB
	LD	A,E		;GET NUMBER OF RECORDS LSB
	CP	(HL)		;TEST IF AT LAST RECORD
	JR	NZ,EOFCNL	;SKIP IF NOT THERE YET
	DEC	HL		;BACKUP
	DEC	HL		; TO EOF ADDRESS
	LD	A,(HL)		;GET EOF ADDRESS TO A
	DEC	HL		;BACKUP TO
	DEC	HL		; INDEX INTO
	DEC	HL		;  RECORD BUFFER
	SUB	(HL)		;TEST IF AT LAST BYTE
EOFCNL:	SUB	1		;SET CARRY FLAG IF EOF
	SBC	A,A		;A=-1 IF EOF, ELSE 0
	JP	PASIGN		;PASS TRUE/FALSE FLAG
;
;
; CLOSE A FILE
; ENTRY:  A       - FILE NUMBER TO CLOSE
;
FILCLS:	CALL	GETBPT		;GET POINTER TO BUFFER
	RET	Z		;RETURN IF FILE IS CLOSED
	CP	1		;TEST IF OPEN FOR INPUT
	JP	Z,FILCNC	;THEN NO NEED TO CLOSE FILE
	PUSH	BC		;SAVE POINTER TO BUFFER
	XOR	A		;ZERO ACCUMULATOR
	LD	(BC),A		;ZERO OPERATION CODE BYTE
	INC	BC		;BUMP TO START
	INC	BC		; OF DEVICE CONTROL BLOCK
	LD	D,B		;MOVE POINTER
	LD	E,C		; INTO DE REGISTER
	CALL	CLSFIL		;CLOSE THE FILE
	JP	NZ,DERHAN	;ABORT IF CLOSE FAILED
	POP	BC		;RECOVER FILE BUFFER POINTER
FILCNC:	LD	D,34		;COUNT OF LOCATIONS TO CLEAR
	XOR	A		;ZERO ACCUMULATOR
FILCLP:	LD	(BC),A		;CLEAR ONE LOCATION
	INC	BC		;BUMP BUFFER POINTER
	DEC	D		;DECREMENT COUNTER
	JP	NZ,FILCLP	;CLEAR FILE INFO AND DCB FIELDS
	RET
;
;
; 'LOC' - GET CURRENT RECORD NUMBER (CRIPPLED)
;
	If PATCHG		;PATCHES ARE ACTIVE
;
LOCCMD:	 CALL	GETBFN		;GET POINTER TO FILE BUFFER
;
	Else			;ORIGINAL
;
LOCCMD:	 CALL	BMEROR		;REPORT BAD FILE MODE
;
	EndIf			;ALL DONE
;
	JP	Z,BNEROR	;BAD FILE NUMBER
	LD	HL,12		;INDEX TO CURRENT RECORD FIELD
;
;
; GET INTEGER VALUE FROM FILE BUFFER AND PASS IT TO BASIC
; ENTRY:  HL     - INDEX INTO BUFFER TO FIELD
;         BC     - POINTER TO START OF BUFFER
;
FILINT:	ADD	HL,BC		;POINT TO CORRECT FIELD
	LD	E,(HL)		;GET LSB OF VALUE TO E
	INC	HL		;BUMP TO MSB
	LD	D,(HL)		;GET MSB OF VALUE TO D
	EX	DE,HL		;MOVE INTEGER TO HL
	JP	STOINT		;STORE INTEGER IN 'PRIACC'
;
;
; 'LOF' - GET END-OF-FILE RECORD NUMBER
;
LOFCMD:	CALL	GETBFN		;GET POINTER TO FILE BUFFER
	JP	Z,BNEROR	;BAD FILE NUMBER IF CLOSED
	LD	HL,14		;INDEX TO FILE SIZE FIELD
	JP	FILINT		;READ VALUE AND PASS TO BASIC
	POP	HL		;REDUNDANT POP
;
;
; OUTPUT A BYTE TO AN OPENED FILE
; ENTRY:  A       - BYTE TO OUTPUT
;
OUTBYT:	PUSH	HL		;SAVE CODE STRING POINTER
	PUSH	AF		;SAVE THE BYTE ON STACK
	LD	HL,(FIOPTR)	;GET FILE I/O POINTER
	LD	A,(HL)		;GET FILE ACCESS CODE
	CP	1		;TEST IF INPUTTING
	JP	Z,POPTWO	;THEN CLEAR STACK AND RETURN
	POP	AF		;RECOVER OUTPUT BYTE
	PUSH	DE		;SAVE DE REGISTER
	PUSH	BC		;SAVE BC REGISTER
	INC	HL		;BUMP FILE BUFFER POINTER
	LD	B,0		;LOAD LOGICAL RECORD LENGTH
	PUSH	AF		;SAVE OUTPUT BYTE AGAIN
	LD	D,(HL)		;GET BUFFER INDEX TO D
	CP	CR		;TEST IF CARRIAGE RETURN
	LD	(HL),B		;ZERO BUFFER INDEX
	JR	Z,OUTBCR	;SKIP IF CARRIAGE RETURN
	ADD	A,256-32	;SET CARRY IF PAST BUFFER END
	LD	A,D		;GET BUFFER INDEX TO A
	ADC	A,B		;ADD EVENTUAL CARRY
	LD	(HL),A		;SET NEW BUFFER INDEX
OUTBCR:	INC	HL		;BUMP TO FILE DCB
	EX	DE,HL		;GET DCB POINTER TO DE
	POP	AF		;RECOVER BYTE TO WRITE
	PUSH	AF		;SAVE BYTE AGAIN
	PUSH	DE		;SAVE DCB ADDRESS
	CALL	BYTOUT		;OUTPUT BYTE TO FILE
	POP	DE		;RECOVER DCB ADDRESS
	JP	NZ,OUTBER	;SKIP IF ERROR WRITING BYTE
OUTBEX:	POP	AF		;ELSE RECOVER BYTE
	POP	BC		;RECOVER BC REGISTER
	POP	DE		;RECOVER DE REGISTER
	POP	HL		;RECOVER CODE STRING POINTER
	RET			;THEN RETURN TO CALLER
OUTBER:	LD	C,A		;SAVE ERROR CODE IN C
	LD	A,(DE)		;GET FILE OPEN FLAG
	OR	A		;TEST IF FILE IS OPEN
	LD	A,C		;RECOVER ERROR CODE
	JP	M,DERHAN	;ABORT IF FILE IS OPEN
	JP	OUTBEX		;ELSE SUCCESSFUL WRITE
;
;
; 'PUT' - WRITE A RECORD TO DISK USING RANDOM ACCESS
;
PUTCMD:	Db	0F6H		;FLAG PUT (OR INSTRUCTION)
;
;
; 'GET' - READ A RECORD FROM DISK USING RANDOM ACCESS
;
GETCMD:	XOR	A		;FLAG GET (ZERO)
	LD	(PGFLAG),A	;SAVE PUT/GET FLAG
	CALL	GETBNF		;GET POINTER TO FILE BUFFER
	CP	3		;TEST IF RANDOM FILE BUFFER
	JP	NZ,BMEROR	;BAD FILE MODE IF NOT
	PUSH	BC		;SAVE FILE BUFFER POINTER
	PUSH	HL		;SAVE CODE STRING POINTER
	LD	HL,12		;LOAD INDEX TO CURRENT RECORD
	ADD	HL,BC		;GET POINTER TO ADDRESS
	LD	E,(HL)		;GET LSB OF RECORD NUMBER
	INC	HL		;BUMP TO MSB
	LD	D,(HL)		;GET MSB OF RECORD NUMBER
	INC	DE		;BUMP CURRENT RECORD NUMBER
	POP	HL		;RECOVER CODE STRING POINTER
	LD	A,(HL)		;GET BYTE FROM BASIC LINE
	CP	','		;TEST IF RECORD SPECIFIED
	CALL	Z,INTEVL	;THEN GET RECORD NUMBER
	DEC	HL		;BACKUP CODE STRING POINTER
	RST	CHRGET		;TEST IF END OF LINE
	JP	NZ,SNEROR	;SYNTAX ERROR IF NOT
	EX	(SP),HL		;GET FILE BUFFER POINTER
	PUSH	HL		;SAVE IT AGAIN
	LD	A,E		;GET LSB OF RECORD NUMBER
	OR	D		;TEST IF RECORD ZERO
	JP	Z,RBEROR		;THEN BAD RECORD NUMBER
	DEC	DE		;ZERO BASE RECORD NUMBER
	LD	B,D		;GET RECORD
	LD	C,E		; NUMBER TO BC
	EX	DE,HL		;GET FILE BUFFER POINTER TO DE
	INC	DE		;BUMP TO
	INC	DE		; START OF NAME FIELD
	LD	HL,32		;LOAD INDEX TO DATA FIELD
	ADD	HL,DE		;GET ADDRESS OF DATA FIELD
	PUSH	HL		;SAVE POINTER TO DATA FIELD
	CALL	POSREC		;POSITION TO SPECIFIED RECORD
	POP	HL		;RECOVER POINTER TO DATA FIELD
	JR	Z,GETCOK	;SKIP IF POSITIONING SUCCEEDED
	CP	28		;TEST IF NORMAL END OF FILE
	JR	Z,GETCLR	;THEN PROCESS LAST RECORD
	CP	29		;TEST IF ON LAST RECORD
	JP	NZ,DERHAN	;ABORT IF PAST END OF FILE
GETCLR:	LD	A,(PGFLAG)	;GET PUT/GET FLAG
	OR	A		;TEST IF GET IN PROGRESS
	JR	Z,GETCRR	;THEN SKIP PUT CODE
GETCWR:	CALL	WRTREC		;WRITE RECORD TO FILE
	JP	NZ,DERHAN	;ABORT IF WRITE ERROR
	POP	AF		;REMOVE FILE BUFFER POINTER
	POP	HL		;RECOVER CODE STRING POINTER
	RET			;THEN RETURN TO CALLER
GETCOK:	LD	A,(PGFLAG)	;GET PUT/GET FLAG
	OR	A		;TEST IF PUT IN PROGRESS
	JR	NZ,GETCWR	;THEN SKIP GET CODE
	CALL	REDREC		;READ RECORD FROM FILE
	JP	NZ,DERHAN	;ABORT IF ERROR
	POP	BC		;REMOVE FILE BUFFER POINTER
	POP	HL		;RECOVER CODE STRING POINTER
	RET			;THEN RETURN TO CALLER
GETCRR:	POP	HL		;RECOVER FILE BUFFER POINTER
	LD	DE,34		;INDEX TO START OF DATA FIELD
	ADD	HL,DE		;HL HAS ADDRESS OF DATA
	LD	B,0		;ZERO COUNTER (256 BYTES)
	XOR	A		;ZERO ACCUMULATOR
GETCZB:	LD	(HL),A		;ZERO ONE BUFFER LOCATION
	INC	HL		;BUMP BUFFER POINTER
	DJNZ	GETCZB		;COMPLETLY CLEAR THE BUFFER
	POP	HL		;RECOVER CODE STRING POINTER
	RET
;
;
; GET A BYTE FROM AN OPENED FILE
; EXIT:   A       - BYTE JUST READ
;         CF      - SET IF END OF FILE
;
INPBYT:	PUSH	BC		;SAVE BC REGISTER
	PUSH	HL		;SAVE HL REGISTER
	LD	HL,(FIOPTR)	;GET FILE I/O POINTER
	PUSH	DE		;SAVE DE REGISTER
	EX	DE,HL		;GET FILE I/O POINTER TO DE
	INC	DE		;POINT TO START
	INC	DE		; OF DEVICE CONTROL BLOCK
INPBLP:	PUSH	DE		;SAVE DCB ADDRESS
	CALL	BYTINP		;INPUT BYTE FROM FILE
	POP	DE		;RECOVER DCB ADDRESS
	PUSH	AF		;SAVE BYTE JUST READ
	LD	A,(DE)		;GET FILE OPEN FLAG
	OR	A		;TEST IF FILE IS OPEN
	JP	P,INPBCL	;SKIP IF FILE IS CLOSED
	POP	AF		;RECOVER BYTE JUST READ
	JR	Z,INPBEX	;SKIP IF NO ERRORS
	CP	28		;TEST IF NORMAL END OF FILE
	JP	NZ,DERHAN	;ABORT IF READ ERROR
	SCF			;ELSE SHOW END OF FILE
	Db	06H		;SKIP NEXT INSTRUCTION
INPBEX:	OR	A		;SHOW NOT END OF FILE
	POP	DE		;RECOVER DE REGISTER
	POP	HL		;RECOVER HL REGISTER
	POP	BC		;RECOVER BC REGISTER
	RET			;THEN RETURN TO CALLER
INPBCL:	POP	AF		;RECOVER FLAGS AND BYTE
	JR	Z,INPBLP	;LOOP BACK IF NO ERRORS
	JP	INPBEX		;RETURN SUCCESS TO CALLER
;
;
; GET FILESPEC FROM BASIC LINE INTO FILE BUFFER
; ENTRY:  BC      - POINTER TO FILE BUFFER
;         HL      - CODE POINTER
;
GETFSP:	PUSH	BC		;SAVE BUFFER POINTER
	CALL	FRMEV2		;EVALUATE EXPRESSION
	PUSH	HL		;SAVE CODE STRING POINTER
	CALL	TSTDIS		;GET POINTER TO STRING
	LD	A,(HL)		;GET STRING LENGTH TO A
	OR	A		;TEST IF EMPTY STRING
	JP	Z,NMEROR		;THEN BAD FILE NAME
	CP	23		;TEST IF NAME TOO LONG
	JP	NC,NMEROR	;THEN BAD FILE NAME
	INC	HL		;BUMP TO STRING ADDRESS
	LD	C,(HL)		;GET LSB OF ADDRESS TO C
	INC	HL		;BUMP TO MSB
	LD	B,(HL)		;GET MSB OF ADDRESS TO B
	LD	HL,NAMBUF	;POINT TO FILENAME BUFFER
	LD	E,A		;GET CHARACTER COUNT TO E
GETFUC:	LD	A,(BC)		;GET CHARACTER FROM STRING
	CP	'a'		;TEST IF LOWER CASE
	JP	C,GETFNL	;SKIP IF IT ISM'T
	CP	'z'+1		;TEST IF STILL LOWER CASE
	JP	NC,GETFNL	;SKIP IF IT ISN'T
	XOR	00100000B	;ELSE CONVERT TO UPPER CASE
GETFNL:	LD	(HL),A		;STORE FILENAME CHARACTER
	INC	HL		;BUMP DCB POINTER
	INC	BC		;BUMP STRING POINTER
	DEC	E		;DECREMENT NAME CHARACTER COUNT
	JP	NZ,GETFUC	;LOOP IF MORE CHARACTERS
	LD	(HL),E		;TERMINATE THE STRING
	POP	HL		;GET CODE POINTER BACK
	POP	DE		;RECOVER BUFFER POINTER
	LD	B,D		;GET BUFFER
	LD	C,E		; POINTER INTO BC
	PUSH	BC		;SAVE BUFFER POINTER ON STACK
	PUSH	HL		;SAVE CODE STRING POINTER
	LD	HL,NAMBUF	;POINT TO NAME BUFFER
	INC	DE		;BUMP TO START
	INC	DE		; OF NAME FIELD
	CALL	VALNAM		;GET FILENAME INTO NAME FIELD
	JP	NZ,NMEROR	;ABORT IF INVALID NAME
	OR	A		;TEST IF MORE THAN ONE
	JP	NZ,NMEROR	;ABORT IF MULTIPLE NAMES
	POP	HL		;RECOVER CODE POINTER
	POP	BC		;RECOVER FILE BUFFER POINTER
	RET
;
;
; 'OPEN' - OPEN A FILE FOR SEQUENTIAL OR RANDOM ACCESS
;
OPNCMD:	LD	BC,DFLOUT	;POINT TO ERROR CLEANUP CODE
	PUSH	BC		;SET IT AS RETURN ADDRESS
	CALL	FRMEV2		;EVALUATE EXPRESSION
	PUSH	HL		;SAVE CODE POINTER
	CALL	TSTDIS		;GET POINTER TO STRING
	LD	A,(HL)		;GET STRING LENGTH
	OR	A		;TEST IF EMPTY STRING
	JP	Z,BMEROR		;THEN BAD FILE MODE
	INC	HL		;BUMP TO STRING ADDRESS
	LD	C,(HL)		;GET LSB OF ADDRESS
	INC	HL		;BUMP TO MSB
	LD	B,(HL)		;GET MSB OF ADDRESS
	LD	A,(BC)		;GET CHARACTER FROM STRING
	AND	11011111B	;MASK TO UPPER CASE
	LD	D,2		;ASSUME OPEN FOR OUTPUT
	CP	'O'		;TEST IF OUTPUT WANTED
	JP	Z,OPNCGM	;THEN GO DO THE FILE I/O
	LD	D,1		;ASSUME OPEN FOR INPUT
	CP	'I'		;TEST IF INPUT WANTED
	JP	Z,OPNCGM	;THEN GO DO THE FILE I/O
	LD	D,3		;ASSUME OPEN RANDOM
	CP	'R'		;TEST IF RANDOM ACCESS
	JP	NZ,BMEROR	;BAD FILE MODE IF NOT
OPNCGM:	POP	HL		;RECOVER CODE POINTER
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	','		; BE A COMMA
	PUSH	DE		;SAVE FILE ACCESS CODE
	CP	'#'		;TEST IF POUND SIGN
	CALL	Z,PARSER	;THEN SKIP PAST THE SIGN
	CALL	BYTGET		;EVALUATE EXPRESSION < 256
	RST	TSTNXT		;NEXT BYTE MUST
	 Db	','		; BE A COMMA
	LD	A,E		;GET FILE NUMBER TO A
	OR	A		;TEST IF FILE NUMBER ZERO
	JP	Z,BNEROR		;BAD FILE NUMBER IF SO
	Db	0FEH		;SKIP FOLLOWING PUSH
;
;
; OPEN A FILE FOR SEQUENTIAL OR RANDOM ACCESS
; ENTRY:  D       - 1 IF INPUT, 2 IF OUTPUT, 3 IF RANDOM
;         A       - FILE BUFFER NUMBER TO OPEN
;
FILOPN:	PUSH	DE		;SAVE FILE ACCESS CODE
	CALL	GETBPT		;GET POINTER TO BUFFER
	JP	NZ,OFEROR	;ABORT IF FILE ALREADY OPEN
	PUSH	BC		;SAVE FILE BUFFER POINTER
	CALL	GETFSP		;GET FILESPEC TO NAME FIELD
	LD	B,0		;LOGICAL RECORD LENGTH IS 0
	POP	DE		;RECOVER FILE BUFFER POINTER
	POP	AF		;GET FILE ACCESS CODE
	PUSH	AF		;RESAVE THE ACCESS CODE
	PUSH	DE		;RESAVE FILE BUFFER POINTER
	CP	3		;TEST IF RANDOM ACCESS
	JR	NZ,FILONR	;SKIP IF NOT
	DEC	HL		;BACKUP CODE POINTER
	RST	CHRGET		;TEST IF END OF LINE
	JR	Z,FILONR	;SKIP IF IT IS
	RST	TSTNXT		;ELSE NEXT BYTE
	Db	','		; MUST BE A COMMA
	CALL	BYTGET		;EVALUATE EXPRESSION < 256
	LD	B,E		;GET LOGICAL RECORD LENGTH
FILONR:	LD	(CHPSAV),HL	;SAVE CODE STRING POINTER
	POP	HL		;RECOVER FILE BUFFER POINTER
	LD	A,(SYSCON)	;GET SYSTEM CONDITION FLAGS
	AND	11111001B	;CLR RUN ACTIVE AND PROT FLAGS
	LD	C,A		;SAVE FLAGS IN C
	LD	A,(EXECFL)	;GET RUN FLAG
	OR	A		;TEST IF RUNNING PROGRAM
	LD	A,C		;RESTORE FLAGS TO A
	JR	Z,FILOLO	;SKIP IF NOT RUNNING
	OR	00000100B	;ELSE SET RUN ACTIVE FLAG
FILOLO:	LD	(SYSCON),A	;RESAVE SYSTEM CONDITION FLAGS
	POP	AF		;RECOVER FILE ACCESS CODE
	PUSH	AF		;RESAVE ACCESS CODE
	PUSH	HL		;SAVE FILE BUFFER POINTER
	LD	(FIOPTR),HL	;SET FILE I/O POINTER
	EX	DE,HL		;GET POINTER TO DE
	INC	DE		;BUMP TO
	INC	DE		; START OF FILESPEC
	LD	HL,32		;INDEX TO START OF DATA FIELD
	ADD	HL,DE		;GET DATA FIELD ADDRESS TO HL
	LD	C,A		;GET FILE ACCESS CODE TO C
	LD	A,B		;GET LOGICAL RECORD LENGTH
	OR	A		;TEST IF LENGTH IS ZERO
	JR	Z,FILOLZ	;SKIP IF LENGTH IS ZERO
	LD	A,(0)		;GET BYTE FROM ROM START (???)
	OR	A		;TEST IF ZERO (???)
	JP	Z,BMEROR	;BAD FILE MODE IF ZERO (???)
	INC	H		;ELSE ADD 256 TO BUFFER PTR
FILOLZ:	LD	A,C		;GET FILE ACCESS CODE TO A
	CP	1		;TEST IF INPUTTING
	JR	Z,FILOIN	;THEN SKIP FORWARDS
	CALL	CREFIL		;INIT THE FILE
	JR	FILOSR		;THEN SKIP READ CODE
FILOIN:	CALL	OPNFIL		;OPEN EXISTING FILE
	PUSH	AF		;SAVE RESULT OF OPEN
	LD	A,(EXECFL)	;GET RUN FLAG
	OR	A		;TEST IF RUNNING
	JR	Z,FILONX	;SKIP IF NOT RUNNING
	XOR	A		;ZERO ACCUMULATOR
	LD	(EXECFL),A	;CLEAR RUN FLAG
	LD	A,(SYSCON)	;GET SYSTEM CONDITION FLAGS
	RRA			;SHIFT BASIC PROGRAM
	RRA			; PROTECTION BIT INTO CARRY
	SBC	A,A		;A=0FFH IF PROTECTED
	LD	(PROTFL),A	;(DE)ACTIVATE PROTECTION
FILONX:	POP	AF		;RECOVER OPEN FLAGS
FILOSR:	JP	NZ,DERHAN	;ABORT IF OPEN FAILURE
	POP	HL		;RECOVER FILE BUFFER POINTER
	POP	AF		;RECOVER FILE ACCESS CODE
	LD	(HL),A		;STORE ACCESS CODE IN BUFFER
	INC	HL		;BUMP BUFFER POINTER
	LD	(HL),0		;ZERO FILE BUFFER INDEX
	LD	HL,(CHPSAV)	;RECOVER CODE STRING POINTER
	RET
;
;
; TEST IF FILE IS PROTECTED - CLEAR MEMORY IF IT IS
;
TSTPRO:	PUSH	AF		;SAVE ACCUMULATOR AND FLAGS
	XOR	A		;ZERO ACCUMULATOR
	LD	(EXECFL),A	;CLEAR RUN FLAG
	LD	A,(PROTFL)	;GET PROTECTION FLAG
	OR	A		;TEST IF PROTECTION ACTIVE
	JP	Z,NOPROT	;WE ARE ALL DONE IF NOT
	LD	HL,(TXTTAB)	;GET START OF BASIC PROGRAM
	LD	BC,1100		;NUMBER OF BYTES TO CLEAR
TPCLRM:	LD	(HL),0		;ZERO A MEMORY BYTE
	INC	HL		;BUMP MEMORY POINTER
	DEC	BC		;DECREMENT COUNTER
	LD	A,B		;GET MSB OF COUNT TO A
	OR	C		;TEST IF ALL IS CLEARED
	JP	NZ,TPCLRM	;LOOP BACK IF IT ISN'T
	LD	(PROTFL),A	;CLEAR PROTECTION FLAG
	CALL	RESPTR		;ISSUE 'NEW' COMMAND
	LD	HL,MCLMSG	;LOAD START OF MESSAGE
	CALL	MSGPRT		;SHOW MEMORY HAS BEEN CLEARED
	JP	WARMST		;ENTER BASIC'S IMMEDIATE MODE
NOPROT:	POP	AF		;RECOVER ACCUMULATOR AND FLAGS
	RET
;
;
; MISCELLANEOUS STORAGE LOCATIONS AND FLAGS
;
RECSIZ	Db	0		;RECORD SIZE STORAGE
EXECFL	Db	0		;RUN FLAG (RUN=0FFH)
PROTFL	Db	0		;PROTECTION ACTIVE FLAG
;
;
; 'KILL' - DELETE A PROGRAM FROM DISK
;
KILCMD:	XOR	A		;USE FILE BUFFER ZERO
	CALL	GETBPT		;GET POINTER TO BUFFER
	CALL	GETFSP		;GET FILENAME INTO NAME FIELD
	PUSH	HL		;SAVE CODE STRING POINTER
	LD	HL,(BUFZPT)	;GET POINTER TO BUFFER 0
	EX	DE,HL		;GET POINTER TO DE
	INC	DE		;BUMP TO START
	INC	DE		; OF FILESPEC FIELD
	LD	B,0		;LOAD LOGICAL RECORD LENGTH
	CALL	OPNFIL		;OPEN EXISTING FILE
	JP	NZ,DERHAN	;ABORT IF NO SUCH FILE
	CALL	KILFIL		;KILL THE FILE
	JP	NZ,DERHAN	;ABORT IF KILL FAILED
	LD	HL,(BUFZPT)	;GET BUFFER POINTER TO HL
	LD	(HL),0		;SHOW BUFFER AS EMPTY
	POP	HL		;RECOVER CODE STRING POINTER
	RET
;
;
; 'NAME' - RENUMBER A BASIC PROGRAM
;
NAMCMD:	CALL	CLEARV		;EXECUTE 'CLEAR'
	LD	BC,XQLOOP	;GET ADDRESS OF RUN ROUTINE
	DEC	HL		;RECOVER CODE STRING POINTER
	RST	CHRGET		;GET BYTE FROM BASIC LINE
	PUSH	BC		;RUN ROUTINE ADDRESS ON STACK
	LD	BC,10		;ASSUME FIRST NEW LINE IS 10
	PUSH	BC		;SAVE IT ON THE STACK
	LD	D,B		;ASSUME STARTING
	LD	E,B		; LINE IS ZERO
	JR	Z,DFLALL	;START IF NO PARAMETERS
	CP	','		;TEST IF COMMA
	JR	Z,DFLFIR	;THEN NO FIRST NUMBER
	PUSH	DE		;SAVE STARTING LINE NUMBER
	CALL	EVALCO		;GET FIRST LINE NUMBER
	LD	B,D		;MOVE FIRST
	LD	C,E		; NUMBER TO BC
	POP	DE		;RECOVER STARTING LINE NUMBER
	JR	Z,DFLALL	;SKIP IF END OF LINE
DFLFIR:	RST	TSTNXT		;NEXT BYTE
	 Db	','		; MUST BE A COMMA
	CALL	EVALCO		;ASCII TO BINARY
	JR	Z,DFLALL	;SKIP IF END OF LINE
	POP	AF		;RECOVER DEFAULT INCREMENT
	RST	TSTNXT		;NEXT BYTE
	 Db	','		; MUST BE A COMMA
	PUSH	DE		;SAVE STARTING LINE
	CALL	EVALIN		;CONVERT ASCII TO BINARY
	JP	NZ,SNEROR	;ERROR IF NOT END OF LINE
	LD	A,D		;GET INCREMENT MSB TO A
	OR	E		;TEST IF INCREMENT ZERO
	JP	Z,FCEROR	;THEN ILLEGAL FUNCTION CALL
	EX	DE,HL		;MOVE INCREMENT TO HL
	EX	(SP),HL		;STACK INCREMENT, GET START LINE
	EX	DE,HL		;MOVE START LINE TO DE
DFLALL:	PUSH	BC		;SAVE FIRST NEW LINE NUMBER
	EX	DE,HL		;MOVE START LINE TO HL
	LD	(BEGLIN),HL	;SAVE STARTING LINE NUMBER
	EX	DE,HL		;MOVE STARTING LINE TO DE
	CALL	FINDLN		;SEARCH FOR BASIC LINE
	POP	DE		;GET FIRST NEW LINE NUMBER
	PUSH	DE		;SAVE IT AGAIN
	PUSH	BC		;SAVE ADDRESS OF LINE
	CALL	FINDLN		;SEARCH FOR BASIC LINE
	LD	H,B		;GET LINE
	LD	L,C		; ADDRESS TO HL
	POP	DE		;RECOVER FIRST NEW LINE NUMBER
	RST	CPHLDE		;TEST IF END GREATER THAN START
	EX	DE,HL		;SWAP START AND END
	JP	C,FCEROR	;ERROR IF END LESS THAN START
	POP	DE		;RECOVER FIRST NEW LINE NUMBER
	POP	BC		;RECOVER LINE ADDRESS
	POP	AF		;REMOVE RETURN ADDRESS
	PUSH	DE		;SAVE FIRST NEW LINE NUMBER
	JR	NXTRSL		;THEN SKIP THE FOLLOWING
NXTRSC:	ADD	HL,BC		;TEST IF END LINE TOO HIGH
	JP	C,FCEROR	;ILLEGAL FUNCTION CALL IF SO
	EX	DE,HL		;FLIP LINK FIELD AND ACCUM
	PUSH	HL		;SAVE LINK FIELD ADDRESS
	LD	HL,65529	;MAX ALLOWABLE LINE NUMBER
	RST	CPHLDE		;TEST IF LINE NUMBER TOO HIGH
	POP	HL		;RECOVER LINK FIELD ADDRESS
	JP	C,FCEROR	;ERROR IF NUMBER TOO HIGH
NXTRSL:	PUSH	DE		;SAVE FIRST NEW LINE NUMBER
	LD	E,(HL)		;GET LINK FIELD ADDRESS LSB
	LD	A,E		;MOVE ADDRESS LSB TO A
	INC	HL		;BUMP TO LINK FIELD MSB
	LD	D,(HL)		;GET LINK FIELD ADDRESS MSB
	OR	D		;TEST IF END OF PROGRAM
	EX	DE,HL		;MOVE LINK FIELD ADDRESS TO HL
	POP	DE		;RECOVER FIRST NEW LINE NUNBER
	JR	Z,RESSDN	;SKIP IF END OF PROGRAM
	LD	A,(HL)		;GET FIRST BYTE OF LINK TO A
	INC	HL		;BUMP TO THE SECOND BYTE
	OR	(HL)		;TEST IF PROGRAM END
	DEC	HL		;BACKUP TO LINE NUMBER
	EX	DE,HL		;SWAP LINK FIELD ADDRESS TO DE
	JR	NZ,NXTRSC	;THEN GO INCREMENT COUNT
RESSDN:	PUSH	BC		;SAVE THE INCREMENT
	CALL	SCNLIN		;SCAN FOR LINE NUMBER TOKENS
	CALL	SCCLIN		;CONVERT LINES TO POINTERS
	LD	HL,(BEGLIN)	;GET STARTING LINE TO HL
	EX	DE,HL		;SWAP THE LINE TO DE
	CALL	FINDLN		;SEARCH FOR BASIC LINE
	LD	H,B		;COPY LINE ADDRESS MSB TO B
	LD	L,C		;COPY LINE ADDRESS LSB TO C
	POP	BC		;RECOVER INCREMENT
	POP	DE		;RECOVER NEW NUMBER
RESNXT:	PUSH	DE		;SAVE CURRENT LINE
	LD	E,(HL)		;GET LINK ADDRESS LSB TO E
	LD	A,E		;COPY ADDRESS BYTE TO A
	INC	HL		;BUMP TO LINK ADDRESS MSB
	LD	D,(HL)		;GET LINK ADDRESS MSB TO D
	OR	D		;TEST IF THE END REACHED
	JR	Z,SCCALL	;STOP RENUMBERING IF END
	EX	DE,HL		;SWAP LINE POINTER, LINK FIELD
	EX	(SP),HL		;SWAP LINK POINTER TO STACK
	EX	DE,HL		;NUMBER IN DE, POINTER IN HL
	INC	HL		;POINT AT LINE NUMBER FIELD
	LD	(HL),E		;CHANGE TO NEW NUMBER LSB
	INC	HL		;BUMP TO LINE NUMBER MSB
	LD	(HL),D		;CHANGE TO NEW NUMBER MSB
	EX	DE,HL		;SWAP LINE NUMBER TO HL
	ADD	HL,BC		;ADD INCREMENT TO NUMBER
	EX	DE,HL		;SWAP LINE NUMBER BACK TO HL
	POP	HL		;RECOVER NEXT LINE POINTER
	JR	RESNXT		;THEN CONTINUE RENUMBERING
SCCALL:	LD	BC,POPWRM	;SET RETURN ADDRESS AT
	PUSH	BC		; EDIT CHECK IF SYNTAX ERROR
	db	0FEH		;SKIP NEXT INSTRUCTION (CP N)
;
;
; THE SUBROUTINES 'SCCLIN' AND 'SCCPTR' CONVERT ALL LINE
; NUMBERS TO POINTERS AND VICE-VERSA. THE ONLY SPECIAL CASE
; IS "ON ERROR GOTO 0" WHERE THE "0" IS LEFT AS A LINE NUMBER
; TOKEN SO IT WONT BE CHANGED BY RESEQUENCE.
;
;
; CONVERT POINTER TO LINE NUMBER
;
SCCLIN:	Db	0F6H		;SKIP NEXT INSTRUCTION (OR N)
;
;
; CONVERT LINE NUMBER TO POINTER
;
SCCPTR:	XOR	A		;ZERO THE ACCUMULATOR
	LD	(PTRFLG),A	;CLEAR OR SET POINTER FLAG
	LD	HL,(TXTTAB)	;GET START OF PROGRAM STORAGE
	DEC	HL		;BACKUP POINTER FOR FOLLOWING
SCNPLN:	INC	HL		;BUMP PROGRAM POINTER
	LD	A,(HL)		;GET LINK ADDRESS LSB
	INC	HL		;BUMP POINTER TO MSB
	OR	(HL)		;TEST IF END OF PROGRAM
	RET	Z		;RETURN IF IT IS
	INC	HL		;BUMP POINTER TO LINE NUMBER
	LD	E,(HL)		;GET LSB OF LINE NUMBER
	INC	HL		;BUMP TO MSB
	LD	D,(HL)		;GET MSB OF LINE NUMBER
SCNEXT:	RST	CHRGET		;GET BYTE FROM BASIC LINE
SCNEXI:	OR	A		;TEST IF END OF LINE
	JR	Z,SCNPLN	;THEN GO DO NEXT LINE
	LD	C,A		;SAVE BYTE FROM LINE IN C
	LD	A,(PTRFLG)	;GET CONVERSION FLAG TO A
	OR	A		;SET FLAGS FOR CONVERSION TYPE
	LD	A,C		;RESTORE BYTE TO A AGAIN
	JP	Z,TONUMB	;SKIP IF POINTER TO NUMBER
	CP	EROTOK		;TEST IF 'ERROR' TOKEN
	JR	NZ,NTERRG	;SKIP IF NOT SO
	RST	CHRGET		;GET BYTE FROM BASIC LINE
	CP	GTOTOK		;TEST IF 'GOTO' TOKEN
	JR	NZ,SCNEXI	;NOT 'ON ERROR GOTO'
	RST	CHRGET		;GET BYTE FROM BASIC LINE
	CP	LINCON		;TEST IF LINE NUMBER CONSTANT
	JR	NZ,SCNEXI	;IGNORE IF IT ISN'T
	PUSH	DE		;SAVE LINE NUMBER ON STACK
	CALL	LINGET		;GET LINE NUMBER INTO DE
	LD	A,D		;GET LINE NUMBER MSB TO A
	OR	E		;TEST IF NUMBER IS ZERO
	JR	NZ,CHGPTR	;THEN CHANGE IT TO POINTER
	PUSH	HL		;SAVE BASIC PROGRAM POINTER
	LD	HL,(LINADR)	;GET POINTER INTO LINE
	DEC	HL		;BACKUP POINTER
	LD	(HL),' '	;STORE A BLANK IN LINE
	DEC	HL		;BACKUP POINTER
	LD	(HL),' '	;STORE A BLANK IN LINE
	DEC	HL		;BACKUP POINTER
	LD	(HL),'0'	;STORE A ZERO IN LINE
	POP	HL		;RECOVER BASIC PROGRAM POINTER
	JR	SCNNLN		;THEN DO NOT CHANGE TO POINTER
NTERRG:	CP	LINCON		;TEST IF LINE NUMBER CONSTANT
	JR	NZ,SCNEXT	;KEEP SCANNING IF NOT
	PUSH	DE		;SAVE NUMBER IN CASE OF ERROR
	CALL	LINGET		;GET CONSTANT LINE NUMBER TO DE
CHGPTR:	PUSH	HL		;SAVE THE CODE STRING POINTER
	CALL	FINDLN		;SEARCH FOR BASIC LINE
	DEC	BC		;BACK TO PREVIOUS TRAILING ZERO
	LD	A,PTRCON	;CHANGE LINE NUMBER TO POINTER
	JP	C,MAKPTR	;CHANGE TO POINTER IF FOUND
	CALL	CRLFDO		;POSITION CURSOR TO NEXT LINE
	LD	HL,UDEFLN	;POINT TO ERROR STRING
	PUSH	DE		;SAVE ERROR LINE NUMBER
	CALL	MSGPRT		;SHOW LINE NUMBER UNDEFINED
	POP	HL		;RECOVER LINE NUMBER
	CALL	NUMPRT		;DISPLAY DECIMAL NUMBER
	POP	BC		;GET STORAGE POINTER TO BC
	CALL	BLANKN		;STORE 5 BLANKS IN LINE
	POP	HL		;RECOVER CURRENT LINE NUMBER
	PUSH	HL		;RE-SAVE THE NUMBER
	PUSH	BC		;RE-SAVE STORAGE POINTER
	CALL	INLINE		;DISPLAY 'IN' AND NUMBER
SCNPOP:	POP	HL		;RECOVER CODE STRING POINTER
SCNNLN:	POP	DE		;RECOVER CURRENT LINE NUMBER
	DEC	HL		;BACKUP CODE STRING POINTER
	JP	SCNEXT		;THEN GO CONTINUE SCANNING
;
;
; ERROR MESSAGE DISPLAYED WHEN UNDEFINED LINE REFERENCED
;
UDEFLN	db	'Undefined line ',0
;
;
; CONVERT LINE POINTER TO LINE NUMBER
;
TONUMB:	CP	PTRCON		;TEST IF LINE POINTER CONSTANT
	JP	NZ,SCNEXT	;JUST KEEP SCANNING IF NOT
	PUSH	DE		;SAVE CURRENT LINE NUMBER
	CALL	LINGET		;GET THE NUMBER
	EX	DE,HL		;SWAP TEXT POINTER AND POINTER
	INC	HL		;BUMP THE POINTER
	INC	HL		;POINT AT LINE
	INC	HL		; NUMBER FIELD
	LD	C,(HL)		;GET LINE NUMBER LSB TO C
	INC	HL		;BUMP TO MSB
	LD	B,(HL)		;GET LINE NUMBER MSB TO B
	EX	DE,HL		;SWAP POINTER AND TEXT POINTER
	LD	H,B		;GET LINE NUMBER
	LD	L,C		; FROM BC INTO HL
	CALL	INTASC		;CONVERT INTEGER TO ASCII
	EX	DE,HL		;GET ASCII POINTER TO DE
	INC	DE		;BUMP PAST SIGN CHARACTER
	LD	HL,(LINADR)	;GET POINTER INTO LINE
	DEC	HL		;BACKUP
	DEC	HL		; LINE
	DEC	HL		;  POINTER
	LD	C,5		;INIT DIGIT COUNTER
STODIG:	LD	A,(DE)		;GET ASCII DIGIT
	OR	A		;TEST IF ALL DIGITS DONE
	JR	Z,BLANKF	;FILL WITH BLANKS IF SO
	LD	(HL),A		;STORE ASCII DIGIT
	INC	HL		;BUMP DESTINATION POINTER
	INC	DE		;BUMP SOURCE POINTER
	DEC	C		;DECREMENT COUNTER
	JR	NZ,STODIG	;LOOP IF MORE DIGITS
CONTSC:	POP	DE		;RECOVER CURRENT LINE NUMBER
	DEC	HL		;BACKUP DESTINATION POINTER
	JP	SCNEXT		;THEN KEEP SCANNING
;
;
; CHANGE LINE NUMBER TO POINTER
;
MAKPTR:	LD	HL,SCNPOP	;LOAD RETURN ADDRESS
	PUSH	HL		;PUSH ADDRESS ON THE STACK
	LD	HL,(LINADR)	;GET POINTER INTO LINE
	PUSH	HL		;SAVE THE POINTER ON STACK
	DEC	HL		;BACKUP LINE POINTER
	LD	(HL),B		;STORE POINTER MSB
	DEC	HL		;BACKUP LINE POINTER
	LD	(HL),C		;STORE POINTER LSB
	DEC	HL		;BACKUP LINE POINTER
	LD	(HL),A		;STORE POINTER CONSTANT
	POP	HL		;RESTORE POINTER INTO LINE
	RET
;
;
; BLANK FILL A NUMBER FIELD
;
BLANKF:	LD	(HL),' '	;STORE A BLANK
	INC	HL		;BUMP DESTINATION POINTER
	DEC	C		;DECREMENT DIGIT COUNTER
	JR	NZ,BLANKF	;FILL OUT WITH BLANKS
	JR	CONTSC		;THEN CONTINUE SCANNING
;
;
; GET A LINE NUMBER FROM PROGRAM LINE
; ENTRY:  HL      - POINTER TO LINE NUMBER FIELD
; EXIT:   A       - FIRST BASIC TEXT LINE CHARACTER
;         DE      - THE LINE NUMBER
;         HL      - POINTER FIRST LINE CHARACTER
;         LINADR  - POINTER FIRST LINE CHARACTER
;
LINGET:	INC	HL		;BUMP TO LINE NUMBER LSB
	LD	E,(HL)		;GET LSB OF THE NUMBER
	INC	HL		;BUMP TO LINE NUMBER MSB
	LD	D,(HL)		;GET MSB OF THE NUMBER
	INC	HL		;BUMP TO BASIC LINE TEXT
	LD	(LINADR),HL	;STORE POINTER INTO LINE
	DEC	HL		;BACKUP POINTER TO NUMBER MSB
	JP	PARSER		;GET BYTE FROM THE LINE

;
; STORE FIVE BLANKS IN BASIC LINE
; ENTRY:  BC     - POINTER TO END OF FIELD
;
BLANKN:	PUSH	DE		;SAVE DE REGISTER
	PUSH	BC		;SAVE LINE POINTER
	LD	A,' '		;LOAD A BLANK CHARACTER
	LD	E,5		;LOAD BLANK COUNTER
BLANKL:	DEC	BC		;BACKUP STORAGE POINTER
	LD	(BC),A		;STORE A BLANK
	DEC	E		;DECREMENT COUNTER
	JR	NZ,BLANKL	;LOOP IF MORE BLANKS
	POP	BC		;RECOVER LINE POINTER
	POP	DE		;RECOVER DE REGISTER
	RET
;
;
; LINE ADDRESS STORAGE
;
LINADR	Dw	0		;POINTER INTO LINE
;
;
; TABLE OF TOKENS THAT ARE OR MAY BE FOLLOWED BY A LINE NUMBER
;
RENUMT	Db	AUTTOK,DELTOK,EDITOK,RSUTOK,ERLTOK,RUNTOK
	Db	LISTOK,LLITOK,GTOTOK,THNTOK,GSBTOK,ELSTOK
;
;
; DEFINE NUMBER OF ENTRIES ON ABOVE TABLE
;
RTOKCT	Equ	$-RENUMT	;NUMBER OF TOKENS IN TABLE
;
;
; SCAN LINE FOR A TOKEN WHICH MAY BE FOLLOWED BY A LINE NUMBER
;
SCNLIN:	LD	HL,(TXTTAB)	;GET START OF PROGRAM STORAGE
SCNLLP:	LD	A,(HL)		;GET LINK ADDRESS LSB
	INC	HL		;BUMP TO LINK ADDRESS MSB
	OR	(HL)		;TEST IF END OF PROGRAM
	JR	Z,RENEND	;SKIP IF IT IS
	INC	HL		;SKIP TO LINE NUMBER LSB
	INC	HL		;SKIP TO LINE NUMBER MSB
	INC	HL		;SKIP TO START OF PROGRAM LINE
SCNLNB:	LD	A,(HL)		;GET BYTE FROM PROGRAM
	OR	A		;TEST IF END OF LINE
	INC	HL		;BUMP LINE POINTER
	JR	Z,SCNLLP	;NEXT LINE IF END OF LINE
	JP	P,SCNLNB	;LOOP BACK IF NOT A TOKEN
	DEC	HL		;BACKUP POINTER TO TOKEN
	LD	DE,RENUMT	;POINT TO TOKEN TABLE
	LD	C,RTOKCT	;LOAD NUMBER OF TOKENS TO TEST
SCNLST:	LD	A,(DE)		;GET TOKEN FROM TABLE
	CP	(HL)		;TEST IF POSSIBLE LINE NUMBER
	JR	Z,PROCLN	;THEN WE MUST PROCESS IT
	INC	DE		;BUMP TO NEXT TOKEN
	DEC	C		;DECREMENT TOKEN COUNT
	JR	NZ,SCNLST	;LOOP IF MORE TOKENS
	LD	A,(HL)		;GET TOKEN BACK
	CP	IPUTOK		;TEST IF 'INPUT' TOKEN
	INC	HL		;BUMP POINTER PAST TOKEN
	JR	NZ,SCNLNB	;LOOP BACK IF IT ISN'T
	PUSH	HL		;SAVE LINE POINTER
	DEC	HL		;BACKUP POINTER
	RST	CHRGET		;GET BYTE FROM BASIC LINE
	CP	'#'		;TEST IF FILE INDICATOR
	JR	NZ,SCNLNT	;SKIP IF IT ISN'T
	RST	CHRGET		;GET BYTE FROM BASIC PROGRAM
	CP	LENTOK		;TEST IF 'LEN' TOKEN
	JR	NZ,SCNLNT	;SKIP IF IT ISN'T
SCNLCO:	RST	CHRGET		;GET BYTE FROM BASIC LINE
	JP	Z,SCNLNT	;SKIP IF END OF LINE
	CP	','		;TEST IF COMMA FOLLOWS
	JP	NZ,SCNLCO	;LOOP UNTIL COMMA OR END
	POP	AF		;CLEAN UP STACK
	JP	PROCLN		;THEN PROCESS LINE NUMBER
SCNLNT:	POP	HL		;RECOVER LINE POINTER
	JP	SCNLNB		;AND CONTINUE WITH LINE SCAN
;
;
; WE HAVE REACHED THE END OF THE PROGRAM
;
RENEND:	LD	HL,(TXTTAB)	;GET START OF PROGRAM STORAGE
	EX	DE,HL		;MOVE POINTER TO DE
RENENL:	LD	H,D		;GET PROGRAM
	LD	L,E		; POINTER TO HL
	LD	A,(HL)		;GET LINK ADDRESS LSB
	INC	HL		;BUMP TO MSB
	OR	(HL)		;TEST IF END OF PROGRAM
	JP	Z,RENUDN	;THEN WE ARE DONE
	INC	HL		;BUMP TO LINE NUMBER LSB
	INC	HL		;BUMP TO LINE NUMBER MSB
	INC	HL		;BUMP TO START OF LINE
RENENC:	LD	A,(HL)		;GET BYTE FROM PROGRAM
	INC	HL		;BUMP PROGRAM POINTER
	CP	LINCON		;TEST IF LINE NUMBER CONSTANT
	JR	Z,RENEIC	;NOTHING TO DO IF IT IS
	OR	A		;TEST IF END OF LINE
	JR	NZ,RENENC	;LOOP BACK IF NOT
	EX	DE,HL		;GET LINK POINTER TO HL
	LD	(HL),E		;STORE LSB OF NEW LINK ADDRESS
	INC	HL		;BUMP TO MSB
	LD	(HL),D		;STORE MSB OF NEW LINK ADDRESS
	JR	RENENL		;THEN GO DO NEXT LINE
RENEIC:	INC	HL		;BUMP PAST LINE NUMBER LSB
	INC	HL		;BUMP PAST LINE NUMBER MSB
	JR	RENENC		;THEN CONTINUE SCANNING
;
;
; PROCESS LINE NUMBERS AND LINE NUMBER RANGES
;
PROCLD:	DEC	HL		;BACKUP CODE STRING POINTER
;
;
; PROCESS LINE NUMBER AND LINE NUMBER RANGES
;
PROCLN:	RST	CHRGET		;GET BYTE FROM BASIC LINE
	PUSH	HL		;SAVE CODE STRING POINTER
	OR	A		;TEST IF BYTE IS ZERO
	JR	Z,PROCEL	;SKIP IF IT IS
PROCLS:	INC	HL		;BUMP CODE STRING POINTER
	LD	A,(HL)		;GET BYTE FROM BASIC LINE
	CP	00AH		;TEST IF ? CONSTANT
	JR	Z,L674F		;SKIP IF IT IS
	OR	A		;TEST IF BYTE IS ZERO
	JR	NZ,PROCLS	;LOOP FOR NEXT BYTE IF NOT
PROCEL:	LD	HL,FACINT	;POINT TO 'PRIACC' LSB
L674F:	LD	(HL),'*'	;STORE A STAR IN 'PRIACC'
	EX	DE,HL		;SWAP 'PRIACC' POINTER TO DE
	POP	HL		;RECOVER CODE STRING POINTER
	PUSH	HL		;RE-SAVE CODE STRING POINTER
	PUSH	DE		;SAVE 'PRIACC' POINTER
	CALL	EVALIN		;EVALUATE LINE NUMBER TO DE
	LD	A,00AH		;LOAD ? CONSTANT
	POP	BC		;GET 'PRIACC' POINTER TO BC
	LD	(BC),A
	POP	BC		;GET CODE STRING POINTER TO BC
	LD	A,L
	SUB	C
	JR	Z,L6785		;6785H
	PUSH	DE		;SAVE THE LINE NUMBER
	LD	E,A
	LD	A,2
	PUSH	AF
	LD	A,5
	SUB	E
	JR	NC,L6772	;6772H
	CPL
	INC	A
	POP	DE
	ADD	A,2
	PUSH	AF
	XOR	A
L6772:	PUSH	BC
	CALL	NZ,L67B1	;67B1H
	POP	HL		;RECOVER LINE INDEX
	LD	(HL),LINCON	;STOR LINE NUMBER CONSTANT
	INC	HL		;BUMP LINE INDEX
	POP	BC
	POP	DE		;RECOVER BINARY NUMBER
	LD	(HL),E		;STORE LSB OF BINARY NUMBER
	INC	HL		;BUMP LINE INDEX
	LD	(HL),D		;STORE MSB OF BINARY NUMBER
L677F:	INC	HL		;BUMP POINTER
	LD	(HL),' '	;STORE A BLANK IN LINE
	DJNZ	L677F		;LOOP UNTIL FILLED
L6784:	INC	HL		;BUMP LINE POINTER
L6785:	DEC	HL		;BACKUP LINE POINTER
	RST	CHRGET		;GET BYTE FROM BASIC LINE
	INC	A		;TEST IF
	DEC	A		; END OF LINE
	JR	C,PROCLD	;BACK IF CHARACTER NUMERIC
	INC	HL		;BUMP LINE POINTER
	JP	Z,SCNLLP	;DO NEXT LINE IF END
	DEC	HL		;ELSE BACKUP POINTER AGAIN
	CP	' '		;TEST IF BLANK
	JR	Z,L6784		;SKIP ALL BLANKS
	CP	','		;TEST IF COMMA
	JR	Z,L6784		;SKIP ALL COMMAS
	CP	MINTOK		;TEST IF MINUS TOKEN
	JR	Z,L6784		;SKIP ALL MINUS TOKENS
	CP	GRTTOK		;TEST IF GREATER THAN TOKEN
	JR	C,SCNLNJ	;CONTINUE IF EQUAL OR GREATER
	CP	SGNTOK		;TEST IF 'SGN' TOKEN
	JR	C,L6784		;CONTINUE IF EQUAL OR GREATER
SCNLNJ:	JP	SCNLNB		;BACK TO START OF LOOP
;
;
; SET START OF ARRAYS AND END OF BASIC PROGRAM
;
RENUDN:	LD	HL,(VARTAB)	;GET ADDR OF SIMPLE VARIABLES
	LD	(ARRTAB),HL	;SET START ARRAY VARIABLES
	LD	(ENDTAB),HL	;SET START OF FREE SPACE LIST
	RET
;
;
;
;
L67B1:	PUSH	HL
	LD	HL,(VARTAB)	;GET ADDR OF SIMPLE VARIABLES
	EX	DE,HL		;MOVE ADDRESS TO DE
	LD	H,0		;ZERO H REGISTER
	LD	L,A		;
	ADD	HL,DE
	LD	(VARTAB),HL	;SET ADDR OF SIMPLE VARIABLES
	LD	B,H		;MOVE MSB OF ADDRESS TO B
	LD	C,L		;MOVE LSB OF ADDRESS TO C
	POP	HL
L67C0:	LD	A,(DE)		;GET BYTE FROM SOURCE
	LD	(BC),A		;STORE AT DESTINATION
	RST	CPHLDE		;TEST IF WE ARE DONE
	RET	Z		;THEN RETURN TO CALLER
	DEC	DE		;DECREMENT SOURCE POINTER
	DEC	BC		;DECREMENT DESTINATION POINTER
	JR	L67C0		;LOOP FOR NEXT BYTE
;
;
; STORAGE REGISTERS
;
PTRFLG	Db	0		;POINTER AND NUMBER FLAG
BEGLIN	Dw	0		;STARTING LINE NUMBER
