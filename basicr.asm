;
; CONVERT INTEGER TO NUMERIC ASCII
; ENTRY:  HL     - INTEGER TO CONVERT
; EXIT:   HL     - POINTER TO CONVERTED NUMBER
;
INTASC:	CALL	STOINT		;STORE INTEGER IN 'PRIACC'
	XOR	A		;ZERO FOR EDIT FLAG CLEAR
	CALL	GETPBF		;GET BUFFER ADDRESS
	OR	(HL)		;GET FIRST BUFFER CHAR
	JP	FACASC		;CONVERT BINARY TO ASCII
