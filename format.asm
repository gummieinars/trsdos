	LD	B,1		;GET BUFFER SIZE TO B
	CALL	KBLINE		;INPUT AND FILL BUFFER
	LD	A,(HL)		;GET CHARACTER FROM LINE
	CP	'N'		;TEST IF FORMAT NOT WANTED
	JP	Z,HASDRB	;THEN WE ABORT THE FORMAT
	CP	'Y'		;TEST IF FORMAT WANTED
	JP	NZ,HASDTA	;LOOP UNTIL EITHER KEY
	NOP			;DO NOTHING AT ALL
	CALL	SELDRV		;RE-SELECT DISKETTE DRIVE
	LD	BC,32768	;HALF SECOND DELAY
	CALL	DELAYL		;CALL ROUTINE IN BASIC ROM
	RET
