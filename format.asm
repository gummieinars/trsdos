BOOTSE	Db	000H		;SIGNATURE/RECORD TYPE (NOP)
	Db	0FEH		;SIGNATURE/RECORD SIZE (CP)
DIRTRK	Db	000H		;DIRECTORY TRACK NUMBER
;
;
; START OF MAIN BOOT LOADER CODE
;
	DI			;DISABLE INTERRUPTS
	LD	SP,STACKT	;SET TOP OF STACK FOR BOOT
	LD	HL,CLRSCR-O	;POINT AT SCREEN CLEAR STRING
	CALL	MSGOUT-O	;CLEAR THE VIDEO SCREEN
	LD	A,00000001B	;CODE FOR SELECTING DRIVE 0
	LD	(DRVREG),A	;SELECT THE DRIVE
	LD	A,(DIRTRK-O)	;LOAD DIRECTORY TRACK TO A
	LD	D,A		;SAVE THE TRACK IN D
	LD	E,4		;SECTOR FOR SYS0/SYS ENTRY
	LD	BC,SCTBUF	;POINT AT SECTOR BUFFER
	CALL	RDSECT-O	;READ THE DIRECTORY SECTOR
	JR	NZ,RDEROR	;ABORT IF READ ERROR
	LD	A,(SCTBUF)	;GET FIRST BUFFER BYTE
	AND	00010000B	;ISOLATE ENTRY OCCUPIED BIT
	LD	HL,NOSYST-O	;POINT AT ERROR MESSAGE
	JR	Z,MSGHLT	;ABORT IF UNOCCUPIED ENTRY
	EXX			;SWAP TO ALTERNATE REGISTERS
	LD	HL,(SCTBUF+22)	;GET FIRST GAP FOR 'SYS0/SYS'
	LD	D,L		;TRACK NUMBER TO D
	LD	A,H		;BYTE COUNT, SECTOR OFFSET TO A
	RLCA			;SHIFT BIT
	RLCA			; FIVE TO
	RLCA			;  BIT TWO
	AND	00000111B	;MASK TO GRANULE NUMBER (0/1)
	LD	H,A		;SAVE RESULT IN H REGISTER
	RLCA			;MULTIPLY BY TWO
	RLCA			;MULTIPLY BY FOUR
	ADD	A,H		;MULTIPLY BY FIVE
	LD	E,A		;GET SECTOR NUMBER TO E
	LD	BC,SCTBUF+255	;AT BUFFER END TO FORCE READ
	EXX			;SWAP TO PRIMARY REGISTERS
BOOTLL:	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	DEC	A		;TEST IF LOAD ADDRESS CODE
	JR	NZ,BOOTTR	;TEST NEXT IF NOT
	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	LD	B,A		;SET AS THE BYTE COUNTER
	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	LD	L,A		;SET AS LOAD ADDRESS LSB
	DEC	B		;DECREMENT BYTE COUNTER
	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	LD	H,A		;SET AS LOAD ADDRESS MSB
BOOTNB:	DEC	B		;DECREMENT BYTE COUNTER
	JR	Z,BOOTLL	;LOOP FOR NEXT RECORD IF ZERO
	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	LD	(HL),A		;STORE THE BYTE IN MEMORY
	INC	HL		;BUMP MEMORY POINTER
	JR	BOOTNB		;THEN GO FOR NEXT BYTE
BOOTTR:	DEC	A		;TEST IF RUN ADDRESS CODE
	JR	Z,BOOTEX	;THEN GO EXECUTE LOADED CODE
	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	LD	B,A		;SET AS THE BYTE COUNTER
BOOTCO:	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	DJNZ	BOOTCO		;LOOP AND DISCARD BYTES
	JR	BOOTLL		;THEN GO FOR NEXT RECORD
BOOTEX:	CALL	BOOTRB-O	;READ AND DISCARD COUNT BYTE
	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	LD	L,A		;SET AS RUN ADDRESS LSB
	CALL	BOOTRB-O	;READ A BYTE FROM DISK
	LD	H,A		;SET AS RUN ADDRESS MSB
	JP	(HL)		;THEN EXECUTE LOADED CODE
;
;
; READ A BYTE FROM SECTOR BUFFER - REFILL IF EMPTY
; ENTRY:  BC      - BUFFER POINTER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - BYTE FROM BUFFER
;         BC      - LSB IS INCREMENTED MODULO 256
;         D       - INCREMENTED IF SECTOR HITS 10
;         E       - INCREMENTED MODULO 10
;5E75
BOOTRB:	EXX			;SWAP TO ALTERNATE REGISTERS
	INC	C		;BUMP BUFFER POINTER
	JR	NZ,BOOTGB	;GET BUFFER BYTE IF NOT EMPTY
	PUSH	BC		;SAVE BUFFER POINTER
	LD	A,00000001B	;LOAD DRIVE SELECT CODE
	LD	(MDRVRE),A	;WAS RESELECT CURRENT DRIVE
	CALL	RDSECT-O	;READ NEXT SECTOR
	JR	NZ,RDEROR	;ABORT IF READ ERROR
	POP	BC		;RECOVER BUFFER POINTER
	INC	E		;BUMP SECTOR NUMBER
	LD	A,E		;GET NUMBER TO A
	SUB	NUMSEC		;TEST IF DONE WITH TRACK
	JR	NZ,BOOTGB	;GET BUFFER BYTE IF NOT
	LD	E,A		;ZERO SECTOR NUMBER
	INC	D		;BUMP TO NEXT TRACK
BOOTGB:	LD	A,(BC)		;GET A BYTE FROM BUFFER
	EXX			;SWAP TO PRIMARY REGISTERS
	RET
;
;
; A DISK READ ERROR OCCURRED
;5E90
RDEROR:	LD	HL,DSKERR-O	;POINT AT ERROR MESSAGE
;
;
; DISPLAY A MESSAGE, GET KEYBOARD INPUT AND REBOOT
;5E93
MSGHLT:	CALL	MSGOUT-O	;DISPLAY THE MESSAGE
	CALL	KBLINE		;GET A KEYBOARD LINE
	HALT			;RE-BOOT THE SYSTEM
;
;
; DISPLAY A MESSAGE STRING ON THE DISPLAY OUTPUT DEVICE
; MESSAGE TERMINATOR IS 'CC' (NOT OUTPUT) OR 'CR' (OUTPUT)
; ENTRY:  HL      - POINTER TO STRING
; EXIT:   HL      - PRESERVED
;5E9A
MSGOUT:	PUSH	HL		;SAVE STRING POINTER
MSGOUL:	LD	A,(HL)		;GET CHARACTER FROM STRING
	CP	CC		;TEST IF MESSAGE TERMINATOR
	JR	Z,MSGOUX	;THEN WE ARE ALL DONE
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	INC	HL		;BUMP STRING POINTER
	CP	CR		;TEST IF MESSAGE TERMINATOR
	JR	NZ,MSGOUL	;LOOP UNTIL IT IS
MSGOUX:	POP	HL		;RECOVER STRING POINTER
	RET
;
;
; READ A DISK SECTOR INTO SECTOR BUFFER - RETRY ONCE
; ENTRY:  BC      - POINTER TO BUFFER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - DISK CONTROLLER STATUS FLAGS
;         D       - UNCHANGED
;         E       - UNCHANGED
;         ZF      - SET IF SUCCESSFUL READ
;5EAA
RDSECT:	PUSH	BC		;SAVE BUFFER POINTER
	CALL	SECTRD-O	;READ SECTOR INTO BUFFER
	POP	HL		;RECOVER BUFFER POINTER
	RET	Z		;DONE IF SUCCESSFUL READ
	LD	B,H		;BUFFER POINTER MSB TO B
	LD	C,L		;BUFFER POINTER LSB TO C
;
;
; READ A DISK SECTOR INTO SECTOR BUFFER
; ENTRY:  BC      - POINTER TO BUFFER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - DISK CONTROLLER STATUS FLAGS
;         D       - UNCHANGED
;         E       - UNCHANGED
;         ZF      - SET IF SUCCESSFUL READ
;5EB2
SECTRD:	LD	(SCTREG),DE	;STORE TRACK AND SECTOR
	LD	HL,CSTREG	;COMMAND/STATUS REGISTER
	LD	(HL),WDSEEK	;SEEK TO TRACK COMMAND
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
SECTRB:	LD	A,(HL)		;GET FLOPPY CONTROLLER STATUS
	RRCA			;COPY BUSY BIT TO CARRY
	JR	C,SECTRB	;LOOP IF CONTROLLER BUSY
	LD	(HL),WDREAD	;READ SECTOR COMMAND
	PUSH	DE		;SAVE TRACK AND SECTOR VALUES
	LD	DE,DTAREG	;POINT AT DATA REGISTER
	EX	(SP),HL		;DELAY FOR I/O
	EX	(SP),HL		;DELAY FOR I/O
	JR	SECTRE		;THEN ENTER READ LOOP
;
;
; TEST IF NOT BUSY - IF SO, THEN WE ARE DONE READING
;5ECD
SECTRN:	RRCA			;COPY BUSY BIT TO CARRY
	JR	NC,SECTRX	;ALL DONE IF NOT BUSY
;
;
; TEST IF DATA BYTE READY - LOOP IF NOT, ELSE READ AND STORE
;5ED0
SECTRL:	LD	A,(HL)		;GET CONTROLLER STATUS TO A
	BIT	1,A		;TEST IF DATA BYTE IS READY
	JR	Z,SECTRN	;TEST IF DONE IF IT ISN'T
	LD	A,(DE)		;GET DATA BYTE FROM DISK
	LD	(BC),A		;STORE BYTE IN BUFFER
	INC	BC		;BUMP BUFFER POINTER
SECTRE:	JR	SECTRL		;LOOP BACK FOR NEXT BYTE
;
;
; DONE READING - GET FINAL STATUS AND RETURN
;5EDA
SECTRX:	LD	A,(HL)		;GET FINAL STATUS TO A
	AND	01011100B	;MASK TO ERROR BITS
	POP	DE		;RECOVER TRACK AND SECTOR
	RET	Z		;RETURN IF NO ERRORS
	LD	(HL),WDFORC	;ELSE FORCE INTERRUPT
	RET
