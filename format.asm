; WAIT FOR SIXTY MILLISECONDS, THEN PROMPT FOR REBOOT
;5BC0
HASDRB:	LD	BC,4096		;LOAD DELAY VALUE
	CALL	DELAYL		;CALL ROUTINE IN BASIC ROM
	JP	PREENT		;THEN GO PROMPT FOR RE-BOOT
