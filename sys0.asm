	RET	NC		;EXIT IF MONTH NOT ROLLED OVER
	LD	A,(HL)		;REFETCH CURRENT DAY NUMBER
	CP	30		;TEST IF FEBRUARY
	JR	NC,CLKHNF	;JUMP IF NOT FEBRUARY
	DEC	L		;BACKSPACE TO YEAR VALUE
	LD	A,(HL)		;FETCH YEAR
	INC	L		;SKIP FORWARD TO DAY
	AND	00000011B	;TEST IF LEAP YEAR
	RET	Z		;EXIT IF NOT LEAP YEAR
