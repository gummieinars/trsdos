;
; COMMON ROUTINE TO STORE DATE OR TIME AS A STRING IN A BUFFER
; ENTRY:  C       - FIELD DELIMITER
;         HL      - POINTER TO STRING BUFFER
;4CBC
STORDT:	LD	B,3		;LOAD FIELD COUNTER TO B
STORDN:	LD	A,(DE)		;GET VALUE FROM STORAGE
	DEC	DE		;BACKUP TO PREVIOUS VALUE
	LD	(HL),'0'-1	;STORE STARTING TENS DIGIT
STORDU:	INC	(HL)		;BUMP THE TENS DIGIT
	SUB	10		;SUBTRACT DECIMAL TEN
	JR	NC,STORDU	;LOOP UNTIL UNDERFLOW
	ADD	A,'9'+1		;ACCUMULATOR HAS ONES DIGIT
	INC	HL		;BUMP STORAGE POINTER
	LD	(HL),A		;STORE ONES DIGIT IN BUFFER
	INC	HL		;BUMP STORAGE POINTER
	DEC	B		;DECREMENT FIELD COUNTER
	RET	Z		;DONE IF ALL CONVERTED
	LD	(HL),C		;STORE DELIMITER IN BUFFER
	INC	HL		;BUMP STORAGE POINTER
	JR	STORDN		;THEN DO NEXT FIELD
