	Org	04C06H
;
EXELOD:	PUSH	HL		;SAVE CALLER'S HL
	CALL	LODFIL		;LOAD FILE FROM SYSTEM DCB
	JP	NZ,DERROR	;ABORT IF ERROR DURING LOAD
	EX	(SP),HL		;SWAP RUN ADDRESS WITH HL
	LD	A,(SYSCON)	;GET SYSTEM CONDITION FLAGS
	OR	A		;TEST IF DEBUG FLAG SET
	JP	M,LDEBUG	;THEN GO LOAD DEBUG
	RET
;
;
; LOAD A FILE SPECIFIED BY A DEVICE CONTROL BLOCK
; ENTRY:  DE      - POINTER TO DEVICE CONTROL BLOCK
;
	Org	04430H
;
LODFIL:	JP	FILLOD		;LOAD THE SPECIFIED FILE
;
;
; LOAD A FILE SPECIFIED BY A DEVICE CONTROL BLOCK
; ENTRY:  DE      - POINTER TO DEVICE CONTROL BLOCK
;
	Org	04C16H
;
FILLOD:	LD	B,0		;SPECIFY PHYSICAL I/O
	LD	HL,GATBUF	;POINT AT FILE BUFFER
	CALL	OPNFIL		;OPEN THE SPECIFIED FILE
	JR	Z,GPFILO	;SKIP IF FILE OPENED OK
	SET	6,A		;SET ERROR CODE DISPLAY BIT
	CP	58H		;FILE NOT IN DIRECTORY?
	RET	NZ		;RETURN IF NOT
	LD	A,5FH		;ELSE PROGRAM NOT FOUND
	OR	A		;SET STATUS FLAGS
	RET
;
;
; GENERAL PURPOSE FILE LOADER
;4C29
GPFILO:	INC	DE		;BUMP TO DCB ACCESS FLAGS
	LD	A,(DE)		;GET ACCESS FLAGS TO A
	DEC	DE		;BACKUP TO DCB START
	AND	00000111B	;ISOLATE ACCESS PERMISSIONS
	CP	00000110B	;TEST FOR RESTRICTED FILE
	JR	C,SYSLDR	;SKIP IF NOT RESTRICTED
	LD	A,(SYSCON)	;GET SYSTEM CONDITION FLAGS
	RLCA			;DEBUG ACTIVE BIT TO CARRY
	LD	A,25H		;LOAD ILLEGAL ACCESS ERROR
	RET	C		;ABORT IF DEBUG ACTIVE
;
;
; SYSTEM LOADER
;4C39
SYSLDR:	LD	BC,GATBUF+255	;SET TO EMPTY BUFFER STATUS
SYSLLP:	CALL	SYSLGB		;GET A BYTE FROM LOAD FILE
	CP	01H		;TEST IF DATA RECORD
	JR	Z,SYSLDA	;THEN GO LOAD DATA BLOCK
	CP	02H		;TEST IF TRANSFER ADDRESS
	JR	Z,SYSLTR	;THEN EXECUTE LOADED CODE
	CP	1FH+1		;TEST IF COMMENT RECORD
	JR	C,SYSLCO	;THEN GO SKIP THE COMMENT
	LD	A,22H		;LOAD FILE FORMAT ERROR
	OR	A		;SET STATUS FOR ERROR CODE
	RET
;
;
; COMMENT RECORD - SKIP THE RECORD
;4C4F
SYSLCO:	CALL	SYSLGB		;GET BYTE COUNT TO A
	LD	B,A		;COPY THE BYTE COUNT TO B
SYSLCL:	CALL	SYSLGB		;READ A DATA BYTE
	DJNZ	SYSLCL		;LOOP UNTIL ALL BYTES READ
	JR	SYSLLP		;THEN LOOP FOR NEXT CODE
;
;
; TRANSFER ADDRESS RECORD - GET THE ADDRESS AND RETURN
; EXIT:   HL      - TRANSFER ADDRESS
;4C5A
SYSLTR:	CALL	SYSLGB		;GET AND DISCARD BYTE COUNT
	CALL	SYSLGB		;GET TRANSFER ADDRESS LSB
	LD	L,A		;COPY THE BYTE TO L
	CALL	SYSLGB		;GET TRANSFER ADDRESS MSB
	LD	H,A		;COPY THE BYTE TO H
	XOR	A		;SET STATUS FOR NO ERROR
	RET
;
;
; DATA RECORD - LOAD THE RECORD
;4C67
SYSLDA:	CALL	SYSLGB		;GET BYTE COUNT TO A
	LD	B,A		;COPY THE BYTE COUNT TO B
	CALL	SYSLGB		;GET LOAD ADDRESS LSB
	LD	L,A		;COPY THE BYTE TO L
	DEC	B		;DECREMENT BYTE COUNT
	CALL	SYSLGB		;GET LOAD ADDRESS MSB
	LD	H,A		;COPY THE BYTE TO H
	DEC	B		;DECREMENT BYTE COUNT
SYSLDL:	CALL	SYSLGB		;GET DATA BYTE TO A
	LD	(HL),A		;STORE DATA IN MEMORY
	CP	(HL)		;TEST IF BYTE STORED OK
	JR	NZ,SYSLER	;NO RAM THERE IF NOT
	INC	HL		;ELSE BUMP DATA ADDRESS
	DJNZ	SYSLDL		;LOOP UNTIL DATA STORED
	JR	SYSLLP		;THEN LOOP FOR NEXT CODE
;
;
; DETERMINE CAUSE OF STORAGE FAILURE
;4C81
SYSLER:	LD	A,(HL)		;FETCH MEMORY CONTENTS
	CPL			;COMPLEMENT THE BYTE
	LD	(HL),A		;STORE THE BYTE BACK
	CP	(HL)		;TEST IF BYTE STORED OK
	LD	A,63H		;MEMORY FAULT ERROR
	RET	NZ		;ABORT IF MISMATCH
	LD	A,64H		;ATTEMPT TO LOAD ROM
	OR	A		;SET ERROR STATUS
	RET
;
;
; GET NEXT BYTE OF LOAD DATA FROM SECTOR BUFFER
;4C8C
SYSLGB:	INC	C		;BUMP BUFFER POINTER LSB
	JR	NZ,SYSLNB	;SKIP IF BUFFER NOT EMPTY
	PUSH	DE		;SAVE DCB ADDRESS
	EX	(SP),IX		;SWAP DCB ADDRESS TO IX
	PUSH	HL		;SAVE CALLER'S HL
	PUSH	DE		;SAVE CALLER'S DE
	PUSH	BC		;SAVE BUFFER POINTER
	CALL	NOTRDP		;READ NEXT FILE RECORD
	POP	BC		;RECOVER BUFFER POINTER
	POP	DE		;RECOVER CALLER'S DE
	POP	HL		;RECOVER CALLER'S HL
	POP	IX		;RECOVER IX REGISTER
	JR	Z,SYSLNB	;SKIP IF NO ERROR
	POP	BC		;REMOVE RETURN ADDRESS
	OR	01000000B	;SIGNAL ERROR DURING LOAD
	RET
;
;
; GET A DATA BYTE FROM THE BUFFER
; ENTRY:  B       - CURRENT BYTE COUNT
;         C       - INDEX INTO DATA BUFFER
; EXIT:   A       - DATA BYTE FROM BUFFER
;4CA3
SYSLNB:	PUSH	BC		;SAVE COUNT AND INDEX
	LD	B,High GATBUF	;LOAD SECTOR BUFFER MSB
	LD	A,(BC)		;GET BYTE FROM BUFFER
	POP	BC		;RECOVER COUNT AND INDEX
	RET
