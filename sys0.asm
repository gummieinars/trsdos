	 Org	04388H		;DEFINE PATCH ORIGIN
	Else			;ORIGINAL
	 Org	04398H		;DEFINE PATCH ORIGIN
	EndIf			;DONE WITH IT
;
WAITNB:	LD	A,(CSTREG)	;GET CONTROLLER STATUS
	BIT	0,A		;TEST IF CONTROLLER BUSY
	RET	Z		;EXIT IF NOT BUSY
	JR	WAITNB		;LOOP UNTIL NOT BUSY
;
;
; ADDITIONAL PATCHES
;
	If	PATCHG		;PATCHES ACTIVE
;
;
; VIDEO DRIVER ROUTINE LOWER CASE PATCH
;
; NOTE:  LOCATED IN ALTERNATE VIDEO DEVICE CONTROL BLOCK
;
	 Org	04378H
;
DOTDCB:	 LD	L,(IX+03)	;GET CURSOR ADDRESS LSB
	 LD	H,(IX+04)	;GET CURSOR ADDRESS MSB
	 JP	C,VIDRCH	;RETURN LAST CHARACTER
	 LD	A,(IX+05)	;GET CURSOR ON FLAG TO A
	 OR	A		;TEST IF CURSOR IS OFF
	 JR	Z,LOCACO	;SKIP IF IT IS OFF
	 LD	(HL),A		;ELSE RESTORE THE CHARACTER
LOCACO:	 LD	A,C		;GET NEW CHARACTER TO A
	 CP	0C0H		;TEST IF GRAPHICS CHARACTER
	 JP	NC,VIDRCO	;COMPRESSION CODE IF NOT
	 CP	20H		;TEST IF CONTROL CODE
	 JP	C,VIDRCC	;THEN HANDLE CONTROL CODE
	 JP	VIDRAU		;ADD CHARACTER TO DISPLAY
;
;
; SET ADDRESS OF VIDEO DRIVER PATCH IN VIDEO DCB
;
	 Org	0401EH
;
VIDPAT	 Dw	DOTDCB		;DRIVER ADDRESS
;
;
; SET ADDRESS OF PRINTER DRIVER PATCH IN PRINTER DCB
;
	 Org	04026H
;
PRTPAT	 Dw	PRINTR		;DRIVER ADDRESS
	EndIf			;DONE WITH IT
;
	End	INITIT

