; INTERRUPT SERVICE ROUTINE
;4518
INTSRV:	PUSH	HL		;SAVE HL REGISTER
	PUSH	AF		;SAVE AF REGISTER
	LD	A,(INTREG)	;GET INTERRUPT STATUS BYTE
	LD	HL,INTSTS	;POINT TO INTERRUPT SAVE AREA
	LD	(HL),A		;SAVE INTERRUPT STATUS
	INC	L		;POINT TO MASK BYTE
	AND	(HL)		;COMPARE TO INTERRUPT STATUS
	JR	Z,INTSRI	;IGNORE INTERRUPT IF NO MATCH
INTSRB:	INC	L		;BUMP TO ADDRESS LIST
	RRA			;TEST FOR A MATCH
	JR	C,DOTASK	;JUMP IF ON BIT FOUND
INTSRN:	INC	L		;BUMP TO NEXT ADDRESS
	OR	A		;TEST IF MORE REMAINING
	JR	NZ,INTSRB	;TEST MORE IF SO
INTSRI:	LD	A,(KROSEV)	;LOAD <BREAK> KEY ROW
	AND	00000100B	;TEST IF <BREAK> PRESSED
	JR	NZ,DOBREK	;JUMP IF <BREAK> ACTIVE
INTSRX:	POP	AF		;RECOVER AF REGISTER
	POP	HL		;RECOVER HL REGISTER
	EI			;RE-ENABLE INTERRUPTS
INTSRR:	RET
