	If	PATCHG		;PATCHES ACTIVE
 	 EX	(SP),HL		;DELAY FOR I/O
	 EX	(SP),HL		;DELAY FOR I/O
	 EX	(SP),HL		;DELAY FOR I/O
	 EX	(SP),HL		;DELAY FOR I/O
	 DI			;NO INTERUPTIONS ALLOWED
	 JR	TSTRDY		;ENTER TRANSFER LOOP
TSTBSY:	 RRCA			;TEST IF CONTROLLER BUSY
	 JR	NC,XFRDON	;ALL DONE IF NOT BUSY
TSTRDY:	 LD	A,(HL)		;GET STATUS BYTE
	 BIT	1,A		;TEST IF BYTE IS READY
	 JR	Z,TSTBSY	;TEST CONTROLLER BUSY IF NOT
DOXFER:	 NOP			;ELSE DO
	 NOP			; THE TRANSFER
	 INC	BC		;BUMP BUFFER POINTER
	 JR	TSTRDY		;THEN LOOP FOR NEXT BYTE
	Else			;ORIGINAL
	 POP	BC		;DELAY FOR I/O
	 PUSH	BC		;DELAY FOR I/O
	 DI			;NO INTERRUPTIONS ALLOWED
	 JR	TSTRDY		;THEN ENTER TRANSFER LOOP
TSTBSY:	 RRCA			;ROTATE BUSY BIT TO CARRY
	 JR	NC,XFRDON	;ALL DONE IF NOT BUSY
TSTRDY:	 LD	A,(HL)		;GET STATUS BYTE
	 BIT	1,A		;TEST IF BYTE IS READY
	 JR	Z,TSTBSY	;CONTINUE TESTING IF NOT
	 DI			;NO INTERRUPTIONS ALLOWED
DOXFER:	 NOP			;DO THE
	 NOP			; TRANSFER
	 INC	BC		;BUMP BUFFER POINTER
	 JP	TSTRDY		;THEN LOOP FOR NEXT BYTE
	EndIf			;DONE WITH IT
;
XFRDON:	EI			;RE-ENABLE INTERRUPTS
	LD	A,(HL)		;GET CONTROLLER STATUS
	AND	01111100B	;MASK TO ERROR BITS
	LD	(HL),0D0H	;CLEAR DISK CONTROLLER
	POP	HL		;RECOVER BUFFER ADDRESS
	POP	DE		;RECOVER TRACK/SECTOR NUMBER
	POP	BC		;RECOVER RETRY COUNT/UNIT
	JR	Z,FONDBI	;EXIT IF NO ERRORS
	BIT	2,A		;TEST IF LOST DATA
	JR	NZ,LOSTDA	;JUMP IF LOST DATA
	CP	00100000B	;TEST IF WRITE FAULT
	JR	Z,WFAULT	;JUMP IF WRITE FAULT
	PUSH	AF		;SAVE ERROR STATUS
	LD	A,-1		;FORCE UNIT TO
	LD	(LASDRV),A	; BE RE-SELECTED
	CALL	SELDRV		;SELECT UNIT
	LD	A,WDREST	;RESTORE HEAD COMMAND
	CALL	ISSCMD		;ISSUE RESTORE COMMAND
	POP	AF		;RECOVER SAVED STATUS
LOSTDA:	DJNZ	DSKDRR		;LOOP FOR RETRY COUNT
WFAULT:	LD	B,A		;MOVE STATUS TO B
	LD	A,0		;MOVE BIAS VALUE TO A
ERBIAS	Equ	$-1		;ERROR CODE BIAS VALUE
FINDBI:	RRC	B		;RIGHT SHIFT ERROR STATUS
	JR	C,FONDBI	; UNTIL ERROR BIT FOUND
	INC	A		;INCREMENT BIAS VALUE
	JR	FINDBI		;LOOP UNTIL ERROR BIT FOUND
FONDBI:	POP	BC		;RECOVER RETRY COUNT/UNIT
	RET
;
;
; READ SUBROUTINE USED TO CALL DISK DRIVER
; ENTRY:  C       - UNIT NUMBER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - RETURN CODE
;         CF      - SET IF ERROR
;46DD
RDSECT:	LD	A,WDREAD	;LOAD READ COMMAND
	CALL	DSKDRV		;CALL DISK DRIVER
	Db	10		;RETRY COUNT IF ERROR
	Db	1		;BIAS TO BE ADDED TO ERROR
	LD	A,(DE)		;FETCH BYTE FROM CONTROLLER
	LD	(BC),A		;STORE IN CALLER'S BUFFER
;
;
; WRITE SUBROUTINE USED TO CALL DISK DRIVER - DATA
; ENTRY:  C       - UNIT NUMBER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - RETURN CODE
;         CF      - SET IF ERROR
;46E6
WRNSEC:	LD	A,WDWRDB	;LOAD WRITE OP CODE 'FB' DAM
;
;
; WRITE SUBROUTINE USED TO CALL DISK DRIVER
; ENTRY:  A       - DISK CONTROLLER COMMAND CODE
;         C       - UNIT NUMBER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - RETURN CODE
;         CF      - SET IF ERROR
;46E8
WRSECT:	CALL	DSKDRV		;CALL DISK DRIVER
	Db	5		;RETRY COUNT IF ERROR
	Db	9		;BIAS TO ADD TO ERROR CODE
	LD	A,(BC)		;FETCH BYTE FROM DATA BUFFER
	LD	(DE),A		;SEND BYTE TO CONTROLLER
;
;
; WRITE SUBROUTINE USED TO CALL DISK DRIVER - DIRECTORY
; ENTRY:  C       - UNIT NUMBER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - RETURN CODE
;         CF      - SET IF ERROR
;46EF
WRDSEC:	LD	A,WDWRDA	;LOAD WRITE OP CODE 'FA' DAM
	JR	WRSECT		;USE NORMAL WRITE DISK CALL
;
;
; READ SUBROUTINE USED TO CALL DISK DRIVER - VERIFY READ
; ENTRY:  C       - UNIT NUMBER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
; EXIT:   A       - RETURN CODE
;         CF      - SET IF ERROR
;46F3
RDSECV:	LD	A,WDREAD	;LOAD READ OP CODE
	CALL	DSKDRV		;CALL DISK DRIVER
	Db	5		;RETRY COUNT IF ERROR
	Db	1		;BIAS TO ADD TO ERROR CODE
	LD	A,(DE)		;FETCH BYTE FROM CONTROLLER
	NOP			;DO NOT STORE DATA IN BUFFER
;
;
; JUMP TO 'POSITION TO SPECIFIED RECORD' ROUTINE
;
	Org	04442H
;
POSREC:	JP	RECPOS		;GO POSITION TO RECORD
;
;
; POSITION FILE TO SPECIFIED RECORD NUMBER
;
	Org	04700H
;
RECPOS:	CALL	SAVREG		;SAVE CALLER'S REGISTERS
	SET	6,(IX+01)	;SIGNAL POSITION CALL
	BIT	7,(IX+01)	;TEST FOR PHYSICAL/LOGICAL I/O
	JR	Z,RECPOP	;JUMP IF PHYSICAL I/O
	LD	H,B		;MOVE RECORD NUMBER FROM BC
	LD	L,C		; TO HL SO IT CAN BE DIVIDED
	LD	A,(IX+09)	;FETCH RECORD SIZE
	CALL	RECTOS		;DIVIDE BY RECORD SIZE
	LD	B,H		;MOVE RELATIVE
	LD	C,L		; RECORD NUMBER TO BC
RECPOP:	LD	(IX+05),A	;SAVE OFFSET WITHIN SECTOR
	PUSH	BC		;SAVE RELATIVE RECORD NUMBER
	CALL	PURGEB		;FLUSH SECTOR BUFFER TO DISK
	POP	BC		;RECOVER RELATIVE RECORD
	RET	NZ		;ABORT IF ANY ERRORS
	LD	(IX+10),C	;MOVE RELATIVE SECTOR TO
	LD	(IX+11),B	; DCB AS NEXT RECORD NUMBER
	SET	5,(IX+01)	;FORCE READ ON NEXT ACCESS
	CALL	TSTEOF		;TEST FOR END OF FILE
	RET	NZ		;EXIT IF END OF FILE
	CALL	LCTGAP		;GET TRACK AND SECTOR FOR REC
	RET	NZ		;GO IF ERROR DURING TRANSLATION
	CALL	SELSEK		;SELECT DRIVE AND FIND TRACK
	XOR	A		;SIGNAL GOOD STATUS
	RET
;
;
; JUMP TO 'BACKSPACE ONE RECORD' ROUTINE
;
	Org	04445H
;
BACREC:	JP	RECBAC		;JUMP TO BACKSPACE ROUTINE
;
;
; BACKSPACE ONE RECORD OPERATION
;
	Org	04737H
;
RECBAC:	CALL	SAVREG		;SET UP EXIT SEQUENCE
	LD	C,(IX+10)	;LOAD BC WITH
	LD	B,(IX+11)	; NEXT SECTOR NUMBER
	BIT	7,(IX+01)	;TEST FOR LOGICAL VS PHY I/O
	JR	Z,RECFUL	;JUMP IF PHY I/O
	LD	A,(IX+09)	;GET RECORD SIZE FROM DCB
	OR	A		;TEST IF 256 BYTE RECORD
	JR	Z,RECFUL	;JUMP IF IT IS
	NEG			;ELSE NEGATE RECORD SIZE
	ADD	A,(IX+05)	;SUBTRACT LENGTH FROM POSITION
	JR	C,RECPOP	;GO IF IT CROSSES SECTOR LINE
RECFUL:	DEC	BC		;DECREMENT SECTOR NUMBER
	JR	RECPOP		;UPDATE BUFFER, FLUSH, RETURN
;
;
; JUMP TO 'REWIND' ROUTINE
;
	Org	0443FH
;
REWIND:	JP	REWINF		;REWIND THE FILE
;
;
; REWIND FILE
;
	Org	04756H
;
REWINF:	CALL	SAVREG		;SAVE CALLER'S REGISTERS
	LD	BC,0		;RECORD NUMBER FOR POSN CALL
	XOR	A		;ZERO OFFSET IN SECTOR BUFFER
	JR	RECPOP		;USE POSN TO REWIND FILE
;
;
; JUMP TO 'SKIP TO END OF FILE' ROUTINE
;
	Org	04448H
;
POSEOF:	JP	EOFPOS		;SKIP TO END OF FILE
;
;
; SKIP TO END OF FILE
;
	Org	0475FH
;
EOFPOS:	CALL	SAVREG		;SAVE CALLERS REGISTERS
	LD	C,(IX+12)	;LOAD NUMBER OF RECORDS
	LD	B,(IX+13)	; IN FILE INTO BC REGISTER
	LD	A,(IX+08)	;GET EOF BYTE IN LAST RECORD
	JR	RECPOP		;USE POSN TO UPDATE DCB
;
;
; JUMP ADDRESS TO READ RECORD ROUTINE
;
	Org	04436H
;
REDREC:	JP	RECRED		;READ THE RECORD
;
;
; READ RECORD PROCESSING
;
	Org	0476DH
;
RECRED:	CALL	SAVREG		;SAVE CALLER'S REGISTERS
	CALL	PURGEB		;PURGE BUFFER IF NECESSARY
	RET	NZ		;ABORT IF ANY ERRORS
	BIT	7,(IX+01)	;TEST FOR PHYSICAL I/O
	JP	Z,RDNXTS	;JUMP IF PHYSICAL READ
;
;
; LOGICAL READ
; TRANSFER RECORD FROM SECTOR BUFFER TO USER'S RECORD AREA,
; BYTE BY BYTE - THE SUBROUTINE AT READOP RETURNS THE NEXT BYTE
; FROM THE SECTOR BUFFER - IF THE BUFFER IS EXHAUSTED THE
; NEXT SECTOR WILL BE READ
;
	LD	B,(IX+09)	;GET RECORD SIZE
LOGIRD:	PUSH	HL		;SAVE USER'S RECORD AREA PTR
	PUSH	BC		;SAVE RECORD SIZE
	CALL	READOP		;GET A BYTE FROM SECTOR BUFFER
	POP	BC		;RECOVER RECORD SIZE
	POP	HL		;RECOVER RECORD AREA POINTER
	RET	NZ		;ABORT IF ANY READ ERRORS
	LD	(HL),A		;STORE BYTE IN USER'S BUFFER
	INC	HL		;BUMP BUFFER POINTER
	DJNZ	LOGIRD		;LOOP UNTIL RECORD MOVED
	RET
;
;
; JUMP TO WRITE RECORD ROUTINE
;
	Org	04439H
;
WRTREC:	JP	RECWRT		;GO WRITE THE RECORD
;
;
; WRITE RECORD PROCESSING
;
	Org	0478BH
;
RECWRT:	CALL	SAVREG		;SAVE CALLERS REGISTERS
;
;
; WRITE RECORD WITH OR WITHOUT VERIFY
; ENTRY:  A       - VERIFY FLAG
;478E
RECWRV:	LD	(VERIFL),A	;INITIALIZE VERIFY FLAG
	BIT	7,(IX+01)	;TEST IF PHYSICAL I/O
	JP	Z,PURGEL	;JUMP IF PHYSICAL
;
;
; LOGICAL WRITE
; TRANSFER RECORD FROM USER'S RECORD AREA TO SECTOR BUFFER,
; BYTE BY BYTE - THE SUBROUTINE AT WRITOP STORES THE NEXT BYTE
; IN THE SECTOR BUFFER - IF THE BUFFER IS FULL, IT IS WRITTEN
; TO DISK
;
	LD	B,(IX+09)	;GET RECORD SIZE
LOGWRT:	LD	A,(HL)		;GET BYTE FROM USER'S RECORD
	INC	HL		;BUMP TO NEXT DATA BYTE
	PUSH	HL		;SAVE USER'S RECORD AREA PTR
	PUSH	BC		;SAVE RECORD SIZE
	CALL	WRITOP		;STORE CHAR IN SECTOR BUFFER
	POP	BC		;RECOVER RECORD SIZE
	POP	HL		;RECOVER RECORD AREA POINTER
	RET	NZ		;ABORT IF ANY WRITE ERRORS
	DJNZ	LOGWRT		;LOOP UNTIL RECORD MOVED
	RET
;
;
; JUMP TO WRITE RECORD WITH VERIFY ROUTINE
;
	Org	0443CH
;
WRTREV:	JP	REVWRT		;GO DO THE VERIFY
;
;
; WRITE RECORD WITH VERIFY
;
	Org	047A8H
;
REVWRT:	CALL	SAVREG		;SAVE CALLER'S REGISTERS
	INC	A		;LOAD A 1 TO SHOW VERIFY
	JR	RECWRV		;THEN USE WRITE ROUTINE
;
;
; GENERAL PURPOSE DRIVER ENTRY
;47AE
GENDRV:	CALL	SAVREG		;SAVE CALLERS REGISTERS
	SET	7,(IX+01)	;SIGNAL LOGICAL I/O
	LD	A,B		;FETCH OPERATION CODE
	CP	2		;TEST FOR READ OR WRITE
	LD	A,C		;SAVE DATA FOR WRITE OP-CODE
	JR	NC,WRITOP	;GO IF WRITE OPERATION
;
;
; READ OPERATION REQUESTED
; EXIT:   A       - CHARACTER READ
;47BB
READOP:	CALL	TSTEOF		;TEST FOR END-OF-FILE
	RET	NZ		;RETURN IF EOF (A = 1CH OR 1DH)
	BIT	5,(IX+01)	;ANOTHER SECTOR FOR BUFFER?
	JR	Z,READON	;GET NEXT RECORD BYTE IF NOT
	CALL	RDNXTS		;READ NEXT SECTOR FROM FILE
	RET	NZ		;EXIT IF EOF OR OTHER ERROR
READON:	CALL	NEXTAD		;NEXT RECORD ADDRESS TO DE
	XOR	A		;CLEAR STATUS FLAGS
	LD	A,(DE)		;GET BYTE FROM SECTOR BUFFER
	PUSH	AF		;SAVE FETCHED CHARACTER
	INC	(IX+05)		;BUMP TO NEXT BUFFER BYTE
	JR	NZ,READOX	;JUMP IF BUFFER NOT EMPTY
	SET	5,(IX+01)	;SIGNAL READ REQUIRED
READOX:	POP	AF		;RESTORE FETCHED CHARACTER
	RET
;
;
; WRITE OPERATION REQUESTED
; ENTRY:  A       - BYTE TO BE WRITTEN
;47DA
WRITOP:	PUSH	AF		;SAVE BYTE TO BE WRITTEN
	BIT	5,(IX+01)	;TEST IF SECTOR BUFFER FULL
	JR	Z,WRITON	;JUMP IF ROOM IN SECTOR BUFFER
	CALL	NXTFIS		;READ NEXT FILE SECTOR
	JR	Z,WRITON	;GO IF NO READ ERRORS
	EX	(SP),HL		;CLEAR CHARACTER FROM STACK
	POP	HL		;CLEAN UP THE STACH
	RET
;
;
; CONTINUATION OF WRITE OPERATION
;47E9
WRITON:	CALL	NEXTAD		;GET NEXT POSITION TO DE
	POP	AF		;RECOVER SAVED CHARACTER
	LD	(DE),A		;STORE IT IN SECTOR BUFFER
	INC	DE		;BUMP BUFFER POSITION
	SET	4,(IX+01)	;FLAG BUFFER AS DIRTY
	INC	(IX+05)		;BUMP TO NEXT BUFFER POSITION
	CALL	TSTEOF		;TEST FOR EOF ACCESS PERMITTED
	JR	NZ,WRTNOP	;ABORT IF NOT PERMITTED
	BIT	6,(IX+01)	;RECORD NUMBER TO INCREMENT
	JR	NZ,WRITNU	;JUMP IF NOT UPDATING
WRTNOP:	LD	(IX+08),C	;UPDATE BUFFER EOF ADDRESS
WRITNU:	LD	A,C		;CURRENT SECTOR BUFFER OFFSET
	OR	A		;SET STATUS FLAGS FOR OFFSET
	JR	NZ,INCREX	;GO IF END NOT REACHED
	SET	5,(IX+01)	;FLAG BUFFER FULL, FORCE READ
	JR	PURGEL		;THEN GO PURGE THE BUFFER
;
;
; READ NEXT SECTOR FROM FILE
;480E
RDNXTS:	LD	A,(IX+01)	;FETCH ACCESS LEVEL TO A
	AND	00000111B	;ISOLATE PERMISSION FLAGS
	CP	00000110B	;TEST FOR READ/WRITE ACCESS
	JR	C,NOTRDP	;JUMP IF NO READ PROTECTION
	LD	A,25H		;PROTECTED FILE ILLEGAL ACCESS
	OR	A		;SET ERROR STATUS FLAGS
	RET
;
;
; NOT READ PROTECTED - TEST FOR END-OF-FILE
;481B
NOTRDP:	CALL	TSTEOF		;TEST FOR END-OF-FILE
	RET	NZ		;ABORT IF FILE END
	CALL	NXTFIS		;READ NEXT SECTOR FROM FILE
	RET	NZ		;EXIT IF ERROR DURING READ
;
;
; INCREMENT NEXT RECORD NUMBER
;4823
INCREC:	INC	(IX+10)		;BUMP NEXT RECORD NUMBER LSB
	JR	NZ,INCREX	;JUMP IF NOT OVERFLOW
	INC	(IX+11)		;BUMP NEXT RECORD NUMBER MSB
;
;
; PASS GOOD STATUS
; EXIT:   A       - ZERO
;         CF      - RESET
;         ZF      - SET
;482B
INCREX:	XOR	A		;SIGNAL GOOD STATUS - NO ERROR
	RET
;
;
; READ NEXT RECORD FROM FILE
;482D
NXTFIS:	CALL	LCTGAP		;GET NEXT SECTOR DISK ADDRESS
	RET	NZ		;EARLY RETURN IF ANY ERROR
	RES	5,(IX+01)	;CLEAR FORCE READ FLAG
	LD	L,(IX+03)	;SECTOR BUFFER ADDRESS LSB
	LD	H,(IX+04)	;SECTOR BUFFER ADDRESS MSB
	JP	RDSECT		;READ SECTOR AND RETURN
;
;
; PURGE LOGICAL SECTOR BUFFER IF NECESSARY
; ENTRY:  IX      - POINTER TO DEVICE CONTROL BLOCK
;483E
PURGEL:	LD	A,(IX+01)	;GET ACCESS FLAGS TO A
	AND	00000111B	;ISOLATE PERMISSIONS
	CP	00000101B	;TEST RUN ONLY OR RESTRICTED
	JR	C,PERMOK	;SKIP IF NEITHER
	LD	A,25H		;PROTECTED FILE ILLEGAL ACCESS
	OR	A		;RESET CARRY AND ZERO FLAGS
	RET
;
;
; FILE PERMISSIONS ARE NOT EXECUTE ONLY OR RESTRICTED ACCESS
;484B
PERMOK:	CALL	LCTGAP		;GET NEXT SECTOR DISK ADDRESS
	RET	NZ		;ABORT IF ANY ERRORS
	LD	L,(IX+03)	;SECTOR BUFFER ADDRESS LSB
	LD	H,(IX+04)	;SECTOR BUFFER ADDRESS MSB
	CALL	WRNSEC		;WRITE CURRENT SECTOR BUFFER
	RET	NZ		;ABORT IF WRITE ERROR
	RES	4,(IX+01)	;SIGNAL BUFFER AVAILABLE
	LD	A,0		;LOAD VERIFY FLAG TO A
VERIFL	Equ	$-1		;VERIFY WRITE FLAG STORAGE
	OR	A		;TEST IF VERIFY IS ON
	CALL	NZ,RDSECV	;READ AND VERIFY SECTOR
	RET	NZ		;ABORT IF READ ERROR
	CALL	TSTEOF		;TEST FOR END-OF-FILE
	JR	NZ,GOTEOF	;SKIP IF FILE END
	BIT	6,(IX+01)	;TEST IF POSITION CALL
	JR	NZ,INCREC	;THEN DO THE POSITIONING
GOTEOF:	INC	HL		;BUMP RECORD NUMBER
	LD	(IX+12),L	;UPDATE RECORD COUNT LSB
	LD	(IX+13),H	;UPDATE RECORD COUNT MSB
	JR	INCREC		;UPDATE THE COUNT AND EXIT
;
;
; PURGE SECTOR BUFFER IF NECESSARY
; ENTRY:  IX      - POINTER TO DEVICE CONTROL BLOCK
; EXIT:   A       - ZERO IF PHYSICAL ACCESS
;         ZF      - SET IF PHYSICAL ACCESS
;4878
PURGEB:	LD	A,(IX+01)	;FETCH ACCESS FLAGS TO A
	AND	10010000B	;MASK LOGICAL AND WRITE
	CP	10010000B	;TEST FOR LOGICAL ACCESS
	JR	Z,PURGEL	;GO IF LOGICAL
	XOR	A		;GOOD STATUS IF PHYSICAL
	RET
;
;
; GET ADDRESS OF NEXT RECORD IN SECTOR BUFFER, COMPUTE ADDRESS
; FOR NEXT BYTE TO BE FETCHED/STORED IN CURRENT LOGICAL RECORD
; EXIT:   DE      - NEXT RECORD ADDRESS
;4883
NEXTAD:	LD	A,(IX+05)	;GET CURRENT BYTE OFFSET
	LD	C,A		;SAVE THE BYTE IN C
	ADD	A,(IX+03)	;ADD IN BUFFER ADDRESS LSB
	LD	E,A		;COPY ADDRESS LSB TO E
	LD	A,(IX+04)	;GET BUFFER ADDRESS MSB
	ADC	A,0		;ADD ANY CARRY TO ADDRESS
	LD	D,A		;COPY ADDRESS MSB TO D
	RET
;
;
; SAVE CALLER'S REGISTERS AND SET UP EXIT PARAMETERS
; TEST IF THE CURRENT DEVICE IS OPEN AND ABORT IF IT IS CLOSED
; ENTRY:  DE      - POINTER TO DEVICE CONTROL BLOCK
;         (SP+00) - BUFFER ADDRESS
; EXIT:   IX      - POINTER TO DEVICE CONTROL BLOCK
;4892
SAVREG:	LD	A,(DE)		;GET DEVICE OPEN FLAG
	RLCA			;COPY OPEN BIT TO CARRY
	JR	NC,NOTOPN	;ABORT IF DEVICE NOT OPEN
;
;
; SAVE CALLER'S REGISTERS AND SET UP RESTORE ADDRESS
;4896
REGSAV:	POP	AF		;GET RETURN ADDRESS TO AF
	EX	(SP),HL		;SWAP BUFFER ADDRESS TO HL
	LD	(BUFADR),HL	;SAVE THE BUFFER ADDRESS
	LD	(DCBADR),DE	;SAVE THE DCB ADDRESS
	EX	(SP),HL		;SWAP BUFFER ADDRESS TO STACK
	PUSH	DE		;SAVE POINTER TO DCB
	EX	(SP),IX		;SWAP DCB POINTER AND IX
	PUSH	HL		;CALLER'S HL TO STACK
	PUSH	DE		;CALLER'S DE TO STACK
	PUSH	BC		;CALLER'S BC TO STACK
	PUSH	HL		;CREATE A HOLE ON THE STACK
	LD	HL,RSTREG	;POINT AT RESTORE SEQUENCE
	EX	(SP),HL		;SWAP ADDRESS AND HL REGISTER
	PUSH	AF		;PUT RETURN ADDRESS ON STACK
	XOR	A		;ZERO ACCUMULATOR AND FLAGS
	RET
;
;
; THE CURRENT DEVICE IS CLOSED, SO WE ABORT REGISTER SAVE
; EXIT:   A       - FILE NOT OPEN ERROR CODE
;         ZF      - CLEAR
;         CF      - CLEAR
;48AE
NOTOPN:	POP	AF		;REMOVE RETURN ADDRESS
	LD	A,26H		;LOAD ERROR CODE
	OR	A		;RESET ZERO AND CARRY FLAGS
	RET
;
;
; EXIT SEQUENCE TO RESTORE SAVED REGISTERS
; ENTRY:  (SP+00) - SAVED BC REGISTER
;         (SP+02) - SAVED DE REGISTER
;         (SP+04) - SAVED HL REGISTER
;         (SP+06) - SAVED IX REGISTER
;         (SP+08) - RETURN ADDRESS
; EXIT:   BC      - ORIGINAL BC REGISTER
;         DE      - ORIGINAL DE REGISTER
;         HL      - ORIGINAL HL REGISTER
;         IX      - ORIGINAL IX REGISTER
;48B3
RSTREG:	POP	BC		;RECOVER BC REGISTER
	POP	DE		;RECOVER DCB POINTER
	POP	HL		;RECOVER BUFFER POINTER
	POP	IX		;RECOVER IX REGISTER
	RET
;
;
; TEST FOR END-OF-FILE
; ENTRY:  IX      - POINTER TO DEVICE CONTROL BLOCK
; EXIT:   A       - 00H IF NOT AT THE END
;                 - 1CH IF AT THE END
;                 - 1DH IF BEYOND THE END
;48B9
TSTEOF:	LD	L,(IX+10)	;GET NEXT RECORD LSB
	LD	H,(IX+11)	;GET NEXT RECORD MSB
	LD	C,(IX+05)	;GET CURRENT RECORD OFFSET
	LD	A,H		;GET MSB OF NEXT RECORD
	CP	(IX+13)		;COMPARE TO END RECORD MSB
	JR	NZ,EOFLAG	;SKIP IF NOT THERE YET
	LD	A,L		;GET LSB OF NEXT RECORD
	CP	(IX+12)		;COMPARE TO END RECORD LSB
	JR	NZ,EOFLAG	;SKIP IF NOT THERE YET
	DEC	C		;ADJUST TO CURRENT RECORD
	CALL	TSTEOP		;TEST FOR SECTOR BUFFER EOF
	JR	NZ,EOFLAG	;SKIP IF NOT FILE END
	OR	00011100B	;SET END-OF-FILE FLAG
	RET
;
;
; BEYOND END-OF-FILE - RETURN THE STATUS
; ENTRY:  CF      - SET IF NOT EOF
;48D7
EOFLAG:	LD	A,1DH		;ASSUME BEYOND THE END
	RET	NC		;RETURN IF WE ARE
	XOR	A		;ELSE NOT THERE YET
	RET
;
;
; LOCATE 'GAP' FOR CURRENT RECORD NUMBER
;48DC
LCTGAP:	LD	L,(IX+10)	;GET NEXT RECORD NUMBER LSB
	LD	H,(IX+11)	;GET NEXT RECORD NUMBER MSB
	LD	A,5		;LOAD MODULO NUMBER
	CALL	DIVMOD		;COMPUTE RELATIVE GRANULE
	LD	(RELGRA),A	;SAVE THE GRANULE NUMBER
	PUSH	IX		;SAVE THE DCB POINTER
	EX	(SP),HL		;SWAP GRANULE AND DCB POINTER
	LD	BC,15		;OFFSET TO NEXT 'GAP' IN DCB
	ADD	HL,BC		;COMPUTE START OF 'GAP'S'
	POP	BC		;GET RELATIVE GRANULE NUMBER
	LD	A,5		;COUNT OF 'GAP' PAIRS TO SEARCH
	LD	DE,0		;STARTING GRANULE NUMBER
;
;
; TOP OF LOOP FOR TESTING "GAP'S"
;48F7
LCTGAL:	PUSH	AF		;SAVE COUNT OF "GAP'S" TESTED
	DEC	HL		;BACKSPACE FOR FIRST 'GAP' BYTE
	LD	A,(HL)		;LOAD FIRST BYTE OF EXTENT
	INC	HL		;BUMP TO SECOND EXTENT BYTE
	INC	A		;BUMP TRACK TO TEST FOR END
	JR	Z,ENDEXT	;GO IF END OF EXTENT
	PUSH	HL		;SAVE CURRENT 'GAP' ADDRESS
	LD	H,D		;GET CUMULATIVE GRANULES MSB
	LD	L,E		;GET CUMULATIVE GRANULES LSB
	XOR	A		;CLEAR THE CARRY FLAG
	SBC	HL,BC		;COMPARE REQUESTED TO TOTAL
	JR	C,BIGSUM	;SKIP IF OUT OF RANGE
	POP	HL		;RECOVER CURRENT 'GAP' ADDRESS
	JR	Z,COMPTS	;GO COMPUTE TRACK AND SECTOR
ENDEXT:	INC	HL		;BUMP TO THIRD EXTENT BYTE
	POP	AF		;GET COUNT OF "GAP'S" TESTED
	DEC	A		;COUNT ONE SET TESTED
	JR	Z,SEAREN	;SKIP IF ALL SETS TESTED
	LD	E,(HL)		;GET CUMULATIVE GRANULES LSB
	INC	HL		;BUMP TO GRANULE COUNT MSB
	LD	D,(HL)		;GET CUMULATIVE GRANULES MSB
	INC	HL		;BUMP TO NEXT 'GAP' FIRST BYTE
	INC	HL		;BUMP TO NEXT 'GAP' SECOND BYTE
	JR	LCTGAL		;THEN CONTINUE SCANNING "GAP'S"
;
;
; COME HERE IF THE RELATIVE GRANULE NUMBER IS
; GREATER THAN THE SUM OF ACCUMULATED GRANULES
;4915
BIGSUM:	INC	H		;IS DIFFERENC GREATER THAN 256
	LD	A,L		;NEGATIVE OF REQUESTED GRANULE
	POP	HL		;RECOVER POINTER TO GRANULE
	JR	NZ,ENDEXT	;GRANULE CAN'T BE IN THIS 'GAP'
;
;
; IF THE DIFFERENCE IS LESS THAN 256, COMPARE IT TO THE
; NUMBER OF GRANULES ASSIGNED TO THE CURRENT 'GAP' BECAUSE
; THE RELATIVE GRANULE MAY FALL WITHIN THE NEXT 'GAP'
;
	PUSH	DE		;SAVE GRANULE TOTAL TO FREE
	LD	E,A		;NEGATIVE OF REQUESTED GRANULE
	LD	A,(HL)		;GET TOTAL GRANULES - 1
	AND	00011111B	;ISOLATE GRANULE COUNT
	ADD	A,E		;COMPARE TO GRANULE COUNT
	LD	A,E		;RESTORE PREVIOUS COUNT
	POP	DE		;RECOVER TOTAL GRANULE COUNT
	JR	NC,ENDEXT	;IF GRANULE NOT IN THIS 'GAP'
	NEG			;CONVERT COUNT TO POSITIVE
	JR	COMPTS		;GO GOMPUTE TRACK AND SECTOR
;
;
; RELATIVE GRANULE NUMBER IS NOT IN CURRENT "GAP'S"
; SEARCH DIRECTORY ENTRIES BELONGING TO FILE FOR 'GAP'
; CONTAINING THE RELATIVE GRANULE NUMBER BEING SOUGHT
;4928
SEAREN:	CALL	FINGAP		;SEARCH FOR 'GAP' OWNING GRANULE
	RET	NZ		;ABORT IF DISK ERROR
	PUSH	HL		;SAVE GRANULE TRACK NUMBER
	LD	H,B		;REQUESTED RELATIVE GRANULE MSB
	LD	L,C		;REQUESTED RELATIVE GRANULE LSB
	XOR	A		;CLEAR CARRY FLAG
	SBC	HL,DE		;GRANULE SOUGHT MINUS TOTAL
	LD	A,L		;NUMBER OF GRANULES IN 'GAP'
	LD	(GRACNT),A	;TRACK ADDRESS UPDATE VALUE
	POP	HL		;RECOVER GRANULE TRACK NUMBER
	PUSH	DE		;SAVE CUMULATIVE GRANULE COUNT
	PUSH	IX		;SAVE DCB ADDRESS
	EX	(SP),HL		;SWAP DCB ADDRESS TO HL
	LD	DE,14		;START OF INDEX FOR "GAP'S"
	ADD	HL,DE		;INDEX INTO THE "GAP'S"
	POP	DE		;GET COUNT AND TRACK NUMBER
;
;
; SEARCH DCB FOR 'GAP' MATCHING NUMBER FROM 'FINGAP'
; WHEN CONTROL RETURNS, THE DCB IS SEARCHED FOR A MATCHING
; TRACK NUMBER AND GRANULE COUNT. IF ONE IS FOUND, CONTROL
; GOES TO 'ABSDAD' WHERE THE ABSOLUTE TRACK AND SECTOR NUMBER
; ARE COMPUTED. IF THE DCB DOES NOT CONTAIN THE TRACK NUMBER,
; THE "GAP'S" IN THE DCB ARE MOVED DOWN ONE ENTRY AND THE TRACK,
; COUNT AND CUMULATIVE TOTAL RETURNED FROM 'FINGAP' ARE COPIED
; TO THE FIRST 'GAP' ENTRY IN THE DCB
; EXIT:   HL      - TRACK AND GRANULE COUNT OWNING THE GRANULE
;         DE      - CUMULATIVE TRACK ADDRESSABLE GRANULE COUNT
;
	LD	B,5		;NUMBER OF "GAP'S" TO EXAMINE
DCBGAP:	LD	A,(HL)		;LOAD FIRST BYTE OF 'GAP'
	INC	HL		;BUMP THE FETCH ADDRESS
	CP	E		;DO TRACK NUMBERS MATCH?
	JR	NZ,DCBGAM	;JUMP IF THEY DON'T
	LD	A,(HL)		;ELSE FETCH THE COUNT
	XOR	D		;COMPARE WITH COUNT IN D
	AND	11100000B	;TEST IF COUNTS MATCH
	JR	Z,DCBGMA	;CONTINUE IF A MATCH
DCBGAM:	DEC	B		;DECREMENT THE 'GAP' COUNT
	JR	Z,DCBGMV	;MOVE "GAP'S" DOWN IF MISMATCH
	INC	HL		;BUMP ADDRESS TO NEXT 'GAP'
	INC	HL		;SKIP OVER THE TWO BYTE
	INC	HL		; TOTALS FOLLOWING EACH 'GAP'
	JR	DCBGAP		;THEN GO TEST NEXT 'GAP'
;
;
; MOVE "GAP'S" IN DCB DOWN ONE ENTRY
;4955
DCBGMV:	PUSH	DE		;SAVE CUMULATIVE GRANULE COUNT
	EX	DE,HL		;SWAP END OF "GAP'S" TO DE
	LD	HL,-4		;LOAD A MINUS FOUR
	ADD	HL,DE		;END ADDRESS OF "GAP'S" IN DCB
	LD	BC,12		;MOVE THREE SETS OF FOUR BYTES
	LDDR			;MOVE THE THREE SETS DOWN
	EX	DE,HL		;SWAP END OF "GAP'S" TO HL
	POP	BC		;GET CUMULATIVE GRANULE COUNT
	POP	DE		;GET REQUESTED GRANULE NUMBER
	JR	GETTRS		;UPDATE DCB GET TRACK/SECTOR
;
;
; GRANULE COUNTS MATCH
;4965
DCBGMA:	LD	(HL),D		;SAVE GRANULE COUNT IN DCB
	EX	DE,HL		;SWAP 'GAP' ENTRY AND DCB ADDR
	POP	AF		;CLEAN UP THE STACK
	JR	ABSDAD		;COMPUTE ABSOLUTE DISK ADDRESS
;
;
; CONVERT GRANULE NUMBER AND 'GAP' INTO ABSOLUTE TRACK AND SECTOR
;496A
COMPTS:	LD	(GRACNT),A	;SAVE GRANULE 'GAP' COUNT
	LD	B,(HL)		;NUMBER OF CONSECUTIVE SECTORS
	DEC	HL		;BACKSPACE TO TRACK NUMBER
	LD	C,(HL)		;GET TRACK NUMBER TO C
	INC	HL		;BACKUP TO SECTOR COUNT
	POP	AF		;GET EXTENT PAIRS COUNTED
	CPL			;MAKE COUNT NEGATIVE
	ADD	A,4		;SUBTRACT FOUR FROM IT
	JR	NC,FISEXT	;GO IF FIRST OR SECOND EXTENT
	INC	A		;GIVES FOUR, THREE, TWO, ONE
	RLCA			;MULTIPLY BY TWO
	RLCA			;MULTIPLY BY FOUR
	PUSH	BC		;SAVE TARGET 'GAP' (TRK, CNT)
	PUSH	DE		;SAVE CUMULATIVE GRANULE TOTAL
	EX	DE,HL		;SWAP 'GAP' ADDRESS TO DE
	LD	HL,-4		;LOAD A MINUS FOUR
	ADD	HL,DE		;BACKUP TO PREVIOUS EXTENT
	LD	B,0		;ZERO MSB OF BYTE COUNT
	LD	C,A		;BC HAS THE BYTE COUNT
	LDDR			;MOVE "GAP'S" AFTER TARGET DOWN
	EX	DE,HL		;TARGET 'GAP' END ADDRESS TO HL
	POP	DE		;CUMULATIVE GRANULE COUNT TO DE
	POP	BC		;TARGET 'GAP' (TRACK, COUNT)
	NOP			;DO NOTHING WHATSOEVER
GETTRS:	LD	(HL),B		;TARGET 'GAP' GRANULE COUNT
	DEC	HL		;BACKUP TO PREVIOUS ENTRY
	LD	(HL),C		;TARGET 'GAP' TRACK NUMBER
	DEC	HL		;BACKUP TO PREVIOUS ENTRY
	LD	(HL),D		;CUMULATIVE GRANULE COUNT MSB
	DEC	HL		;BACKUP TO PREVIOUS ENTRY
	LD	(HL),E		;CUMULATIVE GRANULE COUNT LSB
FISEXT:	LD	H,B		;GRANULE COUNT FOR THIS 'GAP'
	LD	L,C		;TRACK NUMBER FOR CURRENT 'GAP'
;
;
; BEGIN DISK ADDRESS TRANSLATION
; ENTRY:  H       - GRANULE COUNT FOR THIS 'GAP'
;         L       - TRACK NUMBER FOR CURRENT 'GAP'
; EXIT:   C       - DRIVE NUMBER FOR FILE
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
;         H       - UNCHANGED
;         L       - UNCHANGED
;4993
ABSDAD:	LD	A,H		;GET GRANULE COUNT TO A
	RLCA			;SHIFT FIRST
	RLCA			; GRANULE OFFSET
	RLCA			;  INTO THREE LS BITS
	AND	00000111B	;ISOLATE FIRST GRANULE OFFSET
	ADD	A,0		;ADD GRANULE COUNT TO OFFSET
GRACNT	Equ	$-1		;COUNT OF GRANULES IN 'GAP'
	LD	E,A		;SAVE GRANULE WITHIN 'GAP'
	AND	11111110B	;ADD OVERFLOW TO START TRACK
	RRCA			; ISOLATE AND RIGHT JUSTIFY
	LD	(TRKOFS),A	;SAVE FOR ADDING TO START TRACK
	LD	A,E		;REFETCH 'GAP' GRANULE NUMBER
	AND	00000001B	;ISOLATE ODD OR EVEN BIT
	LD	E,A		;COPY THE BIT TO E
	RLCA			;MULTIPLY BY TWO
	RLCA			;MULTIPLY BY FOUR
	ADD	A,E		;MULTIPLY BY FIVE
	ADD	A,0		;GET ABSOLUTE SECTOR ON TRACK
RELGRA	Equ	$-1		;STORAGE FOR RELATIVE GRANULE
	LD	E,A		;SAVE SECTOR NUMBER IN E
	LD	A,L		;GET TRACK NUMBER TO A
	ADD	A,0		;ADD TRACK INCREMENT IN 'GAP'
TRKOFS	Equ	$-1		;OFFSET FOR STARTING TRACK
	LD	D,A		;COPY TRACK NUMBER TO D
	LD	C,(IX+06)	;GET DRIVE NUMBER FOR FILE
	XOR	A		;THEN SIGNAL GOOD STATUS
	RET
;
;
; FIND 'GAP' FOR RELATIVE GRANULE NUMBER BY SEARCHING DIRECTORY
; ENTRIES BELONGING TO FILE. READ OVERFLOW ENTRIES IF NECESSARY
; ENTRY:  BC      - GRANULE NUMBER
; EXIT:   DE      - CUMULATIVE NUMBER OF GRANULES THRU THIS 'GAP'
;         H       - COUNT OF GRANULES ASSIGNED TO TRACK
;         L       - TRACK NUMBER
;49B5
FINGAP:	PUSH	BC		;SAVE REQUESTED GRANULE
	LD	DE,0		;INITIALIZE SKIPPED GRANULES
	LD	B,(IX+07)	;GET DIRECTORY SECTOR TO B
LOCOVE:	LD	A,B		;COPY DIRECTORY SECTOR TO A
	LD	(DIRIDX),A	;SAVE DIRECTORY SECTOR INDEX
	LD	C,(IX+06)	;GET UNIT NUMBER TO C
	CALL	REDDIR		;READ FILE DIRECTORY ENTRY
	LD	BC,22		;OFFSET TO EXTENT PAIRS
	ADD	HL,BC		;ADDRESS OF 'GAP' EXTENTS
	EX	DE,HL		;ADDRESS OF THE PAITS TO DE
	POP	BC		;REQUESTED GRANULE NUMBER
	RET	NZ		;ABORT IT DIRECTORY READ ERROR
FNDEOV:	LD	A,(DE)		;GET FIRST BYTE OF THE 'GAP'
	CP	11111110B	;TEST FOR OVERFLOW EXTENT PAIR
	JR	NC,LOCNEW	;SKIP IF END OR OVERFLOW
	INC	DE		;ELSE BUMP TO NEXT 'GAP' BYTE
	LD	A,(DE)		;THEN FETCH GRANULE COUNT
	PUSH	HL		;SAVE SKIPPED GRANULE COUNT
	AND	00011111B	;ISOLATE GRANULE COUNT - 1
	INC	A		;BUMP TO GET TRUE COUNT
	ADD	A,L		;ADD TO PASSED GRANULE COUNT
	LD	L,A		;UPDATE GRANULES SKIPPED LSB
	JR	NC,NOTOFL	;SKIP IF NOT OVERFLOW
	INC	H		;ELSE BUMP SKIPPED GRANULES MSB
NOTOFL:	PUSH	HL		;SAVE SKIPPED GRANULE COUNT
	DEC	HL		;ZERO BASE SKIPPED GRANULES
	XOR	A		;CLEAR CARRY FLAG
	SBC	HL,BC		;COMPARE THE GRANULE COUNTS
	POP	HL		;GET SKIPPED GRANULE COUNT
	JR	NC,GINGAP	;SKIP IF GRANULE IN THIS 'GAP'
	INC	DE		;BUMP TO NEXT 'GAP' SECOND BYTE
	POP	AF		;CLEAN UP THE STACK
	JR	FNDEOV		;UNTIL FOUND, END OR OVERFLOW
;
;
; GRANULE IS IN THIS 'GAP'
;
GINGAP:	POP	HL		;REQUESTED GRANULE NUMBER TO HL
	EX	DE,HL		;GAP ADDRESS TO HL, COUNT TO DE
	LD	A,(HL)		;COUNT OF ASSIGNED GRANULES
	DEC	HL		;BACKSPACE TO 'GAP' FIRST BYTE
	LD	L,(HL)		;GET TRACK NUMBER TO L
	LD	H,A		;ASSIGNED GRANULES COUNT
	XOR	A		;SIGNAL NO ERROR
	RET
;
;
; LOCATE OVERFLOW ENTRY OR ASSIGN A NEW 'GAP'
;49F1
LOCNEW:	PUSH	BC		;SAVE REQUESTED GRANULE NUMBER
	EX	DE,HL		;SWAP SECTOR ADDRESS, SKIPPED
	JR	NZ,ASSGAP	;SKIP IF 'GAP' ASSIGNED, WRITE
	INC	HL		;OVERFLOW ENTRY FOUND
	LD	B,(HL)		;OFFSET TO OVERFLOW ENTRY
	JR	LOCOVE		;GO LOCATE OVERFLOW "GAP'S"
;
;
; ASSIGN A 'GAP'
;49F9
ASSGAP:	CALL	ASSGRA		;ASSIGN NEXT 'GAP'
	POP	BC		;GET REQUESTED GRANULE
	RET	NZ		;ABORT IF ANY ERRORS
	JR	FINGAP		;ELSE RESTART THE SCAN
;
;
; GRANULE ASSIGNMENT
;
; THIS POINT IS REACHED WHEN A GRANULE NUMBER REQUIRED FOR A
; WRITE DOES NOT EXIST IN THE 'GAP' CHAIN FOR THE FILE. THIS
; SITUATION WILL OCCUR WHEN A FILE IS BEING CREATED, OR IF A
; FILE HAS FIFTY SECTORS ASSIGNED TO IT, AND A REQUEST TO WRITE
; SECTOR SIXTY WAS RECEIVED, FOR EXAMPLE, GRANULES FOR THE
; SPACE BETWEEN SECTORS FIFTY AND SIXTY WOULD BE ASSIGNED
;
; ASSIGNMENT CAN TAKE TWO FORMS. FIRST IS WHEN A GRANULE IS
; ASSIGNED TO AN EXISTING 'GAP'. THE SECOND OCCURS IF IT IS NOT
; POSSIBLE TO ADD GRANULES TO A 'GAP'. THIS CASE OCCURS WHEN A
; 'GAP' IS FULL, THIRTY-TWO GRANULES HAVE BEEN ASSIGNED, OR WHEN
; IT IS IMPOSSIBLE TO ASSIGN THE NEXT CONSECUTIVE GRANULE TO AN
; EXISTING 'GAP'. IN BOTH CASES, A NEW 'GAP' MUST BE CREATED AND
; ADDED TO THE DEVICE CONTROL BLOCK. IF THE 'GAP' AREA IN THE
; DCB IS FULL, AN OVERFLOW DIRECTORY ENTRY IS CREATED
; ENTRY:  BC      - REQUESTED GRANULE NUMBER (TARGET GRANULE)
;         DE      - NUMBER OF GRANULES PRESENTLY ASSIGNED
;         HL      - ADDRESS OF FILE ENTRY IN DIRECTORY SECTOR
;4A00
ASSGRA:	PUSH	BC		;SAVE TARGET GRANULE NUMBER
	LD	B,(IX+07)	;GET OVERFLOW ENTRY TO B
	LD	C,(IX+06)	;GET DRIVE NUMBER TO C
	CALL	REDGAT		;READ THE 'GAT' SECTOR
	POP	BC		;RECOVER TARGET GRANULE
	RET	NZ		;ABORT IF ERROR READING 'GAT'
	PUSH	HL		;SAVE DIRECTORY SECTOR ADDRESS
	LD	H,B		;GET TARGET GRANULE MSB TO H
	LD	L,C		;GET TARGET GRANULE LSB TO L
	XOR	A		;CLEAR THE CARRY FLAG
	SBC	HL,DE		;TARGET LESS ASSIGNED GRANULES
	LD	B,H		;DIFFERENCE BETWEEN REQUESTED
	LD	C,L		; AND CURRENT GRANULE NUMBER
	INC	BC		;GET TRUE COUNT TO BC
	POP	DE		;LOAD DIRECTORY SECTOR ENTRY
	INC	DE		;BUMP TO LAST 'GAP' SECOND BYTE
	INC	BC		;BUMP GRANULE COUNT TO ALLOCATE
	LD	A,(IX+07)	;DIRECTORY ENTRY SECTOR NUMBER
	AND	00000111B	;ISOLATE 'GAT' START POSITION
	RLCA			;MULTIPLY POSITION BY TWO
	RLCA			;MULTIPLY POSITION BY FOUR
	LD	L,A		;FORM 'GAT' SEARCH ADDRESS
	LD	H,High GATBUF	;POINTER INTO SECTOR BUFFER
	PUSH	BC		;GRANULES AND RELATIVE GRANULE
;
;
; TEST FOR INITIAL 'GAP' ASSIGNMENT, OR 'GAP' FULL
;
	LD	A,E		;CURRENT 'GAP' ADDRESS LSB
	AND	00011110B	;ISOLATE THE LOW BYTE
	CP	16H		;TEST FOR FIRST 'GAP' ADDRESS
	JR	Z,GRANAS	;SKIP IF FIRST 'GAP' ASSIGNMENT
	DEC	E		;BACKSPACE TO
	DEC	E		; TO PREVIOUS 'GAP'
ASSANO:	LD	A,(DE)		;CONSECUTIVE GRANULES - 1
	AND	00011111B	;ISOLATE GRANULE COUNT
	INC	A		;MAKE IT A TRUE COUNT
	LD	C,A		;COPY THE COUNT TO C REGISTER
	CP	32		;TEST GRANULE COUNT FIELD FULL
	JR	Z,GAPASG	;ASSIGN NEW 'GAP' IF FULL
;
;
; 'GAP' NOT FULL, TRY TO ASSIGN A GRANULE
;
	LD	A,(DE)		;CONSECUTIVE GRANS ASSIGNED
	AND	11100000B	;ISOLATE FIRST GRAN OFFSET
	RLCA			;ISOLATE STARTING
	RLCA			; SECTOR OFFSET AND
	RLCA			;  MOVE TO BIT ZERO
	ADD	A,C		;TOTAL GRANS ASSIGNED TO 'GAP'
	LD	B,A		;COPY THE GRANULE COUNT TO B
	SRL	B		;DIVIDE GRANULE COUNT BY TWO
	AND	00000001B	;ISOLATE GRANULE BIT
	LD	C,A		;SAVE BIT MASK FOR GRANULE
	DEC	DE		;BACKSPACE TO FIRST 'GAP' BYTE
	LD	A,(DE)		;LOAD STARTING TRACK NUMBER
	INC	DE		;BUMP TO SECOND 'GAP' BYTE
	ADD	A,B		;NUMBER OF CONSECUTIVE TRACKS
	LD	L,A		;FORM 'GAT' ADDRESS LSB
	LD	H,High GATBUF	;LOAD 'GAT' ADDRESS MSB
	CP	NUMTRK		;TEST IF END OF 'GAT' REACHED
	JR	NC,GAPASG	;THEN MUST START ANOTHER 'GAP'
;
;
; TEST IF REQUIRED GRANULE IS AVAILABLE
;
	LD	A,C		;BIT NEEDED IN 'GAT' ENTRY
	LD	B,(HL)		;GET TRACK AVAILABLE
	CALL	BITESB		;TEST NEEDED GRANULE AVAILABLE
	JR	Z,FIRASS	;SKIP IF IT IS
;
;
; ASSIGN A NEW 'GAP'
;4A54
GAPASG:	INC	E		;POINT AT SECOND BYTE
	INC	E		; OF NEXT 'GAP'
	LD	A,E		;COPY THE POINTER TO A
	AND	00011110B	;ISOLATE LSB OF ADDRESS
	CP	00011110B	;TEST FOR LAST PAIR IN ENTRY
	JR	NZ,GRANAS	;SKIP IF NOT LAST PAIR
;
;
; 'GAP' AREA IS FULL - CREATE AN OVERFLOW ENTRY
;
	CALL	GATWRT		;REWRITE 'GAT' AND DIR ENTRY
	POP	BC		;CLEAR STACK IN CASE OF ERROR
	RET	NZ		;ABORT IF WRITE ERROR
	PUSH	BC		;SAVE TRAGET GRANULE NUMBER
	CALL	BLDOVF		;BUILD OVERFLOW DIR ENTRY
	POP	BC		;GET TARGET GRANULE NUMBER
	RET	NZ		;ABORT IF ENTRY CREATE ERROR
	JP	FINGAP		;RESTART 'GAP' ASSIGNMENT
;
;
; CALL SYS2 TO BUILD OVERFLOW ENTRY
;4A6B
BLDOVF:	LD	A,0B4H		;LOAD REQUEST CODE 30
	RST	28H		;BUILD THE OVERFLOW ENTRY
;
;
; GRANULE ASSIGNMENT FOR NEW 'GAP'
;4A6E
GRANAS:	LD	B,2		;LOAD LOOP COUNT
GRANAL:	LD	A,L		;GET CURRENT TRACK TO A
	CP	NUMTRK		;TEST IF END OF 'GAT'
	JR	NC,GRANAR	;GO IF ALL TRACKS TESTED
	LD	A,(HL)		;ELSE FETCH A 'GAT' ENTRY
	INC	A		;TEST IF ANY GRANS AVAILABLE
	JR	NZ,SOMEAV	;SKIP IF SOME AVAILEBLE
	INC	L		;ELSE BUMP TO NEXT ENTRY
	JR	GRANAL		;LOOP UNTIL TABLE EXHAUSTED
GRANAR:	LD	L,Low GATBUF	;RESTART SCAN FROM BEGINNING
	DJNZ	GRANAL		;LOOP UNTIL DONE TWICE
	POP	BC		;GRANULES AND RELATIVE GRANULE
	CALL	GATWRT		;UPDATE 'GAT' AND DIRECTORY
	RET	NZ		;ABORT IF ERROR WRITING 'GAT'
	LD	A,1BH		;DISK SPACE FULL ERROR
	OR	A		;SET ERROR STATUS
	RET
;
;
; MAKE INITIAL 'GAP' BYTE TWO ASSIGNMENT
;4A89
SOMEAV:	LD	A,-1		;LOAD ALL BITS SET VALUE
	LD	(DE),A		;STORE IN SECOND BYTE OF 'GAP'
	LD	C,0		;LOAD BIT NUMBER TO C
	LD	B,(HL)		;LOAD 'GAT' ENTRY TO BIT TEST
RETEST:	LD	A,C		;LOAD BIT NUMBER TO A
	CALL	BITESB		;TEST BIT IN THE BYTE
	JR	Z,FIRASS	;GO IF FIRST GRANULE ASSIGNED
	LD	A,(DE)		;TRACK ASSIGNMENT SECOND GRAN
	ADD	A,00100000B	;SET BIT FIVE OF 'GAP' ENTRY
	LD	(DE),A		;SAVE SECOND BYTE OF 'GAP'
	INC	C		;BUMP TO NEXT BIT IN 'GAT'
	JR	RETEST		;LOOP BACK TO RETEST
FIRASS:	LD	A,C		;LOAD BIT NUMBER TO A
	CALL	SELMSK		;TURN ON BIT IN ACCUMULATOR
	OR	(HL)		;COMBINE WITH 'GAT' ENTRY
	LD	(HL),A		;SAVE UPDATED 'GAT' ENTRY
	DEC	E		;SKIP TO 'GAP' FIRST ENTRY
	LD	A,(DE)		;GET TRACK NUMBER FROM 'GAP'
	INC	A		;TEST NEW TRACK ASSIGNMENT
	JR	NZ,NEWTAS	;SKIP IF NEW TRACK ASSIGNMENT
	LD	A,L		;GET TRACK NUMBER TO A
	LD	(DE),A		;SAVE THE TRACK NUMBER
NEWTAS:	INC	E		;BUMP TO 'GAP' SECOND BYTE
	LD	A,(DE)		;GET SECOND BYTE OF 'GAP'
	INC	A		;BUMP ASSIGNED GRANULE COUNT
	LD	(DE),A		;RESTORE THE COUNT
	POP	BC		;COUNT OF GRANS TO ALLOCATE
	DEC	BC		;DECREMENT GRANULE COUNT
	PUSH	BC		;SAVE UPDATED COUNT
	LD	A,B		;GET MSB TO A FOR TEST
	OR	C		;TEST IF WE WE ARE DONE
	JP	NZ,ASSANO	;ALLOCATE ANOTHER IF MORE
	POP	BC		;CLEAR OUT THE STACK
;
;
; UPDATE 'GAT' AND DIRECTORY
;4AB6
GATWRT:	LD	C,(IX+06)	;GET DRIVE NUMBER TO C
	CALL	WRTGAT		;WRITE UPDATED 'GAT' SECTOR
	RET	NZ		;ABORT IF WRITE ERROR
	LD	B,0		;LOAD SECTOR AND OFFSET
DIRIDX	Equ	$-1		;DIRECTORY SECTOR INDEX
	JR	WRTDIR		;WRITE THE DIRECTORY
;
;
; READ DIRECTORY SECTOR ENTRY
; ENTRY:  B       - HASH INDEX TABLE INDEX
;         C       - UNIT NUMBER
; EXIT:   HL      - INDEX TO THE ENTRY
;4AC1
