; CALL INTERRUPT TASK ROUTINE
;4538
DOTASK:	PUSH	AF		;SAVE AF REGISTER
	PUSH	BC		;SAVE BC REGISTER
	PUSH	DE		;SAVE DE REGISTER
	PUSH	HL		;SAVE HL REGISTER
	PUSH	IX		;SAVE IX REGISTER
	LD	DE,DOTASR	;LOAD RETURN ADDRESS
	PUSH	DE		;SAVE IT ON STACK
	LD	E,(HL)		;LOAD LSB OF TASK ADDRESS
	INC	L		;BUMP TO MSB OF ADDRESS
	LD	D,(HL)		;LOAD MSB OF TASK ADDRESS
	EX	DE,HL		;MOVE ADDRESS TO HL
	JP	(HL)		;JUMP TO INTERRUPT HANDLER
;
;
; RETURN POINT FROM INTERRUPT TASK ROUTINES
;4547
DOTASR:	POP	IX		;RECOVER IX REGISTER
	POP	HL		;RECOVER HL REGISTER
	POP	DE		;RECOVER DE REGISTER
	POP	BC		;RECOVER BC REGISTER
	POP	AF		;RECOVER AF REGISTER
	JR	INTSRN		;LOOK FOR MORE INTERRUPTS
;
;
; ACTIVE <BREAK> KEY DETECTED DURING INTERRUPT PROCESSING
; TEST IF DEBUG IS ACTIVE - RETURN TO POINT OF INTERRUPT IF
; NOT, ELSE CLEAR ACTIVE FLAG, THEN LOAD AND EXECUTE DEBUG
;454F
DOBREK:	LD	HL,DEBUGF	;POINT TO DEBUG ACTIVE FLAG
	XOR	A		;LOAD COMPARISON VALUE
	CP	(HL)		;TEST IF DEBUG ACTIVE
	JR	Z,INTSRX	;JUMP IF INACTIVE
	LD	(HL),A		;RESET FLAG TO INACTIVE
	INC	L		;BUMP TO MSB OF LOAD REQ ADDR
	LD	A,(HL)		;LOAD LSB OF ADDRESS
	INC	L		;BUMP TO MSB OF ADDRESS
	LD	H,(HL)		;LOAD MSB OF ADDRESS
	LD	L,A		;ADDRESS NOW IN HL
	POP	AF		;RESTORE INTERRUPT CONTEXT
	EX	(SP),HL		;MOVE ADDRESS TO STACK
	EI			;RE-ENABLE INTERRUPTS
	RET
