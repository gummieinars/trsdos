	INC	DE		;BUMP STORAGE POINTER
	DJNZ	PATZER		;LOOP UNTIL 8 BYTES ZEROED
	LD	A,-1		;LOAD VALUE TO STORE
	LD	B,16		;NUMBER OF BYTES TO STORE
