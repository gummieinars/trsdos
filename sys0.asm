;
; MAIN DISK DRIVER FOR READ/WRITE OPERATIONS
; ENTRY:  A       - CONTROLLER READ/WRITE CODE
;         C       - UNIT NUMBER
;         D       - TRACK NUMBER
;         E       - SECTOR NUMBER
;         (SP+00) - POINTER TO PARAMETERS
;         SP+00   - ERROR RETRY COUNT
;         SP+01   - ERROR CODE BIAS VALUE
;         SP+02   - LD A,(BC) IF WRITE, LD A,(DE) IF READ
;         SP+03   - LD (DE),A IF WRITE, LD (BC),A IF READ
; EXIT:   CF      - SET IF ERROR, RESET OTHERWISE
;         A       - 0 IF NO ERROR, ERROR CODE OTHERWISE
;4671
DSKDRV:	LD	(RWCODE),A	;SAVE DISK CONTROLLER OP CODE
	EX	(SP),HL		;SAVE BUFFER PTR, GET PARM PTR
	PUSH	BC		;SAVE CALLER'S BC
	LD	B,(HL)		;FETCH RETRY COUNT
	INC	HL		;BUMP PARAMETER POINTER
	LD	A,(HL)		;GET BIAS COUNT
	INC	HL		;BUMP PARAMETER POINTER
	LD	(ERBIAS),A	;SAVE ERROR BIAS VALUE
	LD	A,(HL)		;GET FETCH/STORE INSTRUCTION
	INC	HL		;BUMP PARAMETER POINTER
	LD	H,(HL)		;GET FETCH/STORE INSTRUCTION
	LD	L,A		;ASSEMBLE TRANSFER CODES
