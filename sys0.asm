; SELECT DISK DRIVE
; ENTRY:  C       - DRIVE TO SELECT
;
	Org	04600H
;
SELDRV:	PUSH	HL		;SAVE CALLER'S HL
	LD	HL,LASDRV	;ADDRESS OF LAST DRIVE SELECTED
	LD	A,(HL)		;LOAD LAST DRIVE SELECTED
	CP	C		;COMPARE WITH DRIVE REQUESTED
	JR	NZ,SELDDI	;JUMP IF DIFFERENT DRIVE
	INC	L		;BUMP TO LAST DRIVE SELECT MASK
	LD	A,(HL)		;LOAD DRIVE SELECT MASK
	JR	SELDSA		;THEN GO SELECT DRIVE
SELDDI:	LD	(HL),C		;UPDATE LAST DRIVE SELECTED
	LD	H,High LASTRK	;FORM LAST TRACK TABLE ORIGIN
	LD	L,A		;FORM ORIGIN OF CURRENT DRIVE
	CALL	WAITNB		;WAIT FOR CONTROLLER NOT BUSY
	LD	A,(TRKREG)	;LOAD CURRENT TRACK
	LD	(HL),A		;SAVE LAST TRACK SELECTED
	LD	A,C		;GET DRIVE NUMBER TO A
	LD	L,A		;REFORM LAST TRACK ADDRESS
	LD	A,(HL)		;GET LAST TRACK SELECTED
	LD	(TRKREG),A	;UPDATE TRACK REGISTER
	LD	A,C		;GET DRIVE NUMBER TO A
	CALL	SELMSK		;CONSTRUCT DRIVE SELECT MASK
	LD	(DRVMSK),A	;SAVE FOR FUTURE USE
SELDSA:	LD	L,A		;SAVE MASK FOR LATER
	LD	A,(CSTREG)	;GET DRIVE STATUS
	RLCA			;TEST NOT READY BIT
	LD	A,L		;RESTORE DRIVE SELECT MASK
	LD	(DRVREG),A	;SELECT THE DRIVE
	JR	NC,SELDEX	;JUMP IF DRIVE READY
	LD	HL,0		;LOAD DELAY COUNTER
SELDDL:	DEC	HL		;DECREMENT THE COUNTER
	LD	A,H		;GET MSB TO A FOR TEST
	OR	L		;TEST IF COUNTER ZERO
	JR	NZ,SELDDL	;LOOP IF NOT ZERO
SELDEX:	POP	HL		;RESTORE CALLER'S HL
	RET
