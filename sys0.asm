	INC	L		;BUMP TO MONTH
	INC	(HL)		;INCREMENT MONTH VALUE
	LD	A,(HL)		;FETCH MONTH VALUE
	SUB	13		;TEST FOR YEAR ROLLOVER
	RET	C		;EXIT IF NOT END OF YEAR
	LD	(HL),1		;RESET MONTH TO 1
	DEC	L		;BACKSPACE OVER MONTH
	DEC	L		;THEN OVER DAY
	INC	(HL)		;THEN INCREMENT YEAR
	RET
