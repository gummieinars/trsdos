;         HL      - BUFFER POINTER
; EXIT:   A       - UNCHANGED
;         HL      - INCREMENTED BY ONE
;4CFD
STOBYT:	LD	(HL),A		;STORE CHARACTER IN BUFFER
	INC	HL		;BUMP BUFFER POINTER
	RET
