;
; CONVERT A BINARY WORD TO ASCII HEX AND STORE IN A BUFFER
; ENTRY:  DE      - WORD TO CONVERT AND STORE
;         HL      - POINTER TO BUFFER MEMORY
; EXIT:   HL      - INCREMENTED BY FOUR
;
	LD	A,D		;GET PROGRAM COUNTER MSB
	CALL	BINHEX		;STORE ADDRESS MSB ON SCREEN
	LD	A,E		;GET PROGRAM COUNTER LSB
;
;
; CONVERT A BINARY BYTE TO ASCII HEX AND STORE IN A BUFFER
; ENTRY:  A       - BYTE TO CONVERT AND STORE
;         HL      - POINTER TO BUFFER MEMORY
; EXIT:   HL      - INCREMENTED BY TWO
;4CEA
BINHEX:	PUSH	AF		;SAVE BINARY BYTE
	RRA			; ROTATE
	RRA			;  MS NYBBLE
	RRA			;   INTO
	RRA			;    LS NYBBLE
	CALL	NYBHEX		;CONVERT AND STORE NYBBLE
	POP	AF		;RECOVER SAVED BYTE
;
;
; CONVERT A BINARY NYBBLE TO ASCII HEX AND STORE IN A BUFFER
; ENTRY:  A       - NYBBLE TO CONVERT AND STORE
;         HL      - POINTER TO BUFFER MEMORY
; EXIT:   HL      - INCREMENTED BY ONE
;4CF3
NYBHEX:	AND	00001111B	;MASK TO LS NYBBLE
	ADD	A,'0'		;CONVERT TO ASCII
	CP	'9'+1		;TEST IF NUMERIC HEX
	JR	C,STOBYT	;STORE CHARACTER IF IT IS
	ADD	A,'A'-'9'-1	;ELSE ADD ALPHA HEX BIAS 7
;
;
; STORE A BYTE IN A BUFFER
