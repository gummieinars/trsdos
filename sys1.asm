;
; OVERLAY REQUEST 10 - NORMAL ENTRY TO DOS COMMAND PROCESSOR
;
NORMEN:
;
;
; OVERLAY REQUEST 20 - ERROR ENTRY TO DOS COMMAND PROCESSOR
;4E1F
ERROEN:	EI			;ENABLE INTERRUPTS
	LD	SP,STACKT	;SET UP STACK POINTER
	LD	HL,KIBDCB+01	;POINT AT DCB ACCESS FLAGS
	BIT	5,(HL)		;REDUNDANT INSTRUCTION
	LD	HL,SYSCON	;SYSTEM CONDITION FLAGS
	BIT	7,(HL)		;TEST IF 'DEBUG' ACTIVE
	JR	Z,DEBINA	;SKIP IF INACTIVE
	LD	A,0C3H		;LOAD 'JP' OP-CODE
	LD	(DEBUGF),A	;ACTIVATE 'DEBUG' JUMP
DEBINA:	BIT	5,(HL)		;TEST FOR PROGRAM CHAINING
	JR	Z,CHAINA	;SKIP IF CHAINING INACTIVE
	LD	A,(KROSEV)	;LOAD KEYBOARD ROW BITS
	AND	00000100B	;TEST IF <BREAK> KEY HIT
	JP	NZ,ERRENT	;THEN ABORT TO ERROR HANDLER
CHAINA:	LD	HL,DOSREM	;POINT AT 'DOS READY' PROMPT
	CALL	DOPMSG		;DISPLAY PROMPT STRING
	LD	HL,CMLBUF	;POINT AT COMMAND LINE BUFFER
	LD	B,63		;LOAD BUFFER SIZE TO B
	CALL	KBLINE		;INPUT AND FILL BUFFER
;
;
; OVERLAY REQUEST 30 - EXECUTE A DOS COMMAND
; ENTRY:  HL      - POINTER TO COMMAND LINE BUFFER
;4E4E
CMDEXE:	LD	BC,DOSENT	;LOAD DOS SUCCESS RETURN
	PUSH	BC		;PUT ADDRESS ON THE STACK
	LD	DE,SYSDCB	;POINT AT SYSTEM DCB
	CALL	PARSCL		;PARSE COMMAND LINE TO DCB
	JP	NZ,SYNERR	;ABORT IF ILLEGAL CHARACTER
	LD	A,(DE)		;GET COMMAND LINE CHARACTER
	CP	'*'		;TEST IF DEVICE INDICATOR
	JP	Z,SYNERR	;WE HAVE A SYNTAX ERROR IF SO
	PUSH	HL		;SAVE BUFFER POINTER
	LD	BC,ONECMD	;SYS1/SYS COMMAND ADDRESSES
	CALL	TSTCMD		;TEST FOR THE COMMANDS
	JR	Z,EXECMD	;THEN EXECUTE THE COMMAND
	LD	BC,SIXCMD	;SYS6/SYS COMMAND ADDRESSES
	CALL	TSTCMD		;TEST FOR THE COMMANDS
	JR	Z,EXECMD	;THEN EXECUTE THE COMMAND
;
;
; COMMAND IS NEITHER SYS1 OR SYS6 COMMAND
; ADD 'CMD' SUFFIX TO FILE NAME AND LOAD FILE FROM DISK
;
	LD	A,(SYSCON)	;LOAD SYSTEM CONDITION FLAGS
	RES	4,A		;CLEAR SYS6/SYS LOADED BIT
	LD	(SYSCON),A	;UPDATE CONDITION FLAGS
	LD	HL,CMDEXM	;POINT AT 'CMD' EXTENSION
	CALL	ADDEXT		;ADD EXTENSION TO FILE NAME
	POP	HL		;RECOVER BUFFER POINTER
	JP	LODEXE		;LOAD AND EXECUTE THE FILE
;
;
; COMMAND WAS FOUND - EXECUTE THE COMMAND
; ENTRY:  DE      - COMMAND EXECUTION ADDRESS
;4E84
EXECMD:	POP	HL		;RECOVER BUFFER POINTER
	PUSH	DE		;PUT COMMAND ADDRESS ON STACK
	RET
;
;
; DISPLAY 'WHAT?' SYNTAX ERROR MESSAGE
;4E87
SYNERR:	LD	HL,SYNERM	;POINT AT ERROR STRING
	CALL	DOPMSG		;DISPLAY THE MESSAGE
	JP	ERRENT		;THEN ABORT TO DOS ERROR
;
;
; EXECUTE 'SYS6/SYS' COMMANDS
;4E90
EXESIX:	LD	A,(SYSCON)	;GET CONDITION FLAGS
	BIT	4,A		;TEST IF 'SYS6/SYS' LOADED
	JP	NZ,SYSSIX	;THEN JUST EXECUTE IT
	LD	A,(SYSCON)	;GET CONDITION FLAGS
	SET	4,A		;FLAG 'SYS6/SYS' LOADED
	LD	(SYSCON),A	;RESTORE CONDITION FLAGS
	LD	A,088H		;LOAD REQUEST CODE TO A
	PUSH	AF		;SAVE THE CODE
	RST	28H		;LOAD AND EXECUTE 'SYS6/SYS'
