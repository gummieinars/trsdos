OVRL01:	AND	01110000B	;MASK TO REQUEST BITS
	CP	10H		;REQUEST 10
	JP	Z,NORMEN	;COMMAND PROCESSOR NORMAL ENTRY
	CP	20H		;REQUEST 20
	JR	Z,ERROEN	;COMMAND PROCESSOR ERROR ENTRY
