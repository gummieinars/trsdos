;
; COMPUTE A HASH CODE FOR A FILE
; EXCLUSIVE OR EACH CHARACTER OF FILE NAME WITH THE FOLLOWING
; CHARACTER, THEN MULTIPLY RESULT BY TWO AND USE AS CURRENT
; ENTRY:  HL      - POINTER TO FILE NAME AND EXTENSIOM
; EXIT:   A       - THE HASH CODE
;509B
FSHASH:	LD	B,11		;LOAD ITERATION COUNT
	LD	C,0		;INITIALIZE A MARK VALUE
FSHASL:	LD	A,(HL)		;GET CHARACTER FROM FILE NAME
	INC	HL		;BUMP FILE NAME POINTER
	XOR	C		;EXCLUSIVE OR WITH PREVIOUS
	RLCA			;MULTIPLY RESULT BY TWO
	LD	C,A		;SAVE TEMPORARY CODE
	DJNZ	FSHASL		;LOOP FOR ALL CHARACTERS
	LD	A,C		;GET FINAL HASH TO A
	OR	A		;TEST IF RESULT IS ZERO
	RET	NZ		;ALL DONE IF IT ISN'T
	INC	A		;ELSE FORCE A VALUE OF ONE
	RET
