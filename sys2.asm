;
; PARSE FILE EXTENSION, PASSWORD AND DRIVE
;5052
PARSEP:	LD	A,C		;TERMINATING CHARACTER TO A
	CP	'/'		;TEST IF EXTENSION DELIMITER
	JR	NZ,PARSPW	;SKIP IF IT ISN'T
	LD	DE,FILEXT	;POINT AT STORAGE LOCATION
	LD	B,3		;LOAD MAXIMUM EXTENSION LENGTH
	CALL	PARSES		;PARSE FILE EXTENSION
PARSPW:	CP	'.'		;TEST IF PASSWORD DELIMITER
	JR	NZ,PARSDR	;SKIP IF IT ISN'T
	LD	DE,PASSWD	;POINT AT STORAGE LOCATION
	LD	B,8		;LOAD MAXIMUM PASSWORD LENGTH
	CALL	PARSES		;PARSE PASSWORD STRING
PARSDR:	CP	':'		;TEST IF DRIVE DELIMITER
	JR	NZ,PARSZE	;SKIP IF IT ISN'T
	LD	A,(HL)		;ELSE GET DRIVE CODE
	SUB	'0'		;REMOVE ASCII BIAS
	JR	C,PARSER	;ABORT IF INVALID CODE
	CP	MAXDRV		;TEST IF VALID DRIVE CODE
	JR	C,PARSDC	;CONTINUE IF VALID CODE
PARSER:	LD	A,20H		;ELSE LOAD ERROR CODE
	OR	A		;FLAG ERROR CONDITION
	RET
