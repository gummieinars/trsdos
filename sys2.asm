;
; VALID DRIVE CODE FOUND SO SAVE IT
; ENTRY:  A       - DRIVE CODE
;507C
PARSDC:	LD	(DRVCOD),A	;STORE THE DRIVE CODE
;
;
; NO DRIVE CODE FOUND - RETURN A ZERO BYTE
; EXIT:   A       - ZERO
;         ZF      - SET
;507F
PARSZE:	XOR	A		;FLAG SUCCESSFUL PARSE
	RET
