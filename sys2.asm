OVRL02:	AND	01110000B	;MASK TO REQUEST BITS
	CP	10H		;REQUEST 10 - OPEN FILE
	JP	Z,OPNFIL	;THEN GO HANDLE THE REQUEST
	CP	20H		;REQUEST 20 - INIT FILE
