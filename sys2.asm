;
; FIND AN AVAILABLE HOLE IN THE 'HIT' SECTOR
; ENTRY:  HL      - POINTER TO LOADED 'HIT' SECTOR
; EXIT:   HL      - POINTER TO FREE 'HIT' ENTRY
;         ZF      - SET IF ENTRY FOUND
;50AB
HITHOL:	LD	A,(RANDOM)	;CHOOSE A RANDOM NUMBER
	AND	11100111B	;FORCE 00-07, 20-27, 40-47..
	CP	40H		;TEST IF BELOW 40
	JR	NC,HITHNB	;SKIP IF NOT BELOW
	OR	10000000B	;FORCE 80-87, A0-A7, C0-C7..
;
;
; FIND AN AVAILABLE HOLE IN THE 'HIT' SECTOR
; ENTRY:  A       - STARTING SEARCH INDEX
;         HL      - POINTER TO LOADED 'HIT' SECTOR
; EXIT:   HL      - POINTER TO FREE 'HIT' ENTRY
;         ZF      - SET IF ENTRY FOUND
;50B6
HITHNB:	LD	L,A		;FORM BEGINNING SEARCH IN HL
	CALL	HITHLP		;LOOK FOR AVAILABLE SLOT
	RET	Z		;ALL DONE IF ONE FOUND
	LD	L,40H		;SEARCH AGAIN FROM TABLE START
;
;
; FIND AN AVAILABLE HOLE IN THE 'HIT' SECTOR
; ENTRY:  HL      - POINTER TO LOADED 'HIT' SECTOR
; EXIT:   HL      - POINTER TO FREE 'HIT' ENTRY
;         ZF      - SET IF ENTRY FOUND
;50BD
HITHLP:	LD	A,(HL)		;GET A 'HIT' ENTRY
	OR	A		;TEST IF FREE ENTRY
	RET	Z		;ALL DONE IF ENTRY FREE
	LD	A,L		;GET TABLE POINTER LSB TO A
	ADD	A,20H		;INDEX TO NEXT ENTRY SET
	LD	L,A		;UPDATE TABLE POINTER
	JR	NC,HITHLP	;CONTINUE IF NOT TABLE END
	ADD	A,41H		;RESTART SEARCH AT 2, 3..
	LD	L,A		;UPDATE TABLE POINTER
	AND	11100111B	;FORCE 41-47, 61-67, 81-87..
	CP	L		;IF LSB IS E7 THEN TABLE END
	JR	Z,HITHLP	;LOOP IF NOT TABLE END
	OR	00000001B	;SIGNAL NO AVAILABLE ENTRIES
	RET
