;
; SCAN FILENAME OR PASSWORD STRING FOR INVALID CHARACTERS
; ENTRY:  B       - MAXIMUM BUMBER OF CHARACTERS
;         HL      - POINTER TO THE STRING
;         DE      - POINTER TO STORAGE BUFFER
; EXIT:   B       - REMAINING CHARACTER COUNT
;         HL      - POINTER TO TERMINATOR
;         DE      - POINTS PAST LAST BUFFER CHARACTER
;5081
PARSES:	LD	A,(HL)		;GET CHARACTER FROM STRING
	INC	HL		;BUMP STRING POINTER
	JR	PARSEA		;THEN START SCANNING
PARSEN:	LD	A,(HL)		;GET CHARACTER FROM STRING
	INC	HL		;BUMP STRING POINTER
	CP	'0'		;TEST IF NUMERIC CHARACTER
	RET	C		;ABORT IF NOT NUMERIC
	CP	'9'+1		;TEST IF NUMERIC CHARACTER
	JR	C,PARSEB	;SKIP IF CHARACTER NUMERIC
PARSEA:	CP	'A'		;TEST IF ALPHABETIC CHARACTER
	RET	C		;ABORT IF NOT ALPHABETIC
	CP	'Z'+1		;TEST IF ALPHABETIC CHARACTER
	RET	NC		;ABORT IF NOT ALPHABETIC
PARSEB:	LD	(DE),A		;STORE CHARACTER IN BUFFER
	INC	DE		;BUMP STORAGE BUFFER POINTER
	DJNZ	PARSEN		;LOOP UNTIL ALL SCANNED
	LD	A,(HL)		;LOAD CHARACTER FROM STRING
	INC	HL		;BUMP STRING POINTER
	RET
