;
; COMPUTE PASSWORD HASH CODE
; ENTRY:  DE      - POINTER TO PASSWORD BUFFER
; EXIT:   HL      - PASSWORD HASH CODE
;50D1
PWHASH:	LD	HL,-1		;LOAD INITIAL VALUE
	LD	B,8		;PASSWORD CHARACTER COUNT
	LD	A,E		;GET BUFFER POINTER LSB TO A
	ADD	A,7		;INDEX TO END OF BUFFER
	LD	E,A		;UPDATE BUFFER POINTER LSB
	JR	NC,PWHASL	;SKIP IF NOT OVERFLOW
	INC	D		;ELSE BUMP BUFFER POINTER MSB
PWHASL:	LD	A,(DE)		;GET CHARACTER FROM PASSWORD
	PUSH	DE		;SAVE BUFFER POINTER
	LD	D,A		;COPY THE CHARACTER TO D
	LD	E,H		;MARK VALUE 1 (MV1) TO E
	LD	A,L		;MARK VALUE 2 (MV2) TO A
	AND	00000111B	;MASK OFF TOP FIVE BITS
	RRCA			;ROTATE LOWER THREE
	RRCA			; BITS INTO UPPER
	RRCA			;  THREE BITS
	XOR	L		;EXCLUSIVE OR LOWER AND UPPER
	LD	L,A		;SAVE AS NEW MV2
	LD	H,0		;CLEAR FOR MULTIPLY BY SIXTEEN
	ADD	HL,HL		;MULTIPLY MV2 BY TWO
	ADD	HL,HL		;MULTIPLY MV2 BY FOUR
	ADD	HL,HL		;MULTIPLY MV2 BY EIGHT
	ADD	HL,HL		;MULTIPLY MV2 BY SIXTEEN
	XOR	H		;COMBINE UPPER EIGHT BITS
	XOR	D		;COMBINE CURRENT CHARACTER
	LD	D,A		;SAVE ENCODE UPPER EIGHT BITS
	LD	A,L		;SAVE ENCODE LOWER EIGHT BITS
	ADD	HL,HL		;COMPUTE MV2 TIMES THIRTY-TWO
	XOR	H		;COMBINE UPPER EIGHT BITS
	XOR	E		;COMBINE LOWER EIGHT BITS
	LD	E,A		;SAVE ENCODE LOWER EIGHT BITS
	EX	DE,HL		;SWAP RESULT TO HL REGISTER
	POP	DE		;RECOVER BUFFER POINTER
	DEC	DE		;BACKUP TO PREVIOUS CHARACTER
	DJNZ	PWHASL		;LOOP UNTIL PASSWORD HASHED
	RET
