;
; READ HASH INDEX TABLE (HIT) SECTOR FROM DISK
; ENTRY:  C       - DRIVE NUMBER
; EXIT:   A       - ERROR CODE
;         HL      - HASH IBDEX TABLE BUFFER POINTER
;         ZF      - SET IF ERROR
;512E
REDHIT:	PUSH	BC		;SAVE DRIVE NUMBER
	PUSH	DE		;SAVE DE REGISTER
	CALL	TRKDIR		;GET DIRECTORY TRACK NUMBER
	LD	E,1		;LOAD SECTOR NUMBER
	LD	HL,GATBUF	;POINT AT SECTOR BUFFER
	CALL	DDREAD		;READ SECTOR FROM DISK
	POP	DE		;RECOVER  DE REGISTER
	POP	BC		;RECOVER DRIVE NUMBER
	RET	Z		;ALL DONE IF SUCCESSFUL
	LD	A,16H		;ELSE LOAD ERROR CODE
	RET
;
;
; WRITE HASH INDEX TABLE (HIT) SECTOR TO DISK
; ENTRY:  C       - DRIVE NUMBER
; EXIT:   A       - ERROR CODE
;         HL      - HASH INDEX TABLE BUFFER POINTER
;         ZF      - SET IF ERROR
;5141
WRTHIT:	PUSH	BC		;SAVE DRIVE NUMBER
	PUSH	DE		;SAVE DE REGISTER
	CALL	TRKDIR		;GET DIRECTORY TRACK NUMBER
	LD	E,1		;LOAD SECTOR NUMBER
	LD	HL,GATBUF	;POINT AT SECTOR BUFFER
	CALL	WRDSEC		;WRITE SECTOR TO DISK
	POP	DE		;RECOVER DE REGISTER
	POP	BC		;RECOVER DRIVE NUMBER
	RET	Z		;ALL DONE IF SUCCESSFUL
	LD	A,17H		;ELSE LOAD ERROR CODE
	RET
