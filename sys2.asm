;
; TEST DRIVE READY STATUS BY TESTING FOR INDEX HOLE
; ENTRY:  C       - DRIVE NUMBER TO SELECT AND TEST
; EXIT:   A       - UNDEFINED
;         C       - UNCHANGED
;         CF      - SET IF WRITE PROTECTED
;         ZF      - RESET IF DRIVE NOT READY OR NOT PRESENT
;50FD
TSTRDY:	LD	A,WDFORC	;FORCE INTERRUPT COMMAND
	LD	(CSTREG),A	;RESET FLOPPY CONTROLLER
	CALL	SELDRV		;SELECT THE DISK DRIVE
	PUSH	BC		;SAVE DRIVE NUMBER
	LD	BC,12629	;LOAD LOOP COUNTER TO BC
BEGIDX:	CALL	TSTIDX		;WAIT FOR INDEX HOLE START
	JR	NZ,BEGIDX	;LOOP UNTIL HOLE REACHED
ENDIDX:	CALL	TSTIDX		;WAIT FOR INDEX HOLE END
	JR	Z,ENDIDX	;LOOP UNTIL END REACHED
IDXBEG:	CALL	TSTIDX		;WAIT FOR INDEX HOLE START
	JR	NZ,IDXBEG	;LOOP UNTIL HOLE REACHED
	POP	BC		;RECOVER DRIVE NUMBER
	RLCA			;WRITE PROTECT TO BIT SEVEN
	AND	10000000B	;MASK TO WRITE PROTECT
	ADD	A,A		;SET CARRY IF PROTECTED
	RET
;
;
; TEST FLOPPY CONTROLLER INDEX HOLE STATUS
; ENTRY:  BC      - NUMBER OF TIMES TO TEST COUNTER
; EXIT:   A       - FLOPPY CONTROLLER STATUS
;         BC      - DECREMENTED COUNTER
;         ZF      - RESET IF AT INDEX HOLE
;511E
TSTIDX:	DEC	BC		;DECREMENT TEST COUNT
	LD	A,B		;GET COUNTER MSB TO A
	OR	C		;MERGE IN COUNTER LSB
	JR	Z,IDXNOF	;ABORT IF COUNT TURNS ZERO
	LD	A,(CSTREG)	;GET FLOPPY STATUS
	BIT	1,A		;TEST THE INDEX FLAG
	RET
;
;
; INDEX HOLE NOT NOT FOUND - CLEAN STACK AND ABORT
; EXIT:   C       - DRIVE NUMBER
;         ZF      - RESET TO SHOW DRIVE NOT READY OR PRESENT
;5129
IDXNOF:	POP	BC		;REMOVE RETURN ADDRESS
	POP	BC		;RECOVER DRIVE NUMBER
	OR	00000001B	;RESET ZERO FLAG
	RET
