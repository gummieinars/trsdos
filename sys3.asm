;         B       - GRANULE ALLOCATION ENTRY
; EXIT:   B       - GRANULE ALLOCATION ENTRY WITH BIT RESET
;505B
RLSGRA:	AND	00000111B	;ISOLATE BIT TO BE RESET
	RLCA			;POSITION
	RLCA			; BIT
	RLCA			;  INTO INSTRUCTION
	OR	10000000B	;COMBINE WITH OP-CODE
	LD	(RLSGCO),A	;SAVE SYNTHESIZED CODE
	RES	0,B		;CLEAR BIT FOR GRANULE
RLSGCO	Equ	$-1		;THE BIT RESET CODE
	RET
