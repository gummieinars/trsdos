GATBUF	Equ	04D00H		;SECTOR BUFFER
;
;
; FUNCTIONS ADDRESSES IN TRSDOS NUCLEUS (SYS0/SYS)
;
WRDSEC	Equ	046EFH		;WRITE A DIRECTORY SECTOR
PURGEB	Equ	04878H		;PURGE SECTOR BUFFER
SAVREG	Equ	04892H		;SAVE ALL REGISTERS
REDDIR	Equ	04AC1H		;READ DIRECTORY SECTOR ENTRY
WRTDIR	Equ	04AD6H		;WRITE DIRECTORY SECTOR ENTRY
REDGAT	Equ	04AF0H		;READ 'GAT' SECTOR
WRTGAT	Equ	04B03H		;WRITE 'GAT' SECTOR
DDREAD	Equ	04B35H		;READ A SECTOR TO BUFFER
TRKDIR	Equ	04B55H		;GET DIRECTORY TRACK NUMBER
DIVMOD	Equ	04B84H		;MODULO DIVISION ROUTINE
