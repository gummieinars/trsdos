	OR	A		;TEST IF TRAPPING ON
	JR	NZ,DSPALL	;DISPLAY REGISTERS AND DATA
	LD	A,HO		;LOAD CURSOR HOME CHARACTER
	CALL	VDCHAR		;MOVE DISPLAY CURSOR HOME
	LD	HL,BUGREG	;POINT AT REGISTERS
	PUSH	HL		;SAVE REGISTER POINTER
	LD	HL,REGNAM	;POINT AT REGISTER NAMES
	LD	B,NUMREG	;LOAD REGISTER COUNT
