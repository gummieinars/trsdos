; 'G' COMMAND - EXECUTE PROGRAM WITH UP-TO TWO TRAP ADDRESSES
;4F80
EXECUT:	LD	B,2		;COLLECT UP-TO TWO ADDRESSES
	LD	DE,SECTRB	;POINT AT TRAP ADDRESS TABLE
	CALL	HEXADR		;GET ADDRESS FROM KEYBOARD
	JR	Z,EXECNA	;SKIP IF NO ADDRESS ENTERED
	LD	(BUGREG+PCR),HL	;STORE AS PROGRAM COUNTER
EXECNA:	JR	C,EXECEN	;SKIP IF NOTHING FOLLOWS
	CALL	HEXADR		;GET ADDRESS FROM KEYBOARD
	PUSH	AF		;SAVE ADDRESS FOUND FLAG
	CALL	NZ,SVTRAD	;SAVE ADDRESS IF ENTERED
	POP	AF		;RECOVER ADDRESS FOUND FLAG
	DJNZ	EXECNA		;LOOP FOR NEXT ADDRESS
EXECEN:	LD	HL,LDBVEC	;POINT AT DEBUG LOAD VECTOR
	LD	(DEBUGJ+1),HL	;SET JUMP LOCATION IN TRSDOS
	LD	A,0C3H		;LOAD 'JP' OP-CODE
	LD	(DEBUGJ),A	;STORE OP-CODE IN TRSDOS
