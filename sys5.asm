;
; ';' COMMAND - ADJUST DISPLAY ADDRESS FORWARDS
;4EAE
NXTDSP:	LD	BC,COL		;LOAD COLUMN COUNT TO BC
;
;
; ADJUST DISPLAY ADDRESS FORWARDS OF BACKWARDS
; ENTRY:  BC      - POSITIVE OR NEGATIVE DISPLAY ADJUSTMENT
;         FIRTRA  - CURRENT TRAP ADDRESS
;         THITRA  - CURRENT DISPLAY ADDRESS
; EXIT:   THITRA  - NEW DISPLAY ADDRESS
;4EB1
ADJDSP:	LD	HL,(THITRA)	;GET CURRENT DISPLAY ADDRESS
	LD	A,(FIRTRM)	;GET TRAP ADDRESS MSB
	OR	A		;TEST IF CURRENTLY TRAPPING
	JR	Z,DSPADJ	;ALL DONE IF NOT
	LD	C,0		;ELSE ZERO ADJUSTMENT LSB
	LD	A,B		;LOAD ADJUSTMENT MSB TO A
	OR	A		;TEST IF MSB IS ZERO
	JR	NZ,DSPADJ	;SKIP IF IT ISN'T
	INC	B		;ELSE INCREMENT MSB
;
;
; ADJUST DISPLAY ADDRESS
; ENTRY:  BC      - DISPLAY ADJUSTMENT VALUE
;         HL      - CURRENT DISPLAY ADDRESS
; EXIT:   HL      - ADJUSTED ADDRESS
;         THITRA  - NEW DISPLAY ADDRESS
;4EC1
DSPADJ:	ADD	HL,BC		;ADD OFFSET TO CURRENT ADDRESS
;
;
; STORE ADDRESS FOR CURRENT COMMAND
; ENTRY:  HL      - NEW OR UPDATED ADDRESS
; EXIT:   HL      - NEW DISPLAY ADDRESS
;         THITRA  - UPDATED ADDRESS
;4EC2
UPDADR:	LD	(THITRA),HL	;SAVE THE ADDRESS
	RET
