;
;
; 'I' COMMAND - SINGLE STEP NEXT INSTRUCTION
;505D
STPNXT:	PUSH	AF		;SAVE COMMAND CHARACTER
	LD	DE,(BUGREG+PCR)	;LOAD RESUMPTION ADDRESS
	LD	A,(DE)		;LOAD 'OP'CODE' AT ADDRESS
	LD	HL,GRPTRI	;GROUP 3 INSTRUCTION TYPES
	CP	0DDH		;TEST FOR INDEXED INSTRUCTION
	JR	Z,ISINDX	;SKIP IF 'IX' INSTRUCTION
	CP	0FDH		;ELSE TEST FOR 'IY' INSTRUCTION
	JR	Z,ISINDX	;SKIP IF 'IY' INSTRUCTION
	LD	HL,GRPONE	;GROUP 1 INSTRUCTION TYPES
	CP	0EDH		;TEST FOR SPECIAL INSTRUCTION
	JR	NZ,NOTIDS	;GO IF NOT INDEXED OR SPECIAL
	LD	HL,GRPTWO	;GROUP 2 INSTRUCTION TYPES
ISINDX:	INC	DE		;BUMP TO NEXT INSTRUCTION BYTE
	LD	A,(DE)		;GET NEXT INSTRUCTION BYTE
	DEC	DE		;BACSPACE TO INSTRUCTION START
NOTIDS:	LD	C,A		;COPY OP-CODE LSB TO C
NXTENT:	LD	A,(HL)		;FETCH OP-CODE MASK
	AND	C		;APPLY MASK TO OP-CODE LSB
	INC	HL		;BUMP TO OP-CODE IN LIST
	CP	(HL)		;COMPARE TO CODE IN TABLE
	INC	HL		;BUMP TO CODE LENGTH VALUE
	JR	Z,OPCMAT	;JUMP IF OP-CODES MATCH
	INC	HL		;BUMP TO NEXT TABLE ENTRY
	LD	A,(HL)		;FETCH OP-CODE MASK
	CP	005H		;TEST FOR END OF LIST
	JR	NC,NXTENT	;LOOP IF END NOT REACHED
OPCMAT:	LD	A,(HL)		;GET INSTRUCTION LENGTH TO A
	LD	B,A		;SAVE THE LENGTH IN B
	AND	00001111B	;ISOLATE INSTRUCTION LENGTH
	LD	L,A		;GET LENGTH BYTE TO L
	LD	H,0		;HL HAS INSTRUCTION LENGTH
	ADD	HL,DE		;ADD NEXT INSTRUCTION ADDRESS
	PUSH	DE		;SAVE INSTRUCTION ADDRESS
	LD	DE,SECTRB	;POINT AT TRAP ADDRESS TABLE
	CALL	SVTRAD		;SAVE THE TRAP ADDRESS
	POP	HL		;ADDRESS AFTER CURRENT ADDRESS
	LD	A,B		;GET SAVED LENGTH TO A
	AND	11110000B	;ISOLATE INSTRUCTION TYPE
	JR	Z,SGLCAL	;EXECUTE IF JUST DROP TO NEXT
	INC	HL		;BUMP NEXT INSTRUCTION ADDRESS
	CP	00100000B	;TEST REGISTER JUMP INSTRUCTION
	JR	C,GEJEXE	;EXECUTE IF 'JP (HL)'
	JR	Z,TSTIRJ	;HANDLE INDEX REGISTER JUMP
	CP	01000000B	;TEST JUMP TYPE INSTRUCTION
	JR	C,TSTREL	;GO HANDLE RELATIVE JUMP
	JR	Z,NXTSGL	;ELSE HANDLE ABSOLUTE JUMP
	CP	01100000B	;TEST RETURN TYPE INSTRUCTION
	JR	C,SGLNXT	;GO HANDLE 'RET' INSTRUCTIONS
	POP	AF		;RECOVER COMMAND CHARACTER
	CP	'I'		;TEST IF SINGLE STEP NEXT
	JR	Z,NXTSGL	;THEN GO DO THE SINGLE STEP
;
;
; SINGLE STEP WITH CALLS
;50B4
SGLCAL:	JP	EXECXF		;THEN ENTER EXECUTION LOOP
;
;
; SINGLE STEP NEXT INSTRUCTION
;50B7
SGLNXT:	LD	HL,(BUGREG+SPR)	;GET RETURN ADDRESS FROM STACK
;
;
; SINGLE STEP NEXT INSTRUCTION
;50BA
NXTSGL:	LD	A,(HL)		;GET RETURN ADDRESS LSB
	INC	HL		;BUMP TO THE MSB
	LD	H,(HL)		;GET RETURN ADDRESS MSB
	LD	L,A		;HL HAS THE ADDRESS
	JR	STOEXE		;RESTORE CONTEXT AND EXECUTE
;
;
; EXECUTE RELATIVE BRANCH
;50C0
TSTREL:	LD	C,(HL)		;GET OFFSET FOR BRANCH TO C
	XOR	A		;ASSUME FORWARD BRANCH
	BIT	7,C		;TEST IF POSITIVE VALUE
	JR	Z,RELFWD	;THEN DO FORWARD BRANCH
	CPL			;ELSE COMPLEMENT BRANCH VALUE
RELFWD:	LD	B,A		;GET DISPLACEMENT MSB TO B
	INC	HL		;BUMP INSTRUCTION ADDRESS
	ADD	HL,BC		;NEXT INSTRUCTION ADDRESS IN HL
	JR	STOEXE		;RESTORE CONTEXT AND EXECUTE
;
;
; TEST FOR REGISTER JUMP
;50CC
TSTIRJ:	LD	HL,(BUGREG+IXR)	;GET IX REGISTER CONTENTS
	BIT	5,C		;TEST IF IX REGISTER JUMP
	JR	Z,STOEXE	;THEN TRAP THE REGISTER JUMP
	LD	HL,(BUGREG+IYR)	;GET IY REGISTER CONTENTS
	JR	STOEXE		;RESTORE CONTEXT AND EXECUTE
:
;
; GET JUMP ADDRESS, STORE TRAP, RESTORE CONTEXT AND EXECUTE
;50D8
GEJEXE:	LD	HL,(BUGREG+HLM)	;GET JUMP ADDRESS TO HL
;
;
; STORE TRAP INSTRUCTION, RESTORE CONTEXT AND EXECUTE
;50DB
STOEXE:	CALL	SVTRAD		;SAVE THE TRAP ADDRESS
	JR	SGLCAL		;RESTORE CONTEXT AND EXECUTE
;
;
; GROUP 1 INSTRUCTION LIST
;
; EACH ENTRY HAS THE FOLLOWING FORMAT:
;
;   MASK, OPCODE, TYPE OR LENGTH
;
; TYPE IS A CODE INDICATING WHERE THE ADDRESS OF OF THE NEXT
; INSTRUCTION MAY BE FOUND, TYPE CODES DEFINED AS FOLLOWS:
;
;   0 - NEXT INSTRUCTION FOLLOWS CURRENT INSTRUCTION
;   1 - NEXT INSTRUCTION ADDRESS COMES FROM HL AS IN JP (HL)
;   2 - NEXT INSTRUCTION ADDRESS CONDITIONALLY COMES FROM
;       OPERAND, AS IN JP C,XXXX
;   3 - CONDITIONAL AS IN DJNZ XXXX
;   4 - OPERAND AS IN JP XXXX
;   5 - CONDITIONAL AND INDIRECT AS IN RET, OR RET NZ
;   6 - CONDITIONAL, OPERAND AS IN CALL NZ,XXXX OR CALL XXXX
;50E0
GRPONE	Db	0C7H,0C0H,051H
	Db	0FFH,0C9H,051H
	Db	0FFH,0E9H,011H
	Db	0CFH,001H,003H
	Db	0E7H,022H,003H
	Db	0C7H,0C2H,043H
	Db	0FFH,0C3H,043H
	Db	0C7H,0C4H,063H
	Db	0FFH,0CDH,063H
	Db	0C7H,006H,002H
	Db	0F7H,0D3H,002H
	Db	0C7H,0C6H,002H
	Db	0FFH,0CBH,002H
	Db	0F7H,010H,032H
	Db	0E7H,020H,032H
	Db	001H
;
;
; DEFAULT LENGTH FOR INSTRUCTIONS NOT MATCHING THOSE IN LIST
;
; GROUP 2 INSTRUCTION LIST
;
; EACH BYTE HAS THE FOLLOWING FORMAT:
;
;   MASK, OPCODE, TYPE OR LENGTH
;
; LENGTH EQUALS THE LENGTH OF THE CURRENT OPCODE
;510E
GRPTWO	Db	0C7H,043H,004H
	Db	0F7H,045H,052H
	Db	002H
;
;
; DEFAULT LENGTH FOR ANY INSTRUCTIONS NOT MATCHING LISTS ABOVE
;
; GROUP 3 INSTRUCTION LIST
;
; EACH BYTE HAS THE FOLLOWING FORMAT:
;
;   MASK, OPCODE, TYPE OR LENGTH
;
; LENGTH EQUALS THE LENGTH OF THE CURRENT OPCODE
;5115
GRPTRI	Db	0FEH,034H,003H
	Db	0C0H,040H,003H
	Db	0C0H,080H,003H
	Db	0FFH,021H,004H
	Db	0FFH,022H,004H
	Db	0FFH,02AH,004H
	Db	0FFH,036H,004H
	Db	0FFH,0CBH,004H
	Db	0FFH,0E9H,022H
	Db	002H
