;
; 'R' COMMAND - MODIFY A REGISTERS CONTENTS
;5011
MODREG:	CALL	WAITKB		;GET KEYBOARD CHARACTER
	RET	Z		;DONE IF SPACE OR A COMMA
	LD	C,A		;SAVE CHARACTER IN C
	CALL	WAITKB		;GET KEYBOARD CHARACTER
	RET	Z		;DONE IF SPACE OR A COMMA
	LD	D,A		;SAVE CHARACTER IN D
	LD	E,' '		;LOAD SPACE CHARACTER
	CALL	WAITKB		;GET KEYBOARD CHARACTER
	RET	C		;DONE IF 'ENTER' KEY
	JR	Z,MODRTM	;SKIP IF NO MORE CHARACTERS
	LD	E,A		;COPY CHARACTER TO E
	CALL	WAITKB		;GET KEYBOARD CHARACTER
	RET	NZ		;DONE IF SPACE OR A COMMA
	RET	C		;DONE IF 'ENTER' KEY
MODRTM:	LD	HL,REGNAM	;POINT AT REGISTER NAMES
	LD	B,NUMREG	;LOAD REGISTER COUNT
MODRTL:	LD	A,(HL)		;GET REGISTER NAME CHARACTER
	CP	C		;TEST IF REGISTER NAME MATCH
	JR	Z,MODRTN	;CONTINUE IF NAME MATCH
	INC	HL		;BUMP PAST NAME CHARACTER
MODRNE:	INC	HL		;BUMP PAST NAME CHARACTER
MODRNI:	INC	HL		;BUMP PAST NAME CHARACTER
	DJNZ	MODRTL		;LOOP UNTIL ALL TESTED
	RET
