;
; MAIN DEBUGGER COMMAND LOOP - GET COMMAND CHARACTER
;4E4B
CMDLUP:	LD	SP,(BUGREG+SPR)	;INIT LOCAL STACK POINTER
	CALL	DSPREG		;UPDATE THE DISPLAY
	LD	HL,FIRBOL	;FIRST BOTTOM VIDEO LINE
	LD	(VDUDCB+VIA),HL	;STORE IN VIDEO DCB
	CALL	WAITKB		;GET KEYBOARD CHARACTER
	CP	'G'		;TEST IF EXECUTE COMMAND
	JP	Z,EXECUT	;THEN PROCESS THE COMMAND
	LD	HL,CMDLUP	;LOAD COMMAND LOOP ADDRESS
	PUSH	HL		;SET AS RETURN POINT ADDRESS
	CP	'S'		;TEST IF MEMORY DISPLAY
	JR	Z,MEMDSP	;THEN SWITCH TO MEMORY DISPLAY
	CP	';'		;TEST IF NEXT MEMORY BLOCK
	JR	Z,NXTDSP	;THEN SHOW THE BLOCK
	CP	'-'		;TEST IF PREVIOUS MEMORY BLOCK
	JR	Z,PRVDSP	;THEN SHOW THE BLOCK
	CP	'A'		;TEST IF ASCII DISPLAY
	JR	Z,ASCDSP	;THEN SWITCH TO ASCII
	CP	'C'		;TEST IF SINGLE STEP WITH CALLS
	JR	Z,STPNXB	;THEN GO HANDLE THE STEP
	CP	'D'		;TEST IF DISPLAY MEMORY
	JR	Z,DSPMEM	;THEN DUMP THE LOCATION
	CP	'H'		;TEST IF HEX DISPLAY
	JR	Z,HEXDSP	;THEN SWITCH TO HEX
	CP	'I'		;SINGLE STEP NEXT INSTRUCTION
STPNXB:	JP	Z,STPNXT	;THEN GO HANDLE THE STEPS
	CP	'M'		;TEST IF MODIFY MEMORY
	JP	Z,MODMEM	;THEN MODIFY THE MEMORY
	CP	'R'		;TEST IF MODIFY REGISTER
	JP	Z,MODREG	;THEN MODIFY THE REGISTER
	CP	'U'		;DYNAMIC DISPLAY
	JR	Z,DYNDSP	;THEN WAIT FOR ABORT
	CP	'X'		;TEST IF REGISTER DISPLAY
	JR	Z,REGDSP	;THEN SWITCH TO REGISTER
	RST	28H		;ELSE PASS REQUEST TO TRSDOS
	RET
