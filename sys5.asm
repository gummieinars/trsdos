;
; STORE TRAP ADDRESS IN ADDRESS TABLE
; ENTRY:  DE      - POINTER TO TRAP ADDRESS TABLE
;         HL      - THE TRAP ADDRESS
; EXIT:   DE      - UPDATED TRAP ADDRESS TABLE POINTER
;4FCA
SVTRAD:	LD	A,(HL)		;GET A BYTE FROM MEMORY
	LD	(DE),A		;SAVE IN THE TRAP TABLE
	DEC	DE		;BACKUP TRAP TABLE POINTER
	LD	A,TRAP		;LOAD 'TRAP' INSTRUCTION
	LD	(HL),A		;SET EXECUTION TRAPPING
	CP	(HL)		;TEST IF TRAPPING ROM
	JP	NZ,NOTRAP	;EXIT IF TRYING TO TRAP ROM
	LD	A,H		;GET TRAP ADDRESS MSB
	LD	(DE),A		;SAVE IN THE TRAP TABLE
	DEC	DE		;BACKUP TRAP TABLE POINTER
	LD	A,L		;GET TRAP ADDRESS LSB
	LD	(DE),A		;SAVE IN THE TRAP TABLE
	DEC	DE		;BACKUP TRAP TABLE POINTER
	RET
