; DISPLAY REGISTER ADDRESS AND DATA POINTED TO BY REGISTERS
;
; -- PRECEDE BY A NEWLINE --
;4EE5
ALLREG:	LD	A,CR		;LOAD NEWLINE CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
;
;
; DISPLAY REGISTER ADDRESS AND DATA POINTED TO BY REGISTERS
;
; -- NO NEWLINE PRECEDED --
;4EEA
REGALL:	CALL	MEMTCH		;DISPLAY THREE MEMORY BYTES
	EX	(SP),HL		;GET TOP OF STACK TO HL
	LD	E,(HL)		;GET ADDRESS LSB TO E
	INC	HL		;BUMP TO NEXT ADDRESS BYTE
	LD	D,(HL)		;GET ADDRESS MSB TO D
	INC	HL		;BUMP TO NEXT ADDRESS
	PUSH	HL		;SAVE THE MEMORY POINTER
	EX	DE,HL		;SWAP THE ADDRESS TO HL
	LD	A,'='		;LOAD EQUALS CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	CALL	DSPSPC		;DISPLAY ASCII SPACE CHARACTER
	LD	A,H		;LOAD REGISTER CONTENTS MSB
	CALL	HEXSPC		;DISPLAY HEX FOLLOWED BY SPACE
	LD	A,L		;LOAD REGISTER CONTENTS LSB
	CALL	HEXSPC		;DISPLAY HEX FOLLOWED BY SPACE
	LD	A,B		;GET REGISTER COUNT TO A
	AND	00001011B	;MASK TO RELEVANT BITS
	CP	00001000B	;TEST IF EIGHT DONE
	JR	NZ,REGARD	;DUMP REGISTER AND DATA IF NOT
	LD	C,L		;ELSE GET ADDRESS LSB TO C
	PUSH	BC		;SAVE REGISTER COUNT
	LD	HL,FLGNAM	;POINT AT FLAG CHARACTERS
	LD	B,8		;LOAD FLAG COUNT TO B
REGAFL:	SLA	C		;SHIFT FLAG TO A
	LD	A,(HL)		;GET FLAG CHARACTER TO A
	JR	C,REGANF	;SKIP IF UNDEFINED FLAG
	LD	A,'-'		;LOAD MINUS CHARACTER
REGANF:	CALL	VDCHAR		;DISPLAY FLAG CHARACTER
	INC	HL		;BUMP FLAG TABLE POINTER
	DJNZ	REGAFL		;LOOP FOR NEXT FLAG
	POP	BC		;RECOVER REGISTER COUNT
	LD	A,CO+44		;DISPLAY 44 SPACES
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	JR	REGASD		;THEN SKIP REGISTER DUMP
REGARD:	CALL	REGDTA		;DISPLAY REGISTER AND DATA
REGASD:	POP	HL		;GET RETURN ADDRESS TO HL
	EX	(SP),HL		;SWAP MEMORY ADDRESS TO HL
	DJNZ	ALLREG		;DO NEXT REGISTER AND DATA
	POP	HL		;CLEAN UP THE STACK
	LD	HL,(THITRA)	;LOAD ADDRESS TO HL
	LD	B,4		;LOAD LINE COUNTER
