;
; DISPLAY ALL REGISTER VALUES AND THE MEMORY THEY POINT AT
;5131
REGDTA:	PUSH	BC		;SAVE BC REGISTER
	LD	A,'='		;LOAD EQUALS CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	LD	A,'>'		;LOAD GREATER THAN CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	CALL	DSPSPC		;DISPLAY ASCII SPACE CHARACTER
	LD	B,16		;LOAD BYTE COUNTER
REGDTL:	CALL	PUTBAR		;BARS AROUND MODIFY LOCATION
	LD	A,(FIRTRL)	;GET DISPLAY FORMAT TO A
	CP	'A'		;TEST IF ASCII DISPLAY
	JR	NZ,HEXDIS	;SKIP IF HEX DISPLAY
	CALL	DSPSPC		;DISPLAY ASCII SPACE CHARACTER
	LD	A,(HL)		;LOAD BYTE FROM MEMORY
	CP	' '		;TEST IF CONTROL CHARACTER
	JR	C,REGDTD	;DISPLAY A DOT IF IT IS
	CP	CO		;TEST IF COMPRESSION CODE
	JR	C,REGDTN	;CONTINUE IF IT ISN'T
REGDTD:	LD	A,'.'		;LOAD DECIMAL POINT CHARACTER
REGDTN:	CALL	VDCHAR		;DISPLAY THE CHARACTER
	INC	HL		;BUMP MEMORY POINTER
	XOR	A		;FLAG PROCESSING ASCII DISPLAY
;
;
; WE WANT AN HEX DISPLAY
; ENTRY:  ZF      - SET IF HEX DISPLAY
;515E
HEXDIS:	CALL	NZ,MEMHEX	;DISPLAY MEMORY BYTE IN HEX
	DJNZ	REGDTL		;LOOP UNTIL ALL BYTES DONE
	POP	BC		;RECOVER BC REGISTER
	RET
;
;
; PUT DISPLAY BARS AROUND LOCATION BEING MODIFIED
; ENTRY:  B       - CHARCTER COUNT
;         HL      - DISPLAY ADDRESS
;         SECTRA  - THE LOCATION
;5165
PUTBAR:	LD	DE,(SECTRA)	;GET ADDRESS TO DE
	INC	DE		;BUMP TO NEXT INSTRUCTION
	PUSH	HL		;SAVE CURRENT DISPLAY ADDRESS
	XOR	A		;CLEAR CARRY FLAG
	SBC	HL,DE		;COMPARE DISPLAY AND MODIFY
	LD	A,LEFBAR	;LEFT VERTICAL BAR
	JR	Z,PUTBAL	;IF MODIFY, DISPLAY LEFT BAR
	CALL	SPCEIG		;SPACE IF EIGHT VALUES DONE
	INC	HL		;BUMP DISPLAY ADDRESS
	LD	A,L		;GET DISPLAY ADDRESS LSB TO A
	OR	H		;TEST IF ADDRESS IS ZERO
	POP	HL		;RECOVER DISPLAY ADDRESS
	LD	A,RIGBAR	;RIGHT VERTICAL BAR
	JP	Z,VDCHAR	;THEN DISPLAY THE CHARACTER
	JR	SPCDSP		;AND THEN FOLLOW WITH A SPACE
PUTBAL:	CALL	VDCHAR		;DISPLAY THE CHARACTER
	POP	HL		;RECOVER DISPLAY ADDRESS
;
;
; DISPLAY A SPACE IF 'B' REGISTER IS 8
;5184
SPCEIG:	LD	A,B		;GET B REGISTER TO A
	CP	8		;TEST IF DONE EIGHT BYTES
	RET	NZ		;RETURN IF NOT
;
;
; DISPLAY AN ASCII SPACE
;5188
SPCDSP:	JR	DSPSPC		;DISPLAY ASCII SPACE CHARACTER
;
;
; WAIT FOR A KEYBOARD CHARACTER
; EXIT:   A       - THE CHARACTER
;         ZF      - SET IF CHARACTER IS A COMMA OR A SPACE
;         CF      - SET IF 'ENTER' KEY PRESSED
;518A
WAITKB:	PUSH	DE		;SAVE DE REGISTER
WAITKL:	CALL	KBWAIT		;WAIT FOR KEYBOARD KEY PRESS
	CP	CR		;TEST IF CARRIAGE RETURN
	JR	Z,WAITKE	;THEN WE JUST RETURN
	CP	' '		;TEST IF CONTROL CHARACTER
	JR	C,WAITKL	;THEN IGNORE THE CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	POP	DE		;RECOVER DE REGISTER
	CP	','		;TEST IF COMMA CHARACTER
	RET	Z		;THEN WE RETURN
	CP	' '		;TEST FOR A SPACE CHARACTER
	RET
;
;
; THE 'ENTER' KEY HAS BEEN PRESSED
; EXIT:   A       - CARRIAGE RETURN CHARACTER
;         CF      - SET
;51A0
WAITKE:	POP	DE		;RECOVER DE REGISTER
	SCF			;SET THE CARRY FLAG
	RET
;
;
; GET ADDRESS FROM KEYBOARD
; EXIT:   HL      - THE ADDRESS
;         ZF      - SET IF NO ADDRESS
;         CF      - SET IF CARRIAGE RETURN
;51A3
HEXADR:	CALL	WAITKB		;GET KEYBOARD CHARACTER
	RET	Z		;RETURN IF SPACE OR COMMA
	LD	HL,0		;ZERO ADDRESS REGISTER
HEXADL:	CALL	HEXNIB		;GET ADDRESS NIBBLE TO A
	JP	C,CMDLUP	;ABORT IF INVALID NIBBLE
	ADD	HL,HL		;ADDRESS TIMES 2
	ADD	HL,HL		;ADDRESS TIMES 4
	ADD	HL,HL		;ADDRESS TIMES 8
	ADD	HL,HL		;ADDRESS TIMES 16
	OR	L		;MERGE IN LS NIBBLE
	LD	L,A		;UPDATE LS BYTE
	CALL	WAITKB		;GET KEYBOARD CHARACTER
	JR	NZ,HEXADL	;LOOP IF NOT SPACE OR A COMMA
	RRA			;CARRY TO BIT 7
	ADC	A,129		;SET CARRY IF CARRIAGE RETURN
	RET
;
;
; CONVERT ASCII NIBBLE TO BINARY NIBBLE
; ENTRY:  A       - ASCII BYTE
; EXIT:   A       - BINARY NIBBLE
;         CF      - SET IF INVALID NIBBLE
;51BF
HEXNIB:	SUB	'0'		;REMOVE ASCII BIAS
	RET	C		;ABORT IF INVALID DIGIT
	ADD	A,0E9H		;ADD LETTER BIAS
	RET	C		;DONE IF NOT LETTER
	ADD	A,6		;TEST IF 'A' TO 'Z'
	JR	C,HEXNIX	;CONTINUE IF 'A' TO 'Z'
	ADD	A,7		;ELSE DIGIT '0' TO '9'
	RET	C		;DOES NOTHING IN THIS CONTEXT
HEXNIX:	ADD	A,10		;ELSE MAKE BINARY VALUE
	OR	A		;SET FLAGS FOR RESULT
	RET
;
;
; DISPLAY A BYTE IN ASCII HEXADECIMAL
; ENTRY:  HL      - POINTER TO THE BYTE
; EXIT:   HL      - INCREMENTED
;51D0
MEMHEX:	LD	A,(HL)		;GET BYTE TO DISPLAY
	INC	HL		;INCREMENT MEMORY POINTER
	JR	BYTHEX		;GO CONVERT AND DISPLAY
;
;
; DISPLAY A WORD IN ASCII HEXADECIMAL
; ENTRY:  HL      - THE WORD TO CONVERT AND DISPLAY
;51D4
WORHEX:	LD	A,H		;GET MSB OF WORD TO A
	CALL	BYTHEX		;GO CONVERT AND DISPLAY
	LD	A,L		;GET LSB OF WORD TO A
;
;
; DISPLAY A BYTE IN ASCII HEXADECIMAL
; ENTRY:  A       - THE BYTE TO CONVERT AND DISPLAY
;51D9
BYTHEX:	PUSH	AF		;SAVE THE BINARY BYTE
	RRA			;SHIFT FOUR
	RRA			; MS BITS
	RRA			;  INTO FOUR
	RRA			;   LS BITS
	CALL	NIBHEX		;CONVERT AND DISPLAY NIBBLE
	POP	AF		;RECOVER SAVED BYTE
NIBHEX:	AND	00001111B	;MASK OFF MS NIBBLE
	ADD	A,'0'		;CONVERT TO ASCII
	CP	'9'+1		;TEST IF NUMERIC ASCII
	JR	C,DSPCHR	;GO DISPLAY IF IT IS
	ADD	A,'A'-'9'-1	;ADD ALPHABETICAL BIAS
;
;
; DISPLAY AN ASCII CHARACTER
; ENTRY:  A       - CHARACTER TO DISPLAY
;51EC
DSPCHR:	JP	VDCHAR		;DISPLAY THE CHARACTER
;
;
; DISPLAY A BYTE IN HEXADECIMAL FOLLOWED BY A SPACE CHARACTER
; ENTRY:  A       - BINARY BYTE TO DISPLAY
;51EF
HEXSPC:	CALL	BYTHEX		;DISPLAY BYTE IN ASCII HEX
;
;
; DISPLAY AN ASCII SPACE CHARACTER
;51F2
DSPSPC:	LD	A,' '		;LOAD ASCII SPACE CHARACTER
	JR	DSPCHR		;GO DISPLAY THE CHARACTER
;
;
; DISPLAY THREE CONSECUTIVE CHARACTERS FROM MEMORY LOCATIONS
; ENTRY:  HL      - POINTER TO THE CHARACTERS
; EXIT:   HL      - INCREMENTED THREE TIMES
;51F6
MEMTCH:	CALL	MEMCHR		;DISPLAY MEMORY CHARACTER
	CALL	MEMCHR		;DISPLAY MEMORY CHARACTER
;
;
; DISPLAY A CHARACTER FROM A MEMORY LOCATION
; ENTRY:  HL      - POINTER TO THE CHARACTER
; EXIT:   HL      - INCREMENTED
;51FC
MEMCHR:	LD	A,(HL)		;GET CHARACTER FROM MEMORY
	INC	HL		;BUMP MEMORY POINTER
	JR	DSPCHR		;DISPLAY THE CHARACTER
;
