; 'M' COMMAND - MODIFY MEMORY
;4FDB
MODMEM:	LD	HL,(SECTRA)	;GET MODIFY ADDRESS
	CALL	HEXADR		;GET ADDRESS FROM KEYBOARD
MODMEL:	LD	(SECTRA),HL	;SAVE ENTERED ADDRESS
	RET	C		;EXIT IF CARRIAGE RETURN
	PUSH	HL		;SAVE MODIFY ADDRESS
	CALL	DSPREG		;UPDATE DISPLAY IF CHANGED
	LD	HL,THIBOL	;THIRD BOTTOM VIDEO LINE
	LD	(VDUDCB+VIA),HL	;STORE ADDRESS IN DCB
	LD	HL,(SECTRA)	;GET MEMORY ADDRESS TO HL
	CALL	WORHEX		;DISPLAY HEXADECIMAL ADDRESS
	PUSH	HL		;SAVE MEMORY ADDRESS
	LD	HL,SECBOL	;SECOND BOTTOM VIDEO LINE
	LD	(VDUDCB+VIA),HL	;STORE IN VIDEO DCB
	POP	HL		;RECOVER MEMORY ADDRESS
	CALL	MEMHEX		;DISPLAY MEMORY BYTE IN HEX
	LD	A,'-'		;LOAD A MINUS CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	POP	DE		;RECOVER MODIFY ADDRESS
	CALL	HEXADR		;GET WORD FROM KEYBOARD
	EX	DE,HL		;SWAP THE BYTE TO E
	JR	Z,MODMEN	;DONE IF NO ADDRESS
	LD	(HL),E		;STORE THE BYTE IN MEMORY
MODMEN:	RET	C		;DONE IF CARRIAGE RETURN
	INC	HL		;BUMP MEMORY LOCATION
	JR	MODMEL		;LOOP FOR NEXT MODIFY BYTE
