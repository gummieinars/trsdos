;
; COPY REGISTER VALUES FROM OR TO CONTEXT AREA TO OR FROM STACK
;4FA4
EXECXF:	LD	HL,BUGREG+SPR+1	;POINT AT STACK POINTER MSB
	LD	B,NUMREG-1	;LOAD REGISTER COUNT TO B
EXECSR:	LD	D,(HL)		;GET WORD MSB FROM THE STACK
	DEC	HL		;BACKUP STACK INDEX
	LD	E,(HL)		;GET WORD LSB FROM THE STACK
	DEC	HL		;BACKUP STACK INDEX
	PUSH	DE		;PUT THE WORD ON THE STACK
	DJNZ	EXECSR		;LOOP FOR NEXT REGISTER PAIR
	POP	AF		;RECOVER AF REGISTER
	POP	BC		;RECOVER BC REGISTER
	POP	DE		;RECOVER DE REGISTER
	POP	HL		;RECOVER HL REGISTER
	EX	AF,AF'		;SWAP TO ALTERNATE AF
	EXX			;SWAP TO ALTERNATE REGISTERS
	POP	AF		;RECOVER ALTERNATE AF
	POP	BC		;RECOVER ALTERNATE BC
	POP	DE		;RECOVER ALTERNATE DE
	POP	HL		;RECOVER ALTERNATE HL
	EX	AF,AF'		;SWAP TO MAIN AF REGISTER
	EXX			;SWAP TO MAIN REGISTERS
	POP	IX		;RECOVER IX REGISTER
	POP	IY		;RECOVER IY REGISTER
	POP	HL		;RECOVER SP REGISTER
	LD	SP,HL		;COPY HL TO STACK POINTER
	LD	HL,(BUGREG+PCR)	;GET PROGRAM COUNTER TO HL
	PUSH	HL		;RESTORE EXECUTION ADDRESS
	LD	HL,(BUGREG+HLM)	;RESTORE HL REGISTER
	RET
