; TEST FOR REGISTER NAME MATCH AND MODIFY CONTENTS IF FOUND
; ENTRY:  B       - INDEX INTO REGISTER NAME
;         D       - SECOND REGISTER NAME CHARACTER
;         E       - THIRD REGISTER NAME CHARACTER
;         HL      - POINTER TO REGISTER NAME
;5038
MODRTN:	INC	HL		;BUMP TO NEXT CHARACTER
	LD	A,(HL)		;GET REGISTER NAME CHARACTER
	CP	D		;TEST IF REGISTER NAME MATCH
	JR	NZ,MODRNE	;BUMP TO NEXT IF MISMATCH
	INC	HL		;BUMP TO NEXT CHARACTER
	LD	A,(HL)		;GET REGISTER NAME CHARACTER
	CP	E		;TEST IF REGISTER NAME MATCH
	JR	NZ,MODRNI	;BUMP TO NEXT IF MISMATCH
	LD	A,NUMREG*2	;GET REGISTER COUNT * WORD
	SUB	B		;SUBTRACT CURRENT COUNT
	SUB	B		;SUBTRACT CURRENT COUNT AGAIN
	LD	C,A		;COPY RESULT TO C
	LD	B,0		;REMAINING COUNT IS IN BC
	LD	HL,BUGREG	;POINT AT CONTEXT SAVE AREA
	ADD	HL,BC		;INDEX TO REGISTER WORD
	PUSH	HL		;SAVE REGISTER WORD INDEX
	LD	A,EE		;ERASE TO LINE END CHARACTER
	CALL	VDCHAR		;DISPLAY THE CHARACTER
	POP	DE		;GET REGISTER WORD INDEX
	CALL	HEXADR		;GET ADDRESS FROM KEYBOARD
	RET	Z		;DONE IF NO ADDRESS ENTERED
	EX	DE,HL		;SWAP ADDRESS AND DATA
	LD	(HL),E		;STORE REGISTER CONTENTS LSB
	INC	HL		;BUMP TO MSB
	LD	(HL),D		;STORE REGISTER CONTENTS MSB
	RET
