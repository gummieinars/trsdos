	LD	A,' '		;ELSE LOAD A SPACE CHARACTER
DIRCII:	CALL	VDCHAR		;DISPLAY THE CHARACTER
	PUSH	HL		;SAVE BUFFER POINTER
	LD	A,L		;GET BUFFER POINTER LSB TO A
	ADD	A,16		;INDEX TO ACCESS PASSWORD
	LD	L,A		;UPDATE BUFFER POINTER LSB
	LD	E,(HL)		;GET ACCESS PASSWORD LSB TO E
	INC	L		;BUMP BUFFER POINTER
	LD	D,(HL)		;GET ACCESS PASSWORD MSB TO D
	PUSH	HL		;SAVE BUFFER POINTER
