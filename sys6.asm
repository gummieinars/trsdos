;
; 'PROT' COMMAND PROCESSING
; FORMAT:  PROT :D ([LOCK][UNLOCK][PW=PW])
;536A
PROCMD:	LD	A,(SYSCON)	;GET SYSTEM CONDITION FLAGS
	BIT	5,A		;TEST IF CHAINING IN PROGRESS
	JP	NZ,INVPCH	;THEN INVALID DURING CHAINING
	LD	BC,0		;ZERO BC REGISTER
	LD	(PASSWP),BC	;CLEAR PASSWORD POINTER
	LD	(LOCKFL),BC	;CLEAR LOCK FLAG
	LD	(UNLOFL),BC	;CLEAR UNLOCK FLAG
	LD	C,0		;DEFAULT TO UNIT NUMBER ZERO
	LD	A,(HL)		;GET COMMAND LINE CHARACTER
	CP	':'		;TEST IF DRIVE CODE DELIMITER
	JR	NZ,PROCND	;USE DEFAULT IF NO DRIVE
	INC	HL		;BUMP COMMAND LINE POINTER
	LD	A,(HL)		;GET ASCII DRIVE NUMBER
	SUB	'0'		;REMOVE ASCII BIAS
	LD	C,A		;COPY DRIVE NUMBER TO C
	INC	HL		;BUMP COMMAND LINE POINTER
PROCND:	LD	A,C		;GET UNIT NUMBER TO A
	LD	(UNITNO),A	;SAVE THE DRIVE CODE
	LD	DE,PROPAR	;POINT AT PARAMETER STRINGS
	CALL	PARSEC		;PARSE THE COMMAND LINE
	LD	A,(PASSWP)	;GET PASSWORD POINTER LSB
	LD	HL,LOCKFL	;POINT AT LOCK FLAG
	OR	(HL)		;MERGE WITH LOCK FLAG
	LD	HL,UNLOFL	;POINT AT UNLOCK FLAG
	OR	(HL)		;MERGE WITH UNLOCK FLAG
	JP	Z,NODONE	;EXIT IF NO PARAMETERS
	LD	A,CC		;LOAD STRING TERMINATOR
	LD	DE,DCBONE	;POINT AT DEVICE CONTROL BLOCK
	LD	(DE),A		;STORE AS A FILENAME
	CALL	OPNFIL		;FAKE OPEN TO LOAD 'SYS2/SYS'
	LD	HL,CURMAP	;POINT AT PASSWORD PROMPT
	CALL	DOPMSG		;DISPLAY PROMPT STRING
	CALL	GETPAS		;GET CURRENT MASTER PASSWORD
	LD	(MASHAS),HL	;SAVE PASSWORD HASH CODE
	LD	C,0		;GET UNIT NUMBER TO C
UNITNO	Equ	$ - 1		;DRIVE NUMBER STORAGE
	CALL	REDGAT		;READ 'GAT' SECTOR
	JP	NZ,SYSABO	;ABORT TO SYSTEM IF ANY ERRORS
	LD	HL,(GATBUF+DPA)	;GET PASSWORD HASH FROM 'GAT'
	LD	DE,(MASHAS)	;GET MASTER PASSWORD HASH
	XOR	A		;CLEAR THE CARRY FLAG
	SBC	HL,DE		;TEST FOR A PASSWORD MATCH
	JR	Z,PROCHM	;CONTINUE IF MATCHING HASH
	LD	HL,INVMAP	;POINT AT ERROR MESSAGE
	CALL	DOPMSG		;DISPLAY THE MESSAGE
	JP	ERRENT		;THEN ABORT TO DOS ERROR ENTRY
PROCHM:	LD	DE,0		;GET PASSWORD STRING POINTER
PASSWP	Equ	$ - 2		;POINTER TO PASSWORD STRING
	LD	A,D		;GET POINTER MSB TO A
	OR	E		;TEST IF PASSWORD ENTERED
	JR	Z,PROCNP	;SKIP IF NO PASSWORD
	LD	HL,NEWMAP	;POINT AT PASSWORD PROMPT
	CALL	DOPMSG		;DISPLAY PROMPT STRING
	CALL	GETPAS		;GET NEW MASTER PASSWORD
	LD	(GATBUF+DPA),HL	;SAVE PASSWORD HASH IN BUFFER
	LD	A,(UNITNO)	;GET DISK DRIVE CODE TO A
	LD	C,A		;COPY UNIT NUMBER TO C
	CALL	WRTGAT		;WRITE 'GAT' SECTOR TO DISK
	JP	NZ,SYSABO	;ABORT TO SYSTEM IF ANY ERRORS
PROCNP:	LD	HL,(GATBUF+DPA)	;GET DISK PASSWORD TO HL
	LD	DE,0		;GET SUPPLIED LOCK FLAG
LOCKFL	Equ	$ - 2		;STORAGE FOR LOCK FLAG
	LD	A,D		;GET LOCK FLAG MSB TO A
	OR	E		;TEST IF LOCK A FILE
	JR	NZ,PROCCL	;CONTINUE LOCKING FILE
	LD	HL,PASSWO	;LOAD DEFAULT PASSWORD HASH
	LD	DE,0		;GET SUPPLIED UNLOCK FLAG
UNLOFL	Equ	$ - 2		;STORAGE FOR UNLOCK FLAG
	LD	A,D		;GET UNLOCK FLAG MSB TO A
	OR	E		;TEST IF UNLOCK FILE
	JR	NZ,PROCCL	;GO IF UNLOCKING FILE
	JP	DOSENT		;ELSE EXIT TO DOS PROMPT
PROCCL:	LD	(DSKHAS),HL	;STORE DEFAULT HASH
	LD	A,(UNITNO)	;GET UNIT NUMBER TO A
	LD	C,A		;COPY UNIT CODE TO C
	CALL	TRKDIR		;GET DIRECTORY TRACK NUMBER
	LD	E,2		;LOAD FIRST FILE SECTOR NUMBER
PROCNS:	LD	HL,DIRBUF	;POINT AT DIRECTORY BUFFER
	CALL	DDREAD		;READ SECTOR TO BUFFER
	JP	NZ,SYSABO	;ABORT TO SYSTEM IF ANY ERRORS
	LD	L,64		;FORM THIRD FILE ENTRY ADDRESS
PROCNE:	LD	A,(HL)		;GET FILE ACCESS BITS TO A
	AND	11111000B	;MASK OFF PERMISSION BITS
	CP	00010000B	;TEST IF ENTRY ASSIGNED
	JR	NZ,PROCUA	;SKIP IF ENTRY UNASSIGNED
	LD	A,L		;GET SECTOR INDEX LSB TO A
	ADD	A,16		;INDEX TO UPDATE PASSWORD
	LD	L,A		;FORM ADDRESS OF PASSWORDS
	PUSH	DE		;SAVE SECTOR NUMBER
	LD	DE,0		;GET PASSWORD ENCODE TO DE
DSKHAS	Equ	$ - 2		;STORAGE FOR PASSWORD ENCODE
	LD	(HL),E		;STORE UPDATE PASSWORD LSB
	INC	L		;BUMP PASSWORD POINTER
	LD	(HL),D		;STORE UPDATE PASSWORD MSB
	INC	L		;BUMP PASSWORD POINTER
	LD	(HL),E		;STORE ACCESS PASSWORD LSB
	INC	L		;BUMP PASSWORD POINTER
	LD	(HL),D		;STORE ACCESS PASSWORD MSB
	POP	DE		;RECOVER SECTOR NUMBER
PROCUA:	LD	A,L		;GET BUFFER ADDRESS LSB
	AND	11100000B	;MASK OFF BUFFER INDEX
	ADD	A,32		;INDEX TO NEXT ENTRY
	LD	L,A		;UPDATE BUFFER ADDRESS LSB
	JR	NC,PROCNE	;LOOP IF SECTOR NOT DONE
	LD	HL,DIRBUF	;POINT AT DIRECTORY BUFFER
	CALL	WRDSEC		;WRITE DIRECTORY SECTOR
	JP	NZ,SYSABO	;ABORT TO SYSTEM IF ANY ERRORS
	INC	E		;BUMP DIRECTORY SECTOR NUMBER
	LD	A,E		;GET SECTOR NUMBER TO A
	CP	NUMSEC		;TEST IF LAST SECTOR DONE
	JR	C,PROCNS	;LOOP FOR NEXT SECTOR IF NOT
	JP	DOSENT		;ELSE EXIT TO DOS PROMPT
