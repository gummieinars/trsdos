;
; CONVERT DATE OR TIME STRING TO BINARY CODED DECIMAL
; ENTRY:  C       - DATE OR TIME SEPERATOR
;         HL      - POINTER TO TIME OR DATE STRING
; EXIT:   DE      - POINTER TO START OF STORAGE AREA
;         HL      - POINTER TO END OF STRING
;52EA
CONVDT:	LD	DE,TIDREG+2	;POINT AT LOCAL REGISTERS
	LD	B,3		;LOAD REGISTER COUNT
CONVDL:	PUSH	DE		;SAVE REGISTER POINTER
	CALL	CNVBCD		;CONVERT TO BCD
	POP	DE		;RECOVER REGISTER POINTER
	RET	NZ		;RETURN IF ANY ERRORS
	LD	(DE),A		;ELSE STORE BYTE IN REGISTER
	DEC	DE		;BACKUP REGISTER POINTER
	DEC	B		;DECREMENT REGISTER COUNT
	RET	Z		;RETURN IF ALL DONE
	LD	A,(HL)		;GET DELIMITER TO A
	INC	HL		;BUMP STRING POINTER
	CP	C		;TEST IF VALID SEPERATOR
	JR	Z,CONVDL	;LOOP FOR NEXT IF SO
	RET
;
;
; GET BINARY CODED DECIMAL BYTE FROM ASCII STRING
; ENTRY:  HL      - POINTER TO ASCII STRING
; EXIT:   A       - BINARY CODED DECIMAL BYTE
;         HL      - INCREMENTED TWICE
;         ZF      - SET IF VALID BINARY CODED DECIMAL
;52FF
CNVBCD:	CALL	CNVBCN		;GET MS BCD DIGIT
	JR	NC,CNVBCE	;ABORT IF ANY ERROR
	LD	E,A		;SAVE BCD NIBBLE IN E
	RLCA			;MULTIPLY BY TWO
	RLCA			;MULTIPLY BY FOUR
	ADD	A,E		;MULTIPLY BY FIVE
	RLCA			;MULTIPLY BY TEN
	LD	E,A		;SAVE RESULT IN E
	CALL	CNVBCN		;GET LS BCD DIGIT
	JR	NC,CNVBCE	;ABORT IF ANY ERROR
	ADD	A,E		;MERGE BOTH NIBBLES
	LD	E,A		;SAVE BCD BYTE IN E
	XOR	A		;SET ZERO FLAG
	LD	A,E		;COPY RESULT TO A
	RET
;
;
; ERROR ENCOUNTERED, SO CLEAR THE ZERO FLAG
;5314
CNVBCE:	OR	A		;CLEAR ZERO FLAG
	RET
;
;
; GET ASCII DATE OR TIME CHARACTER AND CONVERT TO BCD NIBBLE
; ENTRY:  HL      - POINTER TO ASCII STRING
; EXIT:   A       - BINARY CODED DECIMAL NIBBLE
;         HL      - INCREMENTED
;         CF      - RESET IF NOT BINARY CODED DECIMAL
;5316
CNVBCN:	LD	A,(HL)		;GET CHARACTER FROM STRING
	INC	HL		;BUMP STRING POINTER
	SUB	'0'		;REMOVE ASCII BIAS
	CP	10		;TEST IF VALID BCD
	RET
