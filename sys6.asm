;
; INPUT NEW MASTER PASSWORD INTO BUFFER - PAD WITH SPACES
; THEN COMPUTE SIXTEEN BIT HASH CODE FROM THE CHARACTERS
; EXIT:   HL      - PASSWORD HASH CODE
